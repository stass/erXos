# frozen_string_literal: true

require_relative 'error'
require_relative 'oracle'

module Erx
  # The modules /tmp's serving processes can call (docs/design-tmp.md, T6): the tree
  # process, the grant and the file owners must never ask the code server for code, since
  # the code server may itself be /tmp's client, waiting on them. xref lists every module
  # reachable by calls from erx_ramfs, erx_ramfs_core and erx_fs, function by function,
  # over the beams a build holds; erx_ramfs_sup loads that list, the generated module
  # erx_ramfs_serving, before it mounts /tmp. Preloaded modules are always loaded and are
  # left out. The runtime build calls check, which fails when the checked-in list lacks a
  # module the beams reach or holds one they do not; tools/gen_ramfs_serving.rb writes it.
  module ServingSet
    SEEDS = %w[erx_ramfs erx_ramfs_core erx_fs].freeze
    GENERATED = 'erlang/apps/erx_files/src/erx_ramfs_serving.erl'
    PRELOAD_MAKEFILE = 'otp/erts/preloaded/src/Makefile'
    # xref's name for a call of a fun value, which names no module.
    FUN_CALL = '$M_EXPR'
    DEADLINE = 300

    # The beams xref reads in an OTP copy: erXos's applications, kernel and stdlib.
    def self.directories(otp:) = %w[erx_files erx kernel stdlib].map { |application| File.join(otp, 'lib', application, 'ebin') }

    # The module names the seeds reach in the beams of directories, sorted, without
    # the preloaded ones. Calls to BIFs count: a BIF's module, such as binary or os, is
    # loaded through the code server like any other. runner runs erl as every build step
    # runs, under a deadline with its output in a log, and the module list is read back
    # from that log.
    def self.closure(runner:, erl:, directories:, root:)
      query = "(Mod) range (closure E | [#{SEEDS.join(',')}] : Mod)"
      expression = <<~ERLANG
        {ok, X} = xref:start(serving, [{xref_mode, functions}]),
        ok = xref:set_default(X, [{warnings, false}, {builtins, true}, {verbose, false}]),
        [{ok, _} = xref:add_directory(X, D) || D <- #{erlang_strings(directories)}],
        {ok, Modules} = xref:q(X, "#{query}"),
        [io:format("module ~ts~n", [M]) || M <- Modules],
        halt().
      ERLANG
      record = runner.run([erl, '-noshell', '-eval', expression], name: 'serving-set', deadline: DEADLINE, chdir: root,
                                                                  env: Oracle::CLEAN_ERLANG_ENV)
      # The log holds erl's stderr too, which need not be UTF-8.
      reached = File.binread(record.fetch('log')).scrub.lines.filter_map { |line| line[/\Amodule (\S+)\n\z/, 1] }
      (reached - [FUN_CALL] - preloaded(root: root)).sort
    end

    # The modules the preloaded Makefile lists.
    def self.preloaded(root:)
      text = File.read(File.join(root, PRELOAD_MAKEFILE))
      %w[PRE_LOADED_ERL_MODULES PRE_LOADED_BEAM_MODULES].flat_map do |list|
        text[/^#{list} = \\\n((?:.*\\\n)*.*\n)/, 1].split.reject { |word| word == '\\' }
      end
    end

    # The module list erx_ramfs_serving holds.
    def self.listed(text) = text[/^modules\(\) ->\n\s*\[([^\]]*)\]\./m, 1].to_s.split(',').map(&:strip)

    def self.render(modules)
      lines = modules.each_slice(6).map { |slice| slice.join(', ') }.join(",\n     ")
      <<~ERLANG
        %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
        %% SPDX-License-Identifier: BSD-2-Clause
        %% Generated by tools/gen_ramfs_serving.rb with xref over the release's beams.
        %% Do not edit this file.

        %% The modules /tmp's tree process, grant and file owners can call, preloaded ones
        %% left out (docs/design-tmp.md, T6). erx_ramfs_sup loads them before it mounts /tmp.
        -module(erx_ramfs_serving).
        -moduledoc false.

        -export([modules/0]).

        -spec modules() -> [module()].
        modules() ->
            [#{lines}].
      ERLANG
    end

    # Fails unless the checked-in list is exactly what the beams reach.
    def self.check(runner:, erl:, directories:, root:)
      want = closure(runner: runner, erl: erl, directories: directories, root: root)
      have = listed(File.read(File.join(root, GENERATED)))
      return if have == want

      raise Error, "#{GENERATED} is stale: missing #{(want - have).join(' ')}; extra #{(have - want).join(' ')}; " \
                   'run tools/gen_ramfs_serving.rb'
    end

    def self.erlang_strings(paths) = "[#{paths.map { |path| "\"#{path}\"" }.join(', ')}]"
  end
end
