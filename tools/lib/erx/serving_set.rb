# frozen_string_literal: true

require 'fileutils'
require_relative 'error'
require_relative 'oracle'

module Erx
  # The modules /tmp's grant can call (docs/design-tmp.md, T6): the grant, which holds
  # the tree and runs its callbacks, must never ask the code server for code, since the
  # code server may itself be /tmp's client, waiting on it. xref lists every module
  # reachable by calls from erx_ramfs, erx_ramfs_core and erx_fs, function by function,
  # over the beams a build holds; erx_ramfs_sup loads that list, the module
  # erx_ramfs_serving, before it mounts /tmp. Preloaded modules are always loaded and
  # are left out. The list is a fact about beams, so no checked-in source holds it: the
  # runtime build calls build, which writes the module's source (see source) and
  # compiles it into erx_files beside the application's own modules.
  module ServingSet
    SEEDS = %w[erx_ramfs erx_ramfs_core erx_fs].freeze
    # The application the module belongs to, and the module.
    APPLICATION = 'erx_files'
    MODULE = 'erx_ramfs_serving'

    PRELOAD_MAKEFILE = 'otp/erts/preloaded/src/Makefile'
    # xref's name for a call of a fun value, which names no module.
    FUN_CALL = '$M_EXPR'
    DEADLINE = 300

    # The module's source for the OTP copy otp: in a directory beside the copy, which one
    # runtime build owns, so each build writes its own and a receipt names the source of its
    # own beam. Not inside the copy, whose ORIGIN.md makes pack provenance treat everything
    # under it as imported source; outside it the source is attributed as generated.
    def self.source(otp:) = File.join(File.dirname(otp), 'serving', "#{MODULE}.erl")

    # The beams xref reads in an OTP copy: erXos's applications, kernel and stdlib.
    def self.directories(otp:) = %w[erx_files erx kernel stdlib].map { |application| File.join(otp, 'lib', application, 'ebin') }

    # The module names the seeds reach in the beams of directories, sorted, without
    # the preloaded ones. Calls to BIFs count: a BIF's module, such as binary or os, is
    # loaded through the code server like any other. runner runs erl as every build step
    # runs, under a deadline with its output in a log, and the module list is read back
    # from that log.
    def self.closure(runner:, erl:, directories:, root:)
      query = "(Mod) range (closure E | [#{SEEDS.join(',')}] : Mod)"
      expression = <<~ERLANG
        {ok, X} = xref:start(serving, [{xref_mode, functions}]),
        ok = xref:set_default(X, [{warnings, false}, {builtins, true}, {verbose, false}]),
        [{ok, _} = xref:add_directory(X, D) || D <- #{erlang_strings(directories)}],
        {ok, Modules} = xref:q(X, "#{query}"),
        [io:format("module ~ts~n", [M]) || M <- Modules],
        halt().
      ERLANG
      record = runner.run([erl, '-noshell', '-eval', expression], name: 'serving-set', deadline: DEADLINE, chdir: root,
                                                                  env: Oracle::CLEAN_ERLANG_ENV)
      # The log holds erl's stderr too, which need not be UTF-8.
      reached = File.binread(record.fetch('log')).scrub.lines.filter_map { |line| line[/\Amodule (\S+)\n\z/, 1] }
      (reached - [FUN_CALL] - preloaded(root: root)).sort
    end

    # The modules the preloaded Makefile lists.
    def self.preloaded(root:)
      text = File.read(File.join(root, PRELOAD_MAKEFILE))
      %w[PRE_LOADED_ERL_MODULES PRE_LOADED_BEAM_MODULES].flat_map do |list|
        text[/^#{list} = \\\n((?:.*\\\n)*.*\n)/, 1].split.reject { |word| word == '\\' }
      end
    end

    def self.render(modules)
      lines = modules.each_slice(6).map { |slice| slice.join(', ') }.join(",\n     ")
      <<~ERLANG
        %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
        %% SPDX-License-Identifier: BSD-2-Clause
        %% Generated by the runtime build (Erx::ServingSet) with xref over the release's beams.

        %% The modules /tmp's grant can call, preloaded ones
        %% left out (docs/design-tmp.md, T6). erx_ramfs_sup loads them before it mounts /tmp.
        -module(erx_ramfs_serving).
        -moduledoc false.

        -export([modules/0]).

        -spec modules() -> [module()].
        modules() ->
            [#{lines}].
      ERLANG
    end

    # Writes the module's source (see source) and compiles it into the ebin of
    # erx_files, built already, from what the beams of otp reach; answers the module's
    # name, which the application file lists. erlc is the erlc the applications build with.
    def self.build(runner:, erlc:, flags:, otp:, root:)
      modules = closure(runner: runner, erl: File.join(File.dirname(erlc), 'erl'), directories: directories(otp: otp), root: root)
      source = source(otp: otp)
      FileUtils.mkdir_p(File.dirname(source))
      File.write(source, render(modules))
      runner.run([erlc, *flags, '-o', File.join(otp, 'lib', APPLICATION, 'ebin'), source], name: "erlang-app-#{MODULE}",
                                                                                         deadline: DEADLINE, chdir: root,
                                                                                         env: Oracle::CLEAN_ERLANG_ENV)
      MODULE
    end

    def self.erlang_strings(paths) = "[#{paths.map { |path| "\"#{path}\"" }.join(', ')}]"
  end
end
