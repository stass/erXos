require 'digest'
require_relative 'bounded_file'
require_relative 'error'
require_relative 'generation_plan'
require_relative 'sysreg'

module Erx
  # The C accessors of the system registers hw/sysreg/aarch64.json describes
  # (docs/design-kernel.md, "Hardware register sources"). Two headers come out
  # of the one file:
  # * erx/arch/aarch64/sysreg_fields.h, for each named field F of register R,
  #   erx_sysreg_R_F_get(word), which takes the field out of a value of R. It
  #   holds no instruction, so host-built cores read register values with it.
  # * erx/arch/aarch64/sysreg.h, which includes the fields and gives, for each
  #   register whose policy says read, erx_sysreg_R_read(void): the register's
  #   read instruction, after an instruction barrier when the policy names one.
  # A register whose policy says write has no generated write yet, and the
  # generator refuses it rather than leave the policy unmet.
  module SysregHeaders
    FIELDS = 'include/erx/arch/aarch64/sysreg_fields.h'
    READS = 'include/erx/arch/aarch64/sysreg.h'
    NOTICE = ['/* Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>', ' * SPDX-License-Identifier: BSD-2-Clause',
              ' * Generated by tools/lib/erx/sysreg_headers.rb from hw/sysreg/aarch64.json. Do not edit.', ' */'].freeze

    module_function

    # The plan Erx::Generated publishes: both headers, from the checked-in file alone.
    def generation(root:)
      bytes = BoundedFile.read(File.join(File.expand_path(root), Sysreg::SPECIFICATION),
                               maximum: Sysreg::MAX_SPECIFICATION_BYTES)
      GenerationPlan.new(files: render(Sysreg.specification(bytes)),
                         reads: { Sysreg::SPECIFICATION => Digest::SHA256.hexdigest(bytes) })
    rescue SystemCallError => error
      raise Error, "cannot read #{Sysreg::SPECIFICATION}: #{error.message}"
    end

    def render(specification)
      registers = specification.fetch('registers')
      # Sysreg.specification refuses a write policy today; this keeps the generator from
      # silently leaving one unmet if that reader ever admits it.
      writable = registers.find { |register| register.fetch('write') }
      raise Error, "system register #{writable.fetch('name')}: no write accessor is generated" if writable

      files = { FIELDS => fields_header(registers), READS => reads_header(registers) }
      raise Error, 'generated system-register output is not ASCII' unless files.values.all?(&:ascii_only?)

      files.transform_values(&:freeze).freeze
    end

    def fields_header(registers)
      body = registers.flat_map do |register|
        register.fetch('fields').select { |field| field.key?('name') }.flat_map do |field|
          mask = field.fetch('width') == 64 ? 'UINT64_MAX' : "UINT64_C(0x#{((1 << field.fetch('width')) - 1).to_s(16)})"
          ['static inline uint64_t',
           "erx_sysreg_#{register.fetch('name').downcase}_#{field.fetch('name').downcase}_get(uint64_t word)",
           '{', "\treturn ((word >> #{field.fetch('offset')}) & #{mask});", '}', '']
        end
      end
      header('ERX_ARCH_AARCH64_SYSREG_FIELDS_H', ['#include <stdint.h>'], body)
    end

    def reads_header(registers)
      body = registers.select { |register| register.fetch('read') }.flat_map do |register|
        encoding = register.fetch('encoding')
        operand = "S#{encoding.fetch('op0')}_#{encoding.fetch('op1')}_C#{encoding.fetch('CRn')}_" \
                  "C#{encoding.fetch('CRm')}_#{encoding.fetch('op2')}"
        barrier = register.fetch('read_barrier') == 'isb' ? ["\t__asm__ volatile(\"isb\" ::: \"memory\");"] : []
        ['static inline uint64_t', "erx_sysreg_#{register.fetch('name').downcase}_read(void)", '{',
         "\tuint64_t value;", '', *barrier,
         "\t__asm__ volatile(\"mrs %0, #{operand}\" : \"=r\"(value));", "\treturn (value);", '}', '']
      end
      header('ERX_ARCH_AARCH64_SYSREG_H', ['#include <stdint.h>', '', '#include "erx/arch/aarch64/sysreg_fields.h"'], body)
    end

    def header(guard, includes, body)
      [*NOTICE, '', "#ifndef #{guard}", "#define #{guard}", '', *includes, '', *body, "#endif /* #{guard} */", ''].join("\n")
    end
    private_class_method :fields_header, :reads_header, :header
  end
end
