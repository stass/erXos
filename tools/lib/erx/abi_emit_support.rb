require_relative 'abi_emit_c'
require_relative 'abi_emit_reader'

module Erx
  module ABI
    # Reference tables and fuzz participants come from the same validated graph
    # as the readers. Adding a wire layout cannot omit it from the C fuzz entry.
    module SupportEmitter
      module_function

      # Each enum with args lines: its members and their typed arguments.
      def event_reference(schema)
        schema.event_enums.flat_map do |type|
          rows = type.members.sort_by { |_member, value| value }.map do |member, value|
            arguments = type.args.fetch(member, []).map { |argument| "`#{argument.name}:#{argument.type}`" }
            "| `#{member}` | #{value} | #{arguments.empty? ? '-' : arguments.join(', ')} |"
          end
          ['', "## Events of `#{type.name}`", '', '| Event | Value | Arguments |', '| --- | ---: | --- |', *rows]
        end
      end

      def reference(schema)
        out = ['<!-- Generated by tools/gen_abi.rb; do not edit. -->',
               '<!-- Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com> -->',
               '<!-- SPDX-License-Identifier: BSD-2-Clause -->', '',
               '# ABI reference', '', "ABI version: #{schema.version}.", '',
               'Prefix decoders copy fixed fields after checking input length. They do not',
               'admit an image, configuration, capability or call. Whole-file readers validate',
               'their declared structural constraints; policy admission is a separate contract.', '',
               '## Constants', '', '| Name | Value |', '| --- | ---: |']
        schema.constants.each_value do |constant|
          out << "| `#{Names.macro(constant.name)}` | #{constant.value} |"
        end
        out.concat(event_reference(schema))
        out.concat(['', '## Layouts', ''])
        schema.type_order.each do |name|
          type = schema.types.fetch(name)
          next unless type.is_a?(Layout)
          out.concat(["### `#{CEmitter.c_type(type)}`", '',
                      "Storage: `#{type.storage}`. Prefix size: #{type.size}. Alignment: #{type.alignment}.", '',
                      *(type.private? ? ["Private to `#{type.private_owner}`: defined only in `#{type.private_header}`.", ''] : []),
                      '| Field | Type | Offset | Count |', '| --- | --- | ---: | ---: |'])
          type.fields.each do |field|
            out << "| `#{field.name}` | `#{field.type.name}` | #{field.offset} | #{field.count || 1} |"
          end
          if type.tail
            out << "| `#{type.tail.name}` | `#{type.tail.type.name}` | #{type.size} | `#{type.tail.count_field}` (maximum #{type.tail.maximum}) |"
          end
          out << ''
        end
        out.concat(['## Calls', '', '| Name | Number | Waits | Executor | Retry | Effects |',
                    '| --- | ---: | --- | --- | --- | --- |'])
        schema.calls.each do |name, call|
          executor = call.fetch(:executor).values_at(:rule, :argument).compact.join(' ')
          out << "| `#{name}` | #{call.fetch(:number)} | #{call.fetch(:properties).fetch('waits')} | " \
                 "#{executor} | #{call.fetch(:retry) ? 'lookup' : 'no'} | #{call.fetch(:properties).fetch('effects')} |"
        end
        (out + ['']).join("\n")
      end

      def fuzz(schema)
        out = [CEmitter::NOTICE, '#include "erx/abi_reader.h"']
        out << '#include "kernel/generated/abi_calls.h"' unless schema.calls.empty?
        out.concat(['', 'int LLVMFuzzerTestOneInput(const uint8_t *, size_t);', '',
                    'int', 'LLVMFuzzerTestOneInput(const uint8_t *bytes, size_t length)', '{'])
        schema.type_order.each do |name|
          type = schema.types.fetch(name)
          next unless type.is_a?(Layout) && type.storage == 'wire_le'
          out.concat(["\t{", "\t\t#{CEmitter.c_type(type)} value;",
                      "\t\t(void)#{Names.c(name)}_decode(bytes, length, &value);", "\t}"])
        end
        schema.readers.each do |reader|
          prefix = Names.c(reader.name)
          out.concat(["\t{", "\t\t#{prefix}_view_t view;", "\t\terx_abi_error_t error;", '',
                      "\t\tif (#{prefix}_open(bytes, length, &view, &error)) {"])
          reader.tables.each do |name, table|
            count = CReaderEmitter.field_expression(table.fetch(:count_path), prefix: 'view.header.')
            out.concat(["\t\t\t{", "\t\t\t\t#{CEmitter.c_type(table.fetch(:type))} row;",
                        "\t\t\t\tfor (size_t index = 0; index <= #{count}; index++)",
                        "\t\t\t\t\t(void)#{prefix}_#{name}_at(&view, index, &row);", "\t\t\t}"])
          end
          out.concat(["\t\t}", "\t}"])
        end
        unless schema.calls.empty?
          count = schema.architecture.fetch(:registers).fetch('args').size
          utcb = schema.types[Contracts::UTCB_LAYOUT]
          raise SchemaError, "call fuzzing requires the #{Contracts::UTCB_LAYOUT} layout" unless utcb.is_a?(Layout)
          words = utcb.fields.find { |field| field.name == Contracts::UTCB_WORDS_FIELD }.count
          out.concat(["\t{", "\t\tuint64_t registers[#{count}] = {0};",
                      "\t\terx_utcb_t utcb = {0};",
                      "\t\terx_sys_shape_t shape;", "\t\tuint64_t number = 0;", '',
                      "\t\tfor (size_t index = 0; index < length && index < sizeof(registers); index++)",
                      "\t\t\tregisters[index / sizeof(uint64_t)] |= (uint64_t)bytes[index] << ((index % sizeof(uint64_t)) * 8);",
                      "\t\tfor (size_t index = 0; index < length && index < sizeof(number); index++)",
                      "\t\t\tnumber |= (uint64_t)bytes[index] << (index * 8);",
                      "\t\t/* The UTCB's message words take the bytes after the registers. */",
                      "\t\tfor (size_t word = 0; word < #{words}; word++) {",
                      "\t\t\tuint64_t value = 0;", '',
                      "\t\t\tfor (size_t byte = 0; byte < sizeof(value); byte++) {",
                      "\t\t\t\tsize_t at = sizeof(registers) + word * sizeof(value) + byte;", '',
                      "\t\t\t\tif (at < length)",
                      "\t\t\t\t\tvalue |= (uint64_t)bytes[at] << (byte * 8);",
                      "\t\t\t}",
                      "\t\t\t(void)erx_utcb_mr_store(&utcb, word, value);",
                      "\t\t}",
                      "\t\t(void)erx_sys_decode_shape(number, registers, &utcb, false, &shape);"])
          schema.calls.each_key do |name|
            out << "\t\t(void)erx_sys_decode_shape(ERX_CALL_#{name.upcase}, registers, &utcb, false, &shape);"
            out << "\t\t(void)erx_sys_decode_shape(ERX_CALL_#{name.upcase}, registers, &utcb, true, &shape);"
          end
          out << "\t}"
        end
        (out + ["\treturn (0);", '}', '']).join("\n")
      end
    end
  end
end
