# frozen_string_literal: true

require_relative 'abi_ui'
require_relative 'abi_emit_inspection'

module Erx
  module ABI
    # Emits erx_ui_schema from the `ui` declaration: the widget format's
    # tables and validate/2, the validator of whole widget trees
    # (docs/design-display.md, "Widget trees"). The tables are clauses, one
    # per kind and per property; the walk and the helpers are fixed text.
    module UIEmitter
      ERLANG_PATH = 'erlang/apps/erx/src/generated/erx_ui_schema.erl'
      WIDTH = 80

      module_function

      def outputs(schema)
        return {} unless schema.ui

        { ERLANG_PATH => erlang(schema.ui, stopgaps: schema.inspection.stopgaps.keys) }.freeze
      end

      # STOPGAPS are the inspection schema's stopgap reporters, the names an
      # attr() may carry.
      def erlang(ui, stopgaps:)
        forms = ui.properties.flat_map { |property| [property.type.form, property.type.element&.form] }.compact.uniq
        [head(ui), tables(ui), walk, plain_clauses(ui), status_functions(ui, stopgaps),
         relation_clauses(ui), helpers(forms)].join("\n").gsub(/\n{3,}/, "\n\n")
      end

      def head(ui)
        <<~ERLANG
          %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
          %% SPDX-License-Identifier: BSD-2-Clause
          %% Generated by tools/gen_abi.rb from abi/formats/ui.txt.
          %% Do not edit this file.

          -module(erx_ui_schema).
          -moduledoc "The widget format's tables and validate/2, the validator of whole widget trees.".
          -export([version/0, validate/2, kinds/0, kind/1, properties/0, property/1, images/0]).
          -export_type([tree/0, reason/0, where/0]).

          %% A renderer lays a tree out recursively on a fixed stack, so no tree is
          %% deeper; ui_children bounds the children of one node.
          -define(MAX_DEPTH, 64).
          -define(MAX_CHILDREN, #{ui.children_max}).

          -type tree() :: {Kind :: atom(), Props :: \#{atom() => term()}, Children :: [tree()]}.
          -type reason() :: not_a_node | unknown_kind | unknown_property | bad_value | children
                          | duplicate_key | too_many_nodes | too_deep.
          %% The child indexes from the root to the node, with the property's name
          %% beside them for unknown_property and bad_value: the client's own map
          %% key, which a printer shows through its line escape.
          -type path() :: [non_neg_integer()].
          -type where() :: path() | {path(), Property :: term()}.

          -spec version() -> pos_integer().
          version() -> #{ui.version}.
        ERLANG
      end

      def tables(ui)
        kinds = ui.kinds.map { |kind| kind_clause(kind) }
        properties = ui.properties.map { |property| property_clause(property) }
        images = ui.images.map { |image| "{#{atom(image.name)}, #{image.number}, #{binary(image.content_type)}}" }
        <<~ERLANG
          -spec kinds() -> [atom()].
          kinds() ->
          #{wrap(ui.kinds.map { |kind| atom(kind.name) }, '    [', ']')}.

          %% A kind's number, whether it takes children, every property it takes,
          %% its state property and its fixed properties.
          -spec kind(atom()) -> map() | error.
          #{kinds.join}kind(_Kind) -> error.

          -spec properties() -> [atom()].
          properties() ->
          #{wrap(ui.properties.map { |property| atom(property.name) }, '    [', ']')}.

          %% A property's number and type, whether every kind takes it, whether it
          %% carries a status, its event detail, and the value its absence means.
          -spec property(atom()) -> map() | error.
          #{properties.join}property(_Property) -> error.

          %% Each image type's atom, number and media type.
          -spec images() -> [{atom(), 1..255, binary()}].
          images() ->
          #{wrap(images, '    [', ']')}.
        ERLANG
      end

      def kind_clause(kind)
        state = kind.state&.property&.name
        fixed = kind.takes.select(&:fixed).map { |entry| atom(entry.property.name) }
        head = "number => #{kind.number}, children => #{kind.children}, " \
               "state => #{state ? atom(state) : 'none'}, fixed => [#{fixed.join(', ')}]"
        "kind(#{atom(kind.name)}) ->\n    \#{#{head},\n" \
          "#{wrap(kind.takes.map { |entry| atom(entry.property.name) }, '      takes => [', ']}')};\n"
      end

      def property_clause(property)
        fields = { 'number' => property.number.to_s, 'type' => type_term(property.type),
                   'common' => property.common.to_s, 'status' => property.status.to_s,
                   'detail' => property.detail ? atom(property.detail) : 'none' }
        fields['default'] = default_term(property.default) unless property.default.nil?
        "property(#{atom(property.name)}) ->\n#{wrap(fields.map { |key, value| "#{key} => #{value}" }, '    #{', '}')};\n"
      end

      def type_term(type)
        case type.form
        when 'integer' then "{integer, #{type.minimum}, #{type.maximum}}"
        when 'text', 'bytes' then "{#{type.form}, #{type.maximum}}"
        when 'list' then "{list, #{type_term(type.element)}, #{type.maximum}}"
        when 'enum', 'image' then "{#{type.form}, [#{type.atoms.map { |name| atom(name) }.join(', ')}]}"
        else type.form
        end
      end

      def default_term(value) = value.is_a?(String) ? atom(value) : value.to_s

      def walk
        <<~'ERLANG'
          %% Whether Tree is a valid widget tree of at most MaxNodes nodes, decided
          %% whole before anything is applied: ok, or the first fault in depth-first
          %% order. The walk visits at most MaxNodes + 1 nodes and 65 levels, and
          %% makes no atom.
          -spec validate(term(), non_neg_integer()) -> ok | {error, {reason(), where()}}.
          validate(Tree, MaxNodes) when is_integer(MaxNodes), MaxNodes >= 0 ->
              try node(Tree, [], 1, MaxNodes) of
                  _Left -> ok
              catch
                  throw:{?MODULE, Fault} -> {error, Fault}
              end.

          %% Checks the node Tree at Path, its child indexes reversed, and Depth,
          %% then its subtree, with Left nodes of the quota unspent; answers the
          %% quota left after the subtree.
          node(_Tree, Path, _Depth, 0) -> fault(too_many_nodes, Path);
          node(_Tree, Path, Depth, _Left) when Depth > ?MAX_DEPTH -> fault(too_deep, Path);
          node({Kind, Props, Children}, Path, Depth, Left)
            when is_atom(Kind), is_map(Props), is_list(Children) ->
              case kind(Kind) of
                  error ->
                      fault(unknown_kind, Path);
                  #{takes := Takes, children := TakesChildren} ->
                      check_properties(Kind, Takes, Props, Path),
                      Children =:= [] orelse TakesChildren orelse fault(children, Path),
                      children(Children, Path, Depth + 1, Left - 1, 0, #{})
              end;
          node(_Tree, Path, _Depth, _Left) ->
              fault(not_a_node, Path).

          %% Walks a node's children in order, refusing a key a sibling before
          %% carried, an improper list and a child past the last index.
          children([], _Path, _Depth, Left, _Index, _Keys) ->
              Left;
          children([Child | Rest], Path, Depth, Left, Index, Keys) when Index < ?MAX_CHILDREN ->
              ChildPath = [Index | Path],
              Keys1 = sibling_key(Child, ChildPath, Keys),
              children(Rest, Path, Depth, node(Child, ChildPath, Depth, Left), Index + 1, Keys1);
          children(_Children, Path, _Depth, _Left, _Index, _Keys) ->
              fault(children, Path).

          sibling_key({_Kind, #{key := Key}, _Children}, Path, Keys) ->
              is_map_key(Key, Keys) andalso fault(duplicate_key, Path),
              Keys#{Key => true};
          sibling_key(_Child, _Path, Keys) ->
              Keys.

          %% Every property is one the kind takes and of its type, in the order of
          %% the names; then the kind's properties agree with one another.
          check_properties(Kind, Takes, Props, Path) ->
              Names = lists:sort(maps:keys(Props)),
              [fault(unknown_property, Path, Name) || Name <- Names, not lists:member(Name, Takes)],
              [fault(bad_value, Path, Name) || Name <- Names, not valid(Name, maps:get(Name, Props))],
              relations(Kind, Props, Path).

          -spec fault(reason(), path()) -> no_return().
          fault(Reason, Path) ->
              throw({?MODULE, {Reason, lists:reverse(Path)}}).

          -spec fault(reason(), path(), term()) -> no_return().
          fault(Reason, Path, Property) ->
              throw({?MODULE, {Reason, {lists:reverse(Path), Property}}}).
        ERLANG
      end

      def plain_clauses(ui)
        clauses = ui.properties.map do |property|
          argument = property.type.form == 'event' ? '_Value' : 'Value'
          "plain(#{atom(property.name)}, #{argument}) -> #{plain_body(property.type)}"
        end
        "%% Whether Value is of the property's type.\n#{clauses.join(";\n")}.\n"
      end

      def plain_body(type)
        case type.form
        when 'integer' then "is_integer(Value) andalso Value >= #{type.minimum} andalso Value =< #{type.maximum}"
        when 'text' then "text(Value, #{type.maximum})"
        when 'bytes' then "is_binary(Value) andalso byte_size(Value) =< #{type.maximum}"
        when 'list' then "texts(Value, #{type.element.maximum}, #{type.maximum})"
        when 'enum', 'image' then "lists:member(Value, [#{type.atoms.map { |name| atom(name) }.join(', ')}])"
        when 'boolean' then 'is_boolean(Value)'
        when 'key' then "\n    is_integer(Value) orelse is_atom(Value) orelse (is_binary(Value) andalso byte_size(Value) =< #{UI::KEY_MAX})"
        when 'event' then 'true'
        when 'presentation' then 'presentation(Value)'
        end
      end

      def status_functions(ui, stopgaps)
        clauses = ui.properties.select(&:status).map { |property| "valid(#{atom(property.name)}, Value) -> status(#{atom(property.name)}, Value);\n" }
        <<~ERLANG
          %% A status property's value is a plain value or an attr() carrying one
          %% (docs/design-live.md, "Inspection records"). A two-tuple whose first
          %% element is a reporter is always read as an attr().
          #{clauses.join}valid(Property, Value) -> plain(Property, Value).
          #{status_body(stopgaps) unless clauses.empty?}
        ERLANG
      end

      def status_body(stopgaps)
        <<~ERLANG

          status(Property, {Reporter, Value}) when Reporter =:= kernel; Reporter =:= service; Reporter =:= runtime ->
              carried(Property, Value);
          status(Property, {{stopgap, Name}, Value}) ->
              lists:member(Name, [#{stopgaps.map { |name| atom(name) }.join(', ')}]) andalso carried(Property, Value);
          status(Property, Value) ->
              plain(Property, Value).

          %% The timeout is a u32 of the binary form.
          carried(Property, {ok, Value}) -> plain(Property, Value);
          carried(Property, {partial, Value}) -> plain(Property, Value);
          carried(_Property, unknown) -> true;
          carried(_Property, unsupported) -> true;
          carried(_Property, {timeout, Ms}) -> is_integer(Ms) andalso Ms >= 1 andalso Ms =< 16#ffffffff;
          carried(_Property, {error, _Reason}) -> true;
          carried(_Property, _Value) -> false.
        ERLANG
      end

      def relation_clauses(ui)
        clauses = ui.kinds.filter_map do |kind|
          calls = kind.takes.flat_map { |entry| relation_calls(kind, entry) }
          next if calls.empty?

          "relations(#{atom(kind.name)}, Props, Path) ->\n    #{calls.join(",\n    ")};\n"
        end
        marks = ui.kinds.flat_map(&:takes)
        used = clauses.join
        <<~ERLANG
          %% The marks that relate a kind's properties: a value within two bounds,
          %% an index into a list, and a flag under which a property is refused.
          #{used}relations(_Kind, _Props, _Path) -> ok.
          #{relation_helpers(marks)}
        ERLANG
      end

      def relation_calls(kind, entry)
        name = atom(entry.property.name)
        calls = []
        if entry.within
          low, high = entry.within.map { |bound| kind.taken(bound).property }
          calls << "within(Props, Path, #{name}, {#{atom(low.name)}, #{low.default}}, {#{atom(high.name)}, #{high.default}})"
        end
        calls << "index(Props, Path, #{name}, #{atom(entry.index)})" if entry.index
        calls << "hides(Props, Path, #{name}, #{atom(entry.hides)})" if entry.hides
        calls
      end

      def relation_helpers(marks)
        helpers = []
        if marks.any?(&:within)
          helpers << <<~'ERLANG'
            within(Props, Path, Property, {LowName, LowDefault}, {HighName, HighDefault}) ->
                Low = maps:get(LowName, Props, LowDefault),
                High = maps:get(HighName, Props, HighDefault),
                Low < High orelse fault(bad_value, Path, blamed(Props, LowName, HighName)),
                case Props of
                    #{Property := Value} when Value < Low; Value > High -> fault(bad_value, Path, Property);
                    _ -> ok
                end.

            %% The bound the tree set, the high one when it set both or neither.
            blamed(Props, LowName, HighName) ->
                case is_map_key(LowName, Props) andalso not is_map_key(HighName, Props) of
                    true -> LowName;
                    false -> HighName
                end.
          ERLANG
        end
        if marks.any?(&:index)
          helpers << <<~'ERLANG'
            index(Props, Path, Property, List) ->
                case Props of
                    #{Property := Index} ->
                        Index < length(maps:get(List, Props, [])) orelse fault(bad_value, Path, Property),
                        ok;
                    _ ->
                        ok
                end.
          ERLANG
        end
        if marks.any?(&:hides)
          helpers << <<~'ERLANG'
            hides(Props, Path, Flag, Hidden) ->
                case Props of
                    #{Flag := true, Hidden := _} -> fault(bad_value, Path, Hidden);
                    _ -> ok
                end.
          ERLANG
        end
        helpers.map { |text| "\n#{text}" }.join
      end

      def helpers(forms)
        parts = []
        parts << <<~ERLANG if forms.include?('list')
          texts([], _TextMax, _Left) -> true;
          texts([Text | Rest], TextMax, Left) when Left > 0 -> text(Text, TextMax) andalso texts(Rest, TextMax, Left - 1);
          texts(_Value, _TextMax, _Left) -> false.
        ERLANG
        parts << <<~ERLANG if forms.include?('text')
          text(Value, Max) -> is_binary(Value) andalso byte_size(Value) =< Max andalso utf8(Value).

          utf8(<<>>) -> true;
          utf8(<<_Character/utf8, Rest/binary>>) -> utf8(Rest);
          utf8(_Bytes) -> false.
        ERLANG
        parts << <<~ERLANG if forms.include?('presentation')
          %% A presentation the inspection schema marks, with a value of its
          %% marked path, so erx_present:text/2 writes its canonical text and a
          %% valid tree always encodes. path/2 raises badarg for a value outside
          %% the path's segments; the marks' names are within the wire's 63 bytes.
          presentation({Type, Value}) when is_atom(Type) ->
              lists:keymember(Type, 1, erx_present:marks()) andalso presented(Type, Value);
          presentation(_Value) -> false.

          presented(Type, Value) ->
              try erx_present:path(Type, Value) of
                  _Path -> true
              catch
                  error:badarg -> false
              end.
        ERLANG
        parts.join("\n")
      end

      # ITEMS joined by commas between OPEN and CLOSE, wrapped at WIDTH with
      # continuation lines aligned under the first item.
      def wrap(items, open, close)
        pieces = items.each_with_index.map { |item, index| index < items.size - 1 ? "#{item}," : item }
        rows = pieces.each_with_object([[]]) do |piece, acc|
          acc << [] if acc.last.any? && open.size + (acc.last + [piece]).sum { |text| text.size + 1 } > WIDTH
          acc.last << piece
        end
        rows.each_with_index.map { |row, index| (index.zero? ? open : ' ' * open.size) + row.join(' ') }.join("\n") + close
      end

      def atom(name) = InspectionEmitter.atom(name)
      def binary(text) = InspectionEmitter.binary(text)
    end
  end
end
