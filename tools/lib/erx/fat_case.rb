# frozen_string_literal: true

require 'digest'
require_relative 'error'
require_relative 'generation_plan'
require_relative 'terminal_generation'

module Erx
  # The FAT server's case table (docs/design-storage.md, "Removable media: FAT",
  # "Names"): each code point of the Basic Multilingual Plane with its simple
  # uppercase mapping, field 12 of Unicode's UnicodeData.txt, as erx_fat_case:upper/1.
  # It reads the one pinned Unicode version abi/terminal.txt names, checked against
  # its OTP origin by Erx::TerminalRules.pinned_inputs, so the FAT server and the
  # terminal tables read the same character database.
  module FatCase
    OUTPUT = 'erlang/apps/erx_fat/src/erx_fat_case.erl'
    BMP_LAST = 0xffff

    module_function

    def generation(root:)
      root = File.realpath(root)
      source_bytes, model, inputs = TerminalRules.pinned_inputs(root: root)
      bytes = inputs.fetch('unicode_data')
      pairs = uppercase_pairs(bytes)
      reads = { 'abi/terminal.txt' => Digest::SHA256.hexdigest(source_bytes),
                model.fetch('input').fetch('unicode_data') => Digest::SHA256.hexdigest(bytes) }
      GenerationPlan.new(files: { OUTPUT => erlang(pairs, unicode: model.fetch('unicode')).freeze }, reads: reads)
    end

    # [[point, upper]] for every BMP code point whose simple uppercase differs from it,
    # in code point order. A mapping out of the plane would need a surrogate pair,
    # which a comparison of single code units cannot give, so one is refused rather
    # than dropped: the comparison the design states would no longer hold. Pure.
    def uppercase_pairs(bytes)
      text = bytes.dup.force_encoding(Encoding::UTF_8)
      raise Error, 'UnicodeData is not valid UTF-8' unless text.valid_encoding?

      text.each_line.filter_map do |line|
        fields = line.chomp.split(';', -1)
        raise Error, 'invalid UnicodeData record' unless fields.size == 15

        point = hex(fields[0])
        next if point > BMP_LAST || fields[12].empty?

        upper = hex(fields[12])
        raise Error, format('U+%04X has an uppercase beyond the Basic Multilingual Plane', point) if upper > BMP_LAST

        [point, upper]
      end
    end

    def hex(field)
      raise Error, "invalid UnicodeData code point #{field.inspect}" unless field.match?(/\A[0-9A-F]{4,6}\z/)

      field.to_i(16)
    end
    private_class_method :hex

    def erlang(pairs, unicode:)
      clauses = pairs.map { |point, upper| format("upper(16#%04x) -> 16#%04x;\n", point, upper) }.join
      <<~ERLANG
        %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
        %% SPDX-License-Identifier: BSD-2-Clause
        %% Generated by tools/lib/erx/fat_case.rb from Unicode #{unicode}'s UnicodeData.txt; do not edit.

        -module(erx_fat_case).
        -moduledoc """
        The FAT server's case table (docs/design-storage.md, "Removable media: FAT",
        "Names"): the simple uppercase mapping of every code point of the Basic
        Multilingual Plane, from Unicode #{unicode}. A UTF-16 code unit that maps to
        itself, a surrogate among them, is answered as it is.
        """.

        -export([upper/1, unicode/0]).

        -doc "The Unicode version the table was generated from.".
        -spec unicode() -> string().
        unicode() -> "#{unicode}".

        -doc "Unit's simple uppercase form.".
        -spec upper(0..16#ffff) -> 0..16#ffff.
        #{clauses}upper(Unit) when is_integer(Unit), Unit >= 0, Unit =< 16#ffff -> Unit.
      ERLANG
    end
    private_class_method :erlang
  end
end
