require 'digest'
require_relative 'abi_emit_inspection'
require_relative 'terminal_rules'

module Erx
  module ABI
    # Emits the web protocol's two codecs from the `web` declaration of
    # abi/protocols/web.txt (docs/design-abi.md, "Web protocol";
    # docs/design-web.md, "The protocol"): erx_web_proto, the Erlang codec the
    # web domain uses, and the type table both codecs read; the TypeScript
    # twin is WebTSEmitter's. Each codec is a fixed interpreter over a
    # generated table of the declaration's types, so the two agree on every
    # layout and bound exactly when they come from one declaration. Both
    # carry the protocol hash this module computes.
    module WebEmitter
      ERLANG_PATH = 'erlang/apps/erx/src/generated/erx_web_proto.erl'
      # The sources generated into the web client besides terminal.txt's
      # Unicode inputs, in the order the hash takes them.
      HASHED = %w[abi/protocols/web.txt abi/formats/ui.txt abi/inspection.txt abi/terminal.txt].freeze
      TERMINAL = 'abi/terminal.txt'
      INPUT_MAX = 8 * 1024 * 1024

      module_function

      # Every source the hash covers, as [path, bytes] in hash order: the
      # ABI sources from INPUTS, the files read for this plan, then
      # terminal.txt and the Unicode data it names, read from ROOT.
      def hashed_sources(root:, inputs:)
        terminal = read_bounded(root, TERMINAL)
        unicode = TerminalRules.source(terminal).fetch('input').values
        HASHED.map { |path| [path, path == TERMINAL ? terminal : inputs.fetch(path)] } +
          unicode.map { |path| [path, read_bounded(root, path)] }
      rescue KeyError => error
        raise SchemaError, "the protocol hash misses a source: #{error.message}"
      end

      # SHA-256 over one line per source, its path and its bytes' SHA-256, so
      # no two source sets of distinct paths or contents share a hash.
      def protocol_hash(sources)
        Digest::SHA256.hexdigest(sources.map { |path, bytes| "#{path} #{Digest::SHA256.hexdigest(bytes)}\n" }.join)
      end

      def outputs(schema, sources:)
        return {} unless schema.web

        hash = protocol_hash(sources)
        { ERLANG_PATH => erlang(schema.web, hash: hash),
          WebTSEmitter::PATH => WebTSEmitter.typescript(schema.web, hash: hash) }.freeze
      end

      def read_bounded(root, path)
        bytes = File.binread(File.join(root, path), INPUT_MAX + 1)
        raise SchemaError, "#{path} exceeds #{INPUT_MAX} bytes" if bytes.nil? || bytes.bytesize > INPUT_MAX

        bytes
      rescue SystemCallError => error
        raise SchemaError, "cannot read #{path} for the protocol hash: #{error.message}"
      end

      def atom(name) = InspectionEmitter.atom(name)

      def binary(text) = "<<\"#{text}\">>"

      def erlang(web, hash:)
        [erlang_head(web, hash), erlang_types(web), ERLANG_CODEC, erlang_tables(web)].join("\n")
      end

      def erlang_head(web, hash)
        <<~ERLANG
          %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
          %% SPDX-License-Identifier: BSD-2-Clause
          %% Generated by tools/gen_abi.rb from abi/protocols/web.txt.
          %% Do not edit this file.

          -module(erx_web_proto).
          -moduledoc """
          The web protocol's codec (docs/design-web.md, "The protocol"). decode/2
          reads one whole message of a message union (#{web.messages.join(' or ')}) and
          refuses one over its bound, of an unknown tag, outside a bound or with
          bytes after it; encode/2 writes one and refuses a term the decoder would
          refuse. Integers are little-endian; bytes and texts are a u32 length and
          the bytes; a list is a u32 count and its elements; a union is a u8 tag
          and its case's fields. The codec interprets type/1, the table generated
          from web.txt, and creates no atom: every atom it returns is a literal of
          that table. hash/0 is the protocol hash, which a client's hello carries.
          """.
          -export([decode/2, encode/2, hash/0, limit/1, messages/0, message_max/1, type/1, types/0, stopgaps/0]).
          -export_type([#{web.types.keys.map { |name| "#{atom(name)}/0" }.join(', ')}]).

          -type reason() :: {truncated | too_long | too_many | bad_value | bad_tag | bad_term | trailing,
                             Type :: atom()}.
          -type spec() :: boolean
                        | {integer, Bits :: 8 | 16 | 32, Min :: non_neg_integer(), Max :: non_neg_integer()}
                        | {bytes, Max :: pos_integer(), exact | upto}
                        | {text | digits | ui_record, Max :: pos_integer()}
                        | stopgap
                        | {list, Element :: atom(), Max :: pos_integer()}
                        | {tuple, [Type :: atom()]}
                        | {map, [{Key :: atom(), Type :: atom()}]}
                        | {union, Depth :: pos_integer() | none,
                           [{Tag :: 1..255, Name :: atom(), [Type :: atom()], Recursive :: boolean()}]}.

          -define(STOPGAP_MAX, #{Web::STOPGAP_MAX}).
          %% The process dictionary key of the room encode/2 has left.
          -define(ROOM, {?MODULE, room}).

          %% The SHA-256 over web.txt, ui.txt, inspection.txt, terminal.txt and the
          %% Unicode data terminal.txt names.
          -spec hash() -> <<_:256>>.
          hash() -> <<16##{hash}:256>>.
        ERLANG
      end

      # One -type per declared type, for readers of the terms and for Dialyzer.
      def erlang_types(web)
        web.types.values.map { |type| "-type #{atom(type.name)}() :: #{erlang_type(type)}.\n" }.join
      end

      def erlang_type(type)
        case type.form
        when 'integer' then "#{type.minimum}..#{type.maximum}"
        when 'list' then "[#{reference(type.element)}]"
        when 'tuple' then "{#{type.fields.map { |field| reference(field.type) }.join(', ')}}"
        when 'map' then "\#{#{type.fields.map { |field| "#{atom(field.name)} := #{reference(field.type)}" }.join(', ')}}"
        when 'union'
          type.cases.map do |entry|
            next atom(entry.name) if entry.fields.empty?

            "{#{[atom(entry.name), *entry.fields.map { |field| reference(field.type) }].join(', ')}}"
          end.join("\n    | ")
        else 'binary()'
        end
      end

      def reference(name) = name == 'boolean' ? 'boolean()' : "#{atom(name)}()"

      def erlang_tables(web)
        types = web.types.values
        type_clauses = types.map { |type| "type(#{atom(type.name)}) ->\n    #{spec(type)}" } +
                       ["type(boolean) ->\n    boolean"]
        limits = web.limits.map { |name, value| "limit(#{atom(name)}) -> #{value}" }
        messages = web.messages.map { |name| "message_max(#{atom(name)}) -> #{web.types.fetch(name).message}" }
        <<~ERLANG
          %% The declared types, in web.txt's order.
          -spec types() -> [atom()].
          types() ->
              [#{types.map { |type| atom(type.name) }.join(",\n     ")}].

          %% The layout of each type; boolean is the one form no declaration names.
          -spec type(atom()) -> spec().
          #{type_clauses.join(";\n")}.

          %% The protocol's bounds, every limit named web_*.
          -spec limit(atom()) -> pos_integer().
          #{limits.join(";\n")}.

          %% The message unions, and the byte bound of each.
          -spec messages() -> [atom()].
          messages() ->
              [#{web.messages.map { |name| atom(name) }.join(', ')}].

          -spec message_max(atom()) -> pos_integer().
          #{messages.join(";\n")}.

          %% The inspection schema's stopgap reporters, the names a stopgap type admits.
          -spec stopgaps() -> [binary()].
          stopgaps() ->
              [#{web.stopgaps.map { |name| binary(name) }.join(', ')}].
        ERLANG
      end

      def spec(type)
        case type.form
        when 'integer' then "{integer, #{type.bits}, #{type.minimum}, #{type.maximum}}"
        when 'bytes' then "{bytes, #{type.maximum}, #{type.exact ? 'exact' : 'upto'}}"
        when 'text', 'digits', 'ui_record' then "{#{type.form}, #{type.maximum}}"
        when 'stopgap' then 'stopgap'
        when 'list' then "{list, #{atom(type.element)}, #{type.maximum}}"
        when 'tuple' then "{tuple, [#{type.fields.map { |field| atom(field.type) }.join(', ')}]}"
        when 'map' then "{map, [#{type.fields.map { |field| "{#{atom(field.name)}, #{atom(field.type)}}" }.join(', ')}]}"
        when 'union'
          cases = type.cases.map do |entry|
            "{#{entry.tag}, #{atom(entry.name)}, [#{entry.fields.map { |field| atom(field.type) }.join(', ')}], #{entry.recursive}}"
          end
          "{union, #{type.depth || 'none'},\n     [#{cases.join(",\n      ")}]}"
        end
      end

      ERLANG_CODEC = <<~'ERLANG'
        -spec decode(atom(), binary()) -> {ok, term()} | {error, reason()}.
        decode(Message, Bytes) when is_binary(Bytes) ->
            case is_message(Message) of
                true -> decode_message(Message, Bytes);
                false -> {error, {bad_term, Message}}
            end.

        decode_message(Message, Bytes) ->
            case byte_size(Bytes) =< message_max(Message) of
                false ->
                    {error, {too_long, Message}};
                true ->
                    try read(Message, Bytes, 1) of
                        {Value, <<>>} -> {ok, Value};
                        {_, _} -> {error, {trailing, Message}}
                    catch
                        throw:{?MODULE, Reason} -> {error, Reason}
                    end
            end.

        -spec encode(atom(), term()) -> {ok, binary()} | {error, reason()}.
        encode(Message, Term) ->
            case is_message(Message) of
                true ->
                    %% The room left is counted as each piece is written, so a term
                    %% that shares subterms is refused once it passes the bound, not
                    %% after it has been written out whole.
                    put(?ROOM, message_max(Message)),
                    try iolist_to_binary(write(Message, Term, 1)) of
                        Bytes -> {ok, Bytes}
                    catch
                        throw:{?MODULE, Reason} -> {error, Reason}
                    after
                        erase(?ROOM)
                    end;
                false ->
                    {error, {bad_term, Message}}
            end.

        is_message(Message) ->
            lists:member(Message, messages()).

        %% Takes Size bytes of the message's room, or refuses the message.
        spend(Size, Type) ->
            case get(?ROOM) - Size of
                Left when Left >= 0 -> put(?ROOM, Left), ok;
                _ -> refuse(too_long, Type)
            end.

        refuse(Reason, Type) ->
            throw({?MODULE, {Reason, Type}}).

        %% A recursive case is open only below its union's depth; every other
        %% case is always open.
        open(false, _Level, _Depth) -> true;
        open(true, Level, Depth) -> Level < Depth.

        %% A depth union's recursive case reads and writes its fields a level
        %% deeper; every other field stays at its parent's level.
        inner(true, Level) -> Level + 1;
        inner(false, Level) -> Level.

        %% read(Type, Bytes, Level) -> {Value, Rest}, or a refusal thrown.
        read(Type, Bytes, Level) ->
            read(type(Type), Type, Bytes, Level).

        read({integer, Bits, Min, Max}, Type, Bytes, _Level) ->
            case Bytes of
                <<Value:Bits/little, Rest/binary>> when Value >= Min, Value =< Max -> {Value, Rest};
                <<_:Bits/little, _/binary>> -> refuse(bad_value, Type);
                _ -> refuse(truncated, Type)
            end;
        read(boolean, Type, Bytes, _Level) ->
            case Bytes of
                <<0, Rest/binary>> -> {false, Rest};
                <<1, Rest/binary>> -> {true, Rest};
                <<_, _/binary>> -> refuse(bad_value, Type);
                _ -> refuse(truncated, Type)
            end;
        read({bytes, Max, Size}, Type, Bytes, _Level) ->
            {Value, Rest} = sized(Bytes, Max, Type),
            case Size =:= upto orelse byte_size(Value) =:= Max of
                true -> {Value, Rest};
                false -> refuse(bad_value, Type)
            end;
        read({text, Max}, Type, Bytes, _Level) ->
            sized(Bytes, Max, Type);
        read({digits, Max}, Type, Bytes, _Level) ->
            {Value, Rest} = sized(Bytes, Max, Type),
            case canonical(Value) of
                true -> {Value, Rest};
                false -> refuse(bad_value, Type)
            end;
        read(stopgap, Type, Bytes, _Level) ->
            {Value, Rest} = sized(Bytes, ?STOPGAP_MAX, Type),
            case lists:member(Value, stopgaps()) of
                true -> {Value, Rest};
                false -> refuse(bad_value, Type)
            end;
        read({ui_record, Max}, Type, Bytes, _Level) ->
            case Bytes of
                <<Length:32/little, Body:Length/binary, Rest/binary>> when Length >= 1, Length =< Max ->
                    {<<Length:32/little, Body/binary>>, Rest};
                <<Length:32/little, _/binary>> when Length < 1; Length > Max -> refuse(bad_value, Type);
                _ -> refuse(truncated, Type)
            end;
        read({list, Element, Max}, Type, Bytes, Level) ->
            %% Every element takes at least one byte, so a count the bytes
            %% cannot hold is refused before any element is read.
            case Bytes of
                <<Count:32/little, _/binary>> when Count > Max -> refuse(too_many, Type);
                <<Count:32/little, Rest/binary>> when Count =< byte_size(Rest) ->
                    elements(Count, Element, Rest, Level, []);
                _ -> refuse(truncated, Type)
            end;
        read({tuple, Fields}, _Type, Bytes, Level) ->
            {Values, Rest} = fields(Fields, Bytes, Level, []),
            {list_to_tuple(Values), Rest};
        read({map, Fields}, _Type, Bytes, Level) ->
            {Keys, Types} = lists:unzip(Fields),
            {Values, Rest} = fields(Types, Bytes, Level, []),
            {maps:from_list(lists:zip(Keys, Values)), Rest};
        read({union, Depth, Cases}, Type, Bytes, Level) ->
            case Bytes of
                <<Tag, Rest/binary>> ->
                    case lists:keyfind(Tag, 1, Cases) of
                        {Tag, Name, [], false} ->
                            {Name, Rest};
                        {Tag, Name, Fields, Recursive} ->
                            open(Recursive, Level, Depth) orelse refuse(bad_tag, Type),
                            {Values, After} = fields(Fields, Rest, inner(Recursive, Level), []),
                            {list_to_tuple([Name | Values]), After};
                        false ->
                            refuse(bad_tag, Type)
                    end;
                <<>> ->
                    refuse(truncated, Type)
            end.

        sized(Bytes, Max, Type) ->
            case Bytes of
                <<Length:32/little, _/binary>> when Length > Max -> refuse(too_long, Type);
                <<Length:32/little, Value:Length/binary, Rest/binary>> -> {Value, Rest};
                _ -> refuse(truncated, Type)
            end.

        elements(0, _Element, Bytes, _Level, Values) ->
            {lists:reverse(Values), Bytes};
        elements(Count, Element, Bytes, Level, Values) ->
            {Value, Rest} = read(Element, Bytes, Level),
            elements(Count - 1, Element, Rest, Level, [Value | Values]).

        fields([], Bytes, _Level, Values) ->
            {lists:reverse(Values), Bytes};
        fields([Type | Types], Bytes, Level, Values) ->
            {Value, Rest} = read(Type, Bytes, Level),
            fields(Types, Rest, Level, [Value | Values]).

        %% An integer's decimal text in its one canonical form: 0, or digits
        %% without a leading zero after an optional minus.
        canonical(<<"0">>) -> true;
        canonical(<<"-", Digits/binary>>) -> nonzero(Digits);
        canonical(Digits) -> nonzero(Digits).

        nonzero(<<First, Rest/binary>>) when First >= $1, First =< $9 -> digits(Rest);
        nonzero(_) -> false.

        digits(<<Digit, Rest/binary>>) when Digit >= $0, Digit =< $9 -> digits(Rest);
        digits(<<>>) -> true;
        digits(_) -> false.

        %% write(Type, Term, Level) -> iodata(), or a refusal thrown.
        %% Each fixed piece spends its own size; a sized value spends its length
        %% word in sized/2 and its bytes here.
        write(Type, Term, Level) ->
            write(type(Type), Type, Term, Level).

        write({integer, Bits, Min, Max}, Type, Term, _Level) when is_integer(Term), Term >= Min, Term =< Max ->
            spend(Bits div 8, Type),
            <<Term:Bits/little>>;
        write(boolean, Type, false, _Level) ->
            spend(1, Type),
            <<0>>;
        write(boolean, Type, true, _Level) ->
            spend(1, Type),
            <<1>>;
        write({bytes, Max, upto}, Type, Term, _Level) when is_binary(Term), byte_size(Term) =< Max ->
            sized(Term, Type);
        write({bytes, Max, exact}, Type, Term, _Level) when is_binary(Term), byte_size(Term) =:= Max ->
            sized(Term, Type);
        write({text, Max}, Type, Term, _Level) when is_binary(Term), byte_size(Term) =< Max ->
            sized(Term, Type);
        write({digits, Max}, Type, Term, _Level) when is_binary(Term), byte_size(Term) =< Max ->
            case canonical(Term) of
                true -> sized(Term, Type);
                false -> refuse(bad_term, Type)
            end;
        write(stopgap, Type, Term, _Level) when is_binary(Term) ->
            case lists:member(Term, stopgaps()) of
                true -> sized(Term, Type);
                false -> refuse(bad_term, Type)
            end;
        write({ui_record, Max}, Type, Term, _Level) when is_binary(Term) ->
            case Term of
                <<Length:32/little, Body/binary>> when Length >= 1, Length =< Max, byte_size(Body) =:= Length ->
                    spend(byte_size(Term), Type),
                    Term;
                _ -> refuse(bad_term, Type)
            end;
        write({list, Element, Max}, Type, Term, Level) when is_list(Term) ->
            case bounded_length(Term, Max, 0) of
                {ok, Count} ->
                    spend(4, Type),
                    [<<Count:32/little>> | [write(Element, Value, Level) || Value <- Term]];
                error -> refuse(bad_term, Type)
            end;
        write({tuple, Fields}, _Type, Term, Level) when is_tuple(Term), tuple_size(Term) =:= length(Fields) ->
            write_fields(Fields, tuple_to_list(Term), Level);
        write({map, Fields}, Type, Term, Level) when is_map(Term), map_size(Term) =:= length(Fields) ->
            [case Term of
                 #{Key := Value} -> write(FieldType, Value, Level);
                 #{} -> refuse(bad_term, Type)
             end || {Key, FieldType} <- Fields];
        write({union, Depth, Cases}, Type, Term, Level) ->
            {Name, Values} = case Term of
                                 Atom when is_atom(Atom) -> {Atom, []};
                                 _ when is_tuple(Term), tuple_size(Term) >= 2, is_atom(element(1, Term)) ->
                                     {element(1, Term), tl(tuple_to_list(Term))};
                                 _ -> refuse(bad_term, Type)
                             end,
            case lists:keyfind(Name, 2, Cases) of
                {Tag, Name, Fields, Recursive} when length(Fields) =:= length(Values) ->
                    open(Recursive, Level, Depth) orelse refuse(bad_term, Type),
                    spend(1, Type),
                    [Tag | write_fields(Fields, Values, inner(Recursive, Level))];
                _ ->
                    refuse(bad_term, Type)
            end;
        write(_Spec, Type, _Term, _Level) ->
            refuse(bad_term, Type).

        sized(Bytes, Type) ->
            spend(4 + byte_size(Bytes), Type),
            [<<(byte_size(Bytes)):32/little>>, Bytes].

        write_fields(Types, Values, Level) ->
            lists:zipwith(fun(Type, Value) -> write(Type, Value, Level) end, Types, Values).

        %% The length of a proper list of at most Max elements, or error,
        %% without walking past the bound.
        bounded_length([], _Max, Count) -> {ok, Count};
        bounded_length([_ | Rest], Max, Count) when Count < Max -> bounded_length(Rest, Max, Count + 1);
        bounded_length(_, _Max, _Count) -> error.
      ERLANG
    end
  end
end
