# frozen_string_literal: true

module Erx
  module ABI
    # What every generated TypeScript module of the web client shares
    # (docs/design-web.md, "The client"): the header that names its source and
    # generator, string literals and constant tables. The output uses
    # TypeScript's erasable syntax only (no enum, namespace or parameter
    # property), so Node runs it by stripping the types, and is ASCII only.
    module TypeScript
      module_function

      # The module's opening comment; summary is its purpose, one paragraph.
      def header(source:, summary:)
        lines = summary.strip.lines.map { |line| " * #{line.strip}".rstrip }
        <<~TS
          /*
           * Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
           * SPDX-License-Identifier: BSD-2-Clause
           * Generated by tools/gen_abi.rb from #{source}.
           * Do not edit this file.
           *
          #{lines.join("\n")}
           */
        TS
      end

      # A double-quoted literal of an ASCII text with no control character.
      def string(text)
        unless text.ascii_only? && !text.match?(/[\x00-\x1f\x7f]/)
          raise SchemaError, "#{text.inspect} is not printable ASCII"
        end

        %("#{text.gsub(/["\\]/) { |char| "\\#{char}" }}")
      end

      # A one-line comment, refusing text that would end it early.
      def comment(text)
        raise SchemaError, "comment #{text.inspect} holds */" if text.include?('*/')

        "/* #{text} */"
      end

      # `export const NAME = value;` under a one-line comment.
      def constant(name:, value:, comment:) = "#{comment(comment)}\nexport const #{name} = #{value};\n"

      # A frozen array of string literals and the union type of its members.
      def names(constant:, type:, members:, comment:)
        <<~TS
          #{comment(comment)}
          export const #{constant} = Object.freeze([#{members.map { |member| string(member) }.join(', ')}] as const);
          export type #{type} = (typeof #{constant})[number];
        TS
      end

      # A ReadonlyMap literal of [key, value] pairs, already rendered, one per
      # line; a Map, not an object, so no key meets Object's prototype.
      def map(pairs, type:, indent: '')
        return "new Map<#{type}>()" if pairs.empty?

        "new Map<#{type}>([\n#{pairs.map { |key, value| "#{indent}  [#{key}, #{value}]" }.join(",\n")},\n#{indent}])"
      end
    end
  end
end
