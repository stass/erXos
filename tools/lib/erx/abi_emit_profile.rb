# frozen_string_literal: true

require_relative 'abi_model'
require_relative 'abi_profile'

module Erx
  module ABI
    # Emits, for each frame protocol with "reader c", the table liberx's
    # erx_profile.c interprets and the typed functions over it
    # (docs/design-abi.md, "Program protocol"): include/erx/P_profile.h with
    # a struct for each tuple, map and union, an iterator type of its own for
    # each list, and liberx/generated/P_profile.c with the table, whose
    # offsets are the compiler's own offsetof, and static asserts that the C
    # check's fixed bounds hold it. A kind's index in the table is its index in
    # the protocol's declarations, then the built-in kinds it uses.
    class ProfileEmitter
      INTEGER_TYPES = { 'u8' => 'uint8_t', 'u16' => 'uint16_t', 'u32' => 'uint32_t', 'u64' => 'uint64_t' }.freeze
      BASE_MAX = { 'u8' => 0xff, 'u16' => 0xffff, 'u32' => 0xffff_ffff, 'u64' => 0xffff_ffff_ffff_ffff }.freeze
      SLOT_MAX = 15

      def self.outputs(schema)
        schema.protocols.select { |protocol| protocol[:reader] == 'c' }.each_with_object({}) do |protocol, files|
          emitter = new(protocol, signals: schema.signals.signals.select(&:nameable?))
          files["include/erx/#{emitter.short}_profile.h"] = emitter.header
          files["liberx/generated/#{emitter.short}_profile.c"] = emitter.source
        end.freeze
      end

      def initialize(protocol, signals:)
        @protocol = protocol
        @kinds = protocol.fetch(:kinds)
        @signals = signals
        builtins = %w[boolean signal u8 u16 u32 u64].select { |name| referenced.include?(name) }
        builtins << 'slot' if protocol.fetch(:frames).any? { |frame| frame.fetch(:slot) }
        @order = @kinds.keys + builtins
        @names = @order + protocol.fetch(:totals).keys + protocol.fetch(:frames).map { |frame| frame.fetch(:name) }
      end

      def short = @protocol.fetch(:name).delete_prefix('erx_')

      def header
        guard = "ERX_#{short.upcase}_PROFILE_H"
        ["/* Generated by tools/lib/erx/abi_emit_profile.rb from #{@protocol.fetch(:source)}. Do not edit. */",
         '', "#ifndef #{guard}", "#define #{guard}", '',
         "/* The #{@protocol.fetch(:name)} frame profile's C check (docs/design-abi.md#program-protocol). */",
         '', '#include <erx/profile.h>', '', enums, types, prototypes, '', "#endif /* !#{guard} */", ''].join("\n")
      end

      def source
        ["/* Generated by tools/lib/erx/abi_emit_profile.rb from #{@protocol.fetch(:source)}. Do not edit. */",
         '', '#include <stddef.h>', '#include <stdint.h>', '', "#include <erx/#{short}_profile.h>", '',
         values_tables, fields_tables, cases_tables, kinds_table, names_table, rules_tables, signals_table,
         frames_table, profile, bounds, functions].join("\n")
      end

      private

      def prefix = "erx_#{short}"

      def referenced
        @referenced ||= @kinds.values.flat_map do |kind|
          [*kind.fetch(:elements, []), kind[:element], *kind.fetch(:fields, []).map(&:last),
           *kind.fetch(:cases, []).flat_map { |item| item.fetch(:fields) }]
        end.compact + @protocol.fetch(:frames).map { |frame| frame.fetch(:kind) }
      end

      def index(name) = @order.index(name) || raise(SchemaError, "no kind #{name}")

      def atoms_only?(kind) = kind.fetch(:cases).all? { |item| item.fetch(:fields).empty? }

      # The C type of a value of kind name.
      def c_type(name)
        kind = @kinds[name]
        return INTEGER_TYPES.fetch(name) if INTEGER_TYPES.key?(name)
        return 'bool' if name == 'boolean'
        return 'int32_t' if name == 'signal'
        return 'uint8_t' if name == 'slot'

        case kind.fetch(:form)
        when 'integer' then INTEGER_TYPES.fetch(kind.fetch(:base))
        when 'text' then 'erx_profile_text_t'
        when 'list' then "#{prefix}_#{name}_iter_t"
        when 'union' then atoms_only?(kind) ? 'uint16_t' : "#{prefix}_#{name}_t"
        else "#{prefix}_#{name}_t"
        end
      end

      # Member names for a tuple's or a case's fields: each kind's name, with
      # _1, _2 ... when a kind repeats.
      def member_names(kinds)
        kinds.map.with_index do |kind, position|
          kinds.count(kind) > 1 ? "#{kind}_#{kinds.first(position + 1).count(kind)}" : kind
        end
      end

      def enum_name(union, atoms) = "#{prefix}_#{union}_#{atoms.join('_')}".upcase

      def enums
        @kinds.select { |_, kind| kind.fetch(:form) == 'union' && !kind.fetch(:cases).empty? }.map do |name, kind|
          constants = kind.fetch(:cases).each_with_index.map { |item, value| "\t#{enum_name(name, item.fetch(:atoms))} = #{value}," }
          "/* The cases of #{name}, the values of its which. */\nenum {\n#{constants.join("\n")}\n};\n"
        end.join("\n")
      end

      def types
        @kinds.filter_map do |name, kind|
          case kind.fetch(:form)
          when 'list'
            "/* #{name}: at most #{kind.dig(:max, :value)} #{kind.fetch(:element)}#{kind.fetch(:ascending) ? ', ascending' : ''}. */\n" \
              "typedef struct #{prefix}_#{name}_iter {\n\terx_profile_list_t\tview;\n} #{c_type(name)};\n"
          when 'tuple'
            members = member_names(kind.fetch(:elements)).zip(kind.fetch(:elements))
            struct(name, members.map { |member, element| "\t#{c_type(element)}\t#{member};" })
          when 'map'
            members = kind.fetch(:fields).flat_map do |field, field_kind|
              line = "\t#{c_type(field_kind)}\t#{field};"
              kind.fetch(:optional).include?(field) ? ["\tbool\thas_#{field};", line] : [line]
            end
            struct(name, members)
          when 'union'
            next if atoms_only?(kind)

            cases = kind.fetch(:cases).reject { |item| item.fetch(:fields).empty? }.map do |item|
              members = member_names(item.fetch(:fields)).zip(item.fetch(:fields))
              "\t\tstruct {\n#{members.map { |member, field| "\t\t\t#{c_type(field)}\t#{member};" }.join("\n")}\n" \
                "\t\t} #{item.fetch(:c_name)};"
            end
            struct(name, ["\tuint16_t\twhich;", "\tunion {\n#{cases.join("\n")}\n\t} u;"])
          end
        end.join("\n")
      end

      def struct(name, members)
        "typedef struct #{prefix}_#{name} {\n#{members.join("\n")}\n} #{prefix}_#{name}_t;\n"
      end

      def prototypes
        frames = @protocol.fetch(:frames).map do |frame|
          slot = frame.fetch(:slot) ? 'uint8_t *slot, ' : ''
          "bool\t#{prefix}_check_#{frame.fetch(:name)}(const uint8_t *frame, size_t len,\n" \
            "\t    void *scratch, size_t scratch_len, #{slot}#{c_type(frame.fetch(:kind))} *#{frame.fetch(:name)},\n" \
            "\t    erx_profile_refusal_t *refusal);"
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.map do |name, kind|
          "bool\t#{prefix}_#{name}_next(#{c_type(name)} *it, #{c_type(kind.fetch(:element))} *element);"
        end
        ["extern const erx_profile_t #{prefix}_profile;", '',
         "size_t\t#{prefix}_scratch_bytes(size_t len);", *frames, *lists,
         "const char *#{prefix}_kind_name(uint16_t kind);"].join("\n")
      end

      def values_tables
        @kinds.select { |_, kind| kind[:values] }.map do |name, kind|
          "static const uint64_t #{name}_values[] = { #{kind[:values].map { |value| "UINT64_C(#{value.fetch(:value)})" }.join(', ')} };\n"
        end.join
      end

      def field(kind:, offset:, name: nil, has: nil)
        "\t{ .name = #{name ? "\"#{name}\"" : 'NULL'}, .kind = #{index(kind)}, .offset = #{offset}, " \
          ".has_offset = #{has || 'ERX_PROFILE_NONE'} },"
      end

      def fields_tables
        @kinds.filter_map do |name, kind|
          type = "#{prefix}_#{name}_t"
          rows = case kind.fetch(:form)
                 when 'tuple'
                   member_names(kind.fetch(:elements)).zip(kind.fetch(:elements)).map do |member, element|
                     field(kind: element, offset: "offsetof(#{type}, #{member})")
                   end
                 when 'map'
                   kind.fetch(:fields).map do |key, field_kind|
                     has = kind.fetch(:optional).include?(key) ? "offsetof(#{type}, has_#{key})" : nil
                     field(kind: field_kind, offset: "offsetof(#{type}, #{key})", name: key, has: has)
                   end
                 when 'union'
                   kind.fetch(:cases).reject { |item| item.fetch(:fields).empty? }.map do |item|
                     members = member_names(item.fetch(:fields)).zip(item.fetch(:fields))
                     rows = members.map do |member, field_kind|
                       field(kind: field_kind, offset: "offsetof(#{type}, u.#{item.fetch(:c_name)}.#{member}) - " \
                                                       "offsetof(#{type}, u.#{item.fetch(:c_name)})")
                     end
                     "static const erx_profile_field_t #{name}_#{item.fetch(:c_name)}_fields[] = {\n#{rows.join("\n")}\n};\n"
                   end.join("\n")
                 end
          next nil if rows.nil? || rows.empty?

          kind.fetch(:form) == 'union' ? rows : "static const erx_profile_field_t #{name}_fields[] = {\n#{rows.join("\n")}\n};\n"
        end.join("\n")
      end

      def cases_tables
        @kinds.select { |_, kind| kind.fetch(:form) == 'union' && !kind.fetch(:cases).empty? }.map do |name, kind|
          atoms = kind.fetch(:cases).map do |item|
            "static const char *const #{name}_#{item.fetch(:c_name)}_atoms[] = { #{item.fetch(:atoms).map { |atom| "\"#{atom}\"" }.join(', ')} };"
          end
          rows = kind.fetch(:cases).map do |item|
            fields = item.fetch(:fields).empty? ? 'NULL' : "#{name}_#{item.fetch(:c_name)}_fields"
            offset = item.fetch(:fields).empty? || atoms_only?(kind) ? '0' : "offsetof(#{prefix}_#{name}_t, u.#{item.fetch(:c_name)})"
            "\t{ .atoms = #{name}_#{item.fetch(:c_name)}_atoms, .fields = #{fields}, .natoms = #{item.fetch(:atoms).size}, " \
              ".nfields = #{item.fetch(:fields).size}, .offset = #{offset} },"
          end
          "#{atoms.join("\n")}\nstatic const erx_profile_case_t #{name}_cases[] = {\n#{rows.join("\n")}\n};\n"
        end.join("\n")
      end

      def kinds_table
        rows = @order.map { |name| "\t[#{index(name)}] = #{kind_row(name)}," }
        "/* Each kind; refusals name it by its index here. */\nstatic const erx_profile_kind_t kinds[] = {\n#{rows.join("\n")}\n};\n"
      end

      def kind_row(name)
        kind = @kinds[name]
        rule = ->(index) { index.nil? ? 'ERX_PROFILE_NONE' : index }
        common = ".name = \"#{name}\", .size = sizeof(#{c_type(name)}), " \
                 ".sum = #{rule.call(kind && kind[:sum] && @protocol.fetch(:totals).keys.index(kind[:sum]))}, " \
                 ".refers = #{rule.call(@protocol.fetch(:refers).index { |item| item.fetch(:kind) == name })}, " \
                 ".target = #{rule.call(@protocol.fetch(:refers).index { |item| item.fetch(:list) == name })}"
        return "{ #{common}, .form = ERX_PROFILE_BOOLEAN }" if name == 'boolean'
        return "{ #{common}, .form = ERX_PROFILE_SIGNAL }" if name == 'signal'
        return "{ #{common}, .form = ERX_PROFILE_INTEGER, .min = 0, .max = #{SLOT_MAX} }" if name == 'slot'
        return "{ #{common}, .form = ERX_PROFILE_INTEGER, .min = 0, .max = UINT64_C(#{BASE_MAX.fetch(name)}) }" unless kind

        fields = "{\n\t    #{common.gsub(', .', ",\n\t    .")}"
        case kind.fetch(:form)
        when 'integer' then "#{fields},\n\t    #{integer_members(name, kind)} }"
        when 'text' then "#{fields},\n\t    #{text_members(kind)} }"
        when 'tuple'
          "#{fields},\n\t    .form = ERX_PROFILE_TUPLE, .fields = #{name}_fields, .nfields = #{kind.fetch(:elements).size} }"
        when 'map'
          "#{fields},\n\t    .form = ERX_PROFILE_MAP, .fields = #{name}_fields, .nfields = #{kind.fetch(:fields).size} }"
        when 'list'
          "#{fields},\n" \
            "\t    .form = ERX_PROFILE_LIST, .element = #{index(kind.fetch(:element))}, " \
            ".list_max = #{kind.dig(:max, :value)}, .ascending = #{kind.fetch(:ascending)} }"
        when 'union'
          form = atoms_only?(kind) ? 'ERX_PROFILE_ATOMS' : 'ERX_PROFILE_UNION'
          cases = kind.fetch(:cases).empty? ? 'NULL' : "#{name}_cases"
          "#{fields},\n\t    .form = #{form}, .cases = #{cases}, .ncases = #{kind.fetch(:cases).size} }"
        end
      end

      def integer_members(name, kind)
        values = kind[:values]&.map { |item| item.fetch(:value) }
        low = values&.min || kind.dig(:min, :value) || 0
        high = values&.max || kind.dig(:max, :value) || BASE_MAX.fetch(kind.fetch(:base))
        members = [".form = ERX_PROFILE_INTEGER", ".min = UINT64_C(#{low})", ".max = UINT64_C(#{high})"]
        members << ".values = #{name}_values, .nvalues = #{values.size}" if values
        members << ".except = UINT64_C(#{kind.dig(:except, :value)}), .has_except = true" if kind[:except]
        members << '.unique = true' if kind[:unique]
        members.join(",\n\t    ")
      end

      def text_members(kind)
        rules = { utf8: 'ERX_PROFILE_UTF8_RULE', assign: 'ERX_PROFILE_ASSIGN_RULE', path: 'ERX_PROFILE_PATH_RULE' }
                .select { |rule, _| kind.fetch(rule) }.values
        rules.insert(kind.fetch(:utf8) ? 1 : 0, 'ERX_PROFILE_NUL_RULE') if kind.fetch(:refuse).include?('nul')
        members = [".form = ERX_PROFILE_TEXT_FORM", ".text_max = #{kind.dig(:max, :value)}",
                   ".rules = #{rules.empty? ? '0' : rules.join(' | ')}"]
        members.join(",\n\t    ")
      end

      def names_table
        "/* The names a refusal gives: each kind's, then each total's, then each frame's. */\n" \
          "static const char *const names[] = {\n#{@names.map { |name| "\t\"#{name}\"," }.join("\n")}\n};\n"
      end

      def rules_tables
        refers = @protocol.fetch(:refers).map do |item|
          "\t{ .low = #{item.fetch(:low)}, .range = #{item.fetch(:range)}, .kind = #{index(item.fetch(:kind))}, " \
            ".list = #{index(item.fetch(:list))} },"
        end
        totals = @protocol.fetch(:totals).map do |total, max|
          "\t{ .max = #{max.fetch(:value)}, .name = #{@names.index(total)} },"
        end
        (refers.empty? ? '' : "static const erx_profile_refers_t refers[] = {\n#{refers.join("\n")}\n};\n") +
          (totals.empty? ? '' : "static const erx_profile_total_t totals[] = {\n#{totals.join("\n")}\n};\n")
      end

      def signals_table
        return '' unless @order.include?('signal')

        rows = @signals.map { |signal| "\t{ \"sig#{signal.name}\", #{signal.number} }," }
        "/* The signals a program may name, by their protocol names. */\n" \
          "static const erx_profile_signal_t signals[] = {\n#{rows.join("\n")}\n};\n"
      end

      def frames_table
        rows = @protocol.fetch(:frames).map do |frame|
          "\t{ .tag = \"#{frame.fetch(:tag)}\", .name = #{@names.index(frame.fetch(:name))}, " \
            ".kind = #{index(frame.fetch(:kind))}, .slot = #{frame.fetch(:slot)} },"
        end
        "static const erx_profile_frame_t frames[] = {\n#{rows.join("\n")}\n};\n"
      end

      def profile
        unique = @protocol.fetch(:unique) ? index(@protocol.fetch(:unique)) : 'ERX_PROFILE_NONE'
        count = ->(table, items) { items.empty? ? ['NULL', 0] : [table, items.size] }
        refers, nrefers = count.call('refers', @protocol.fetch(:refers))
        totals, ntotals = count.call('totals', @protocol.fetch(:totals).to_a)
        signals, nsignals = @order.include?('signal') ? ['signals', @signals.size] : ['NULL', 0]
        "const erx_profile_t #{prefix}_profile = {\n" \
          "\t.kinds = kinds, .names = names, .refers = #{refers}, .totals = #{totals},\n" \
          "\t.signals = #{signals}, .frames = frames, .version = #{@protocol.fetch(:version)},\n" \
          "\t.frame_max = #{@protocol.dig(:frame_max, :value)}, .nkinds = #{@order.size}, .nnames = #{@names.size},\n" \
          "\t.nrefers = #{nrefers}, .ntotals = #{ntotals}, .nsignals = #{nsignals},\n" \
          "\t.nframes = #{@protocol.fetch(:frames).size}, .slot_kind = #{@order.index('slot') || 'ERX_PROFILE_NONE'},\n" \
          "\t.unique_kind = #{unique}, .depth = #{@protocol.fetch(:depth)},\n};\n"
      end

      # Static asserts that the C check's fixed bounds (erx/profile.h) hold
      # this table: the model's depth and totals bounds are the header's, the
      # table's depth and totals are within them, each map's keys and each
      # union's cases fit a level's mask, and each list's iterator is its view
      # alone, which the check stores at the iterator's offset.
      def bounds
        model = Protocols::Profile
        masks = @kinds.filter_map do |name, kind|
          case kind.fetch(:form)
          when 'map' then "#{name}_fields"
          when 'union' then "#{name}_cases" unless kind.fetch(:cases).empty?
          end
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.keys
        ["#define\tNELEM(a)\t(sizeof(a) / sizeof((a)[0]))", '',
         assertion("ERX_PROFILE_DEPTH_MAX == #{model::DEPTH_MAX}", 'the generator bounds depth as erx/profile.h does'),
         assertion("ERX_PROFILE_TOTALS_MAX == #{model::TOTALS_MAX}", 'the generator bounds totals as erx/profile.h does'),
         assertion("#{@protocol.fetch(:depth)} <= ERX_PROFILE_DEPTH_MAX", "#{short}'s kinds nest within the check's stack"),
         *(@protocol.fetch(:totals).empty? ? [] : [assertion('NELEM(totals) <= ERX_PROFILE_TOTALS_MAX', "#{short}'s totals fit the check's sums")]),
         *masks.map { |table| assertion("NELEM(#{table}) <= ERX_PROFILE_KEYS_MAX", "#{table} fit a level's mask") },
         *lists.map do |name|
           type = c_type(name)
           assertion("offsetof(#{type}, view) == 0 &&\n    sizeof(#{type}) == sizeof(erx_profile_list_t)",
                     "#{type} is its view alone")
         end, ''].join("\n")
      end

      def assertion(condition, message) = "_Static_assert(#{condition},\n    \"#{message}\");"

      def functions
        frames = @protocol.fetch(:frames).each_with_index.map do |frame, position|
          slot = frame.fetch(:slot) ? 'uint8_t *slot, ' : ''
          "bool\n#{prefix}_check_#{frame.fetch(:name)}(const uint8_t *frame, size_t len, void *scratch,\n" \
            "    size_t scratch_len, #{slot}#{c_type(frame.fetch(:kind))} *#{frame.fetch(:name)}, erx_profile_refusal_t *refusal)\n{\n" \
            "\treturn (erx_profile_check(&#{prefix}_profile, #{position}, frame, len, scratch,\n" \
            "\t    scratch_len, #{frame.fetch(:slot) ? 'slot' : 'NULL'}, #{frame.fetch(:name)}, refusal));\n}\n"
        end
        lists = @kinds.select { |_, kind| kind.fetch(:form) == 'list' }.map do |name, kind|
          "bool\n#{prefix}_#{name}_next(#{c_type(name)} *it, #{c_type(kind.fetch(:element))} *element)\n{\n" \
            "\treturn (erx_profile_next(&#{prefix}_profile, #{index(name)}, &it->view, element));\n}\n"
        end
        ["size_t\n#{prefix}_scratch_bytes(size_t len)\n{\n\treturn (erx_profile_scratch_bytes(&#{prefix}_profile, len));\n}\n",
         *frames, *lists,
         "const char *\n#{prefix}_kind_name(uint16_t kind)\n{\n\treturn (erx_profile_name(&#{prefix}_profile, kind));\n}\n"].join("\n")
      end
    end
  end
end
