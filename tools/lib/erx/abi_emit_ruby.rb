# frozen_string_literal: true

require_relative 'abi_binary'

module Erx
  module ABI
    # Emit ordinary constructors for the already validated model. The host
    # binding reads no declaration files and evaluates no source text at load.
    class RubyEmitter
      def initialize(schema)
        @schema = schema
        @references = {}
        Model::BASE_TYPES.each_value do |type|
          @references[type.object_id] = "types.fetch(#{type.name.dump})"
        end
      end

      def emit
        out = [
          '# Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>',
          '# SPDX-License-Identifier: BSD-2-Clause',
          '# frozen_string_literal: true',
          '# Generated by tools/gen_abi.rb from abi/erx_abi.txt and its inputs.',
          '# Do not edit this file. Loaded through tools/lib/erx/generated_abi.rb,',
          '# which loads abi_binary.rb first.', '',
          'module Erx', '  module ABI', '    module Generated',
          '      # Source locations belong to generation diagnostics, not runtime bytes.',
          "      source_line = SourceLine.new(path: '<generated ABI>', number: 0,",
          '                                   indent: 0, tokens: [].freeze).freeze',
          '      types = Model::BASE_TYPES.dup'
        ]
        @schema.type_order.each do |name|
          type = @schema.types.fetch(name)
          expression = structure(type)
          out << indent("types[#{name.dump}] = #{expression}", 6)
          @references[type.object_id] = "types.fetch(#{name.dump})"
          if type.is_a?(Layout)
            type.fields.each_with_index do |field, index|
              @references[field.object_id] = "types.fetch(#{name.dump}).fields.fetch(#{index})"
            end
          end
        end
        # The inspection schema has its own table, tools/generated/abi_inspection.rb.
        attributes = @schema.each_pair.to_h.reject { |name, _value| %i[types inputs inspection].include?(name) }
        rendered = attributes.map { |key, item| "#{key}: #{value(item)}" }
        rendered << 'types: types.freeze'
        rendered << 'inputs: {}.freeze'
        out << indent('SCHEMA = Model.freeze_value(Schema.new(' + "\n" +
                      rendered.map { |item| indent(item, 2) }.join(",\n") + "\n))", 6)
        out << '      CODEC = Codec.new(SCHEMA)'
        out.concat(['', '      module_function', '',
                    '      def constant(name)', '        CODEC.constant(name)', '      end', '',
                    '      def fixed_bytes(name)', '        CODEC.fixed_bytes(name)', '      end', '',
                    '      def encode_layout(name, values)', '        CODEC.encode_layout(name, values)', '      end', '',
                    '      def decode_layout(name, bytes, offset: 0, prefix: false)',
                    '        CODEC.decode_layout(name, bytes, offset: offset, prefix: prefix)', '      end', '',
                    '      def open(name, bytes)', '        CODEC.open(name, bytes)', '      end',
                    '    end', '  end', 'end', ''])
        out.join("\n")
      end

      private

      def indent(text, amount)
        text.lines.map { |line| ' ' * amount + line }.join.chomp
      end

      def structure(object)
        name = object.class.name.delete_prefix('Erx::ABI::')
        fields = object.each_pair.to_h
        fields[:tokens] = [] if object.is_a?(SourceLine)
        members = fields.map { |key, item| "#{key}: #{value(item)}" }
        "#{name}.new(\n" + members.map { |item| indent(item, 2) }.join(",\n") + "\n).freeze"
      end

      def value(object)
        return 'source_line' if object.is_a?(SourceLine)
        reference = @references[object.object_id]
        return reference if reference
        case object
        when String
          object.dump + (object.encoding == Encoding::BINARY ? '.b' : '')
        when Symbol, Integer, TrueClass, FalseClass, NilClass
          object.inspect
        when Struct
          structure(object)
        when Array
          return '[].freeze' if object.empty?
          entries = object.map { |item| value(item) }
          compact = '[' + entries.join(', ') + '].freeze'
          return compact if !compact.include?("\n") && compact.bytesize <= 72
          "[\n" + entries.map { |item| indent(item, 2) }.join(",\n") + "\n].freeze"
        when Hash
          return '{}.freeze' if object.empty?
          "{\n" + object.map { |key, item| indent("#{value(key)} => #{value(item)}", 2) }.join(",\n") + "\n}.freeze"
        else
          raise SchemaError, "cannot emit Ruby model value #{object.class}"
        end
      end
    end
  end
end
