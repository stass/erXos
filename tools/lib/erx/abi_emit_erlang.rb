module Erx
  module ABI
    # The Erlang module contains a readable, closed schema and one bounded
    # decoder. All atoms originate in these checked declarations, never bytes
    # supplied to a target reader. Views retain the immutable input binary.
    module ErlangEmitter
      Atom = Struct.new(:name)
      NOTICE = <<~ERLANG.freeze
        %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
        %% SPDX-License-Identifier: BSD-2-Clause
        %% Generated by tools/gen_abi.rb from abi/erx_abi.txt and its inputs.
        %% Do not edit this file.
      ERLANG
      # erx_abi_termios's module doc and its fixed code, which reads the
      # table through bits/1, sizes/0 and indices/0 and the macros the
      # emitter writes. The table's words are Termios::WORDS, a closed set.
      TERMIOS_DOC = <<~'ERLANG'.chomp.freeze
        -moduledoc """
        The termios table of the ABI file (abi/termios.txt): the flags and special
        characters a tty's termios may hold, the types of erx_tty's termios map, and
        the codec between that map and a C program's struct termios, whose words,
        bits and c_cc indices are FreeBSD's (sys/sys/_termios.h).
        """.
        -export([flags/1, chars/0, decode/1, encode/1]).
      ERLANG
      TERMIOS_CODE = <<~'ERLANG'.freeze
        flags(Word) -> [Flag || {Flag, _} <- bits(Word)].

        -doc "The special characters, in name order.".
        -spec chars() -> [char_name()].
        chars() -> [Name || {Name, _} <- indices()].

        -doc """
        The termios of a C program's struct termios. Each flag, size and
        character is read from its bits or index, and a bit or byte the table
        does not name is dropped, as FreeBSD's tcsetattr drops the bits it does
        not support (sys/kern/tty.c:1760-1764). Anything but four 32-bit words,
        ?NCCS bytes and two 32-bit speeds fails with einval.
        """.
        -spec decode(term()) -> {ok, termios()} | {error, einval}.
        decode(#{iflag := I, oflag := O, cflag := C, lflag := L, cc := Cc,
                 ispeed := ISpeed, ospeed := OSpeed} = Struct)
          when map_size(Struct) =:= 7, is_list(Cc), length(Cc) =:= ?NCCS ->
            Words = #{iflag => I, oflag => O, cflag => C, lflag => L},
            case lists:all(fun is_word/1, [ISpeed, OSpeed | maps:values(Words)])
                andalso lists:all(fun is_byte/1, Cc) of
                true ->
                    Bytes = list_to_tuple(Cc),
                    Flags = #{Word => [Flag || {Flag, Bit} <- bits(Word), Value band Bit =/= 0]
                              || Word := Value <- Words},
                    Sizes = #{Name => First + ((map_get(Word, Words) band Mask) bsr Shift)
                              || {Word, Name, Mask, Shift, First} <- sizes()},
                    Chars = #{Name => element(Index + 1, Bytes) || {Name, Index} <- indices()},
                    {ok, (maps:merge(Flags, Sizes))#{cc => Chars, ispeed => ISpeed, ospeed => OSpeed}};
                false ->
                    {error, einval}
            end;
        decode(_) ->
            {error, einval}.

        -doc """
        The struct termios of a termios: each flag's bit and each size's bits in
        its word, each character at its index, and ?UNNAMED in every byte of
        c_cc that the table names no character for.
        """.
        -spec encode(termios()) -> c_termios().
        encode(#{cc := Chars, ispeed := ISpeed, ospeed := OSpeed} = Termios) ->
            Flags = #{Word => lists:sum([Bit || {Flag, Bit} <- bits(Word),
                                                lists:member(Flag, map_get(Word, Termios))])
                      || Word <- ?WORDS},
            Words = lists:foldl(fun({Word, Name, _Mask, Shift, First}, Acc) ->
                                        Bits = (map_get(Name, Termios) - First) bsl Shift,
                                        Acc#{Word := map_get(Word, Acc) bor Bits}
                                end, Flags, sizes()),
            Indexed = #{Index => map_get(Name, Chars) || {Name, Index} <- indices()},
            Words#{cc => [maps:get(Index, Indexed, ?UNNAMED) || Index <- lists:seq(0, ?NCCS - 1)],
                   ispeed => ISpeed, ospeed => OSpeed}.

        is_word(Value) -> is_integer(Value) andalso Value >= 0 andalso Value =< ?WORD_MAX.

        is_byte(Value) -> is_integer(Value) andalso Value >= 0 andalso Value =< 16#ff.
      ERLANG
      SUPPORTED_RULES =%w[value range index slice partition string optional choice].freeze
      # Erlang's reserved words and the function every module defines: no
      # generated function takes one of these names unquoted.
      RESERVED_FUNCTIONS = %w[after and andalso band begin bnot bor bsl bsr bxor case catch cond div else end
                              fun if let maybe not of or orelse receive rem try when xor module_info].freeze

      module_function

      def outputs(schema)
        result = { 'erlang/apps/erx/include/generated/erx_abi.hrl' => header(schema),
                   'erlang/apps/erx/src/generated/erx_abi_enums.erl' => enums(schema),
                   'erlang/apps/erx/src/generated/erx_abi_events.erl' => events(schema),
                   'erlang/apps/erx/src/generated/erx_abi_errno.erl' => errnos(schema),
                   'erlang/apps/erx/src/generated/erx_abi_signals.erl' => signals(schema),
                   'erlang/apps/erx/src/generated/erx_abi_translations.erl' => translations(schema) }
        # Beside erx_prog_grammar, the program protocol's other generated module.
        result['otp/erts/preloaded/src/erx_prog.erl'] = program_status(schema) if schema.faults&.any?
        result['erlang/apps/erx/src/generated/erx_abi_termios.erl'] = termios(schema.termios) if schema.termios
        schema.readers.each do |specification|
          module_name = Names.c(specification.name)
          unless module_name.match?(/\Aerx_[a-z][a-z0-9_]*\z/) && module_name.bytesize <= 255
            raise SchemaError, 'reader has no supported Erlang module name'
          end
          path = "erlang/apps/erx/src/generated/#{module_name}.erl"
          raise SchemaError, "reader module #{module_name} collides with a generated module" if result.key?(path)
          result[path] = reader(schema, specification)
        end
        result.freeze
      end

      def header(schema)
        lines = [NOTICE, '-ifndef(ERX_ABI_HRL).', '-define(ERX_ABI_HRL, true).', '']
        schema.constants.each_value do |constant|
          lines << "-define(#{Names.macro(constant.name)}, #{constant.value})."
        end
        schema.type_order.each do |name|
          type = schema.types.fetch(name)
          if type.is_a?(Layout)
            prefix = Names.macro(type.name)
            lines << "-define(#{prefix}_SIZE, #{type.size})."
            lines << "-define(#{prefix}_ALIGN, #{type.alignment})."
            # A private layout's offsets and sequence are the kernel's alone.
            next if type.private?

            type.fields.each do |field|
              lines << "-define(#{prefix}_OFF_#{field.name.upcase}, #{field.offset})."
            end
            if type.sequence
              sequence = type.sequence
              field = type.fetch_field(sequence.fetch(:field))
              status_name = 'e' + sequence.fetch(:exhaustion).delete_prefix('@')
              status = schema.constants.fetch(status_name)
              sequence_prefix = "#{prefix}_#{field.name.upcase}"
              lines << "-define(#{sequence_prefix}_TERMINAL, #{sequence.fetch(:terminal)})."
              lines << "-define(#{sequence_prefix}_EXHAUSTION, ?#{Names.macro(status.name)})."
            end
          elsif type.is_a?(BytesType)
            prefix = Names.macro(type.name)
            lines << "-define(#{prefix}_SIZE, #{type.size})."
            lines << "-define(#{prefix}_BYTES, #{literal(type.fixed)})." if type.fixed
          elsif type.is_a?(EnumType) && !type.flags
            lines << enum_members(schema, type) << enum_guard(type)
          end
        end
        schema.signals.sets.sort.each { |name, signals| lines << signal_set_members(schema, name, signals) }
        lines << tree_services(schema)
        lines << session_lines(schema) << drive_grants(schema)
        (lines + ['', '-endif.', '']).join("\n")
      end

      # ?ERX_<SET>_SIGNAL_MEMBERS: a signal set of the signal table as
      # {Name, Number} in number order, each by its protocol name (sigint), so
      # a protocol that carries only those signals takes them from the table.
      def signal_set_members(schema, set, signals)
        name = "#{set}_signal_members"
        raise SchemaError, "signal set member list #{name} collides with a constant" if schema.constants.key?(name)
        raise SchemaError, "signal set #{set} collides with the enum #{set}_signal" if schema.types.key?("#{set}_signal")

        members = signals.map { |signal| "{#{literal(atom("sig#{signal.name}"))}, #{signal.number}}" }
        "-define(#{Names.macro(name)}, [#{members.join(', ')}])."
      end

      # ?ERX_TREE_SERVICES: the numbers of the abi/services interfaces declared
      # served_as tree, whose grants are erx_fs grants of one tree, in number order,
      # so the domain service tells them from message services by the ABI alone.
      def tree_services(schema)
        raise SchemaError, 'tree_services collides with a constant' if schema.constants.key?('tree_services')

        numbers = schema.services.select { |service| service.fetch(:served_as) == 'tree' }
                        .map { |service| service.fetch(:number) }.sort
        "-define(ERX_TREE_SERVICES, [#{numbers.join(', ')}])."
      end

      # ?ERX_LINES: each abi/services interface declared served_by session, a session's
      # line, by its name, to its grant's quantities (docs/design-system.md, "A session's
      # lines"), so the domain service mints a line within the limits its interface states.
      def session_lines(schema)
        raise SchemaError, 'lines collides with a constant' if schema.constants.key?('lines')

        unrowed_grants('ERX_LINES', schema.session_lines) { |service| service.fetch(:quantities) }
      end

      # ?ERX_DRIVE_GRANTS: each abi/services interface declared served_by drive, by its name,
      # to the limits every grant of it carries, its operations by name and its quantities
      # (docs/design-system.md, "A drive window as a grant"), so the domain service mints
      # each drive window row's grant within the limits its interface states.
      def drive_grants(schema)
        raise SchemaError, 'drive_grants collides with a constant' if schema.constants.key?('drive_grants')

        unrowed_grants('ERX_DRIVE_GRANTS', schema.drive_grants) do |service|
          service.fetch(:quantities).merge('operations' => "[#{service.fetch(:operations).sort_by { |_, id| id }
                                                                 .map { |name, _| literal(atom(name)) }.join(', ')}]")
        end
      end

      # A map macro from each of services' names to the limits the block gives it, sorted.
      def unrowed_grants(macro, services)
        entries = services.sort_by { |service| service.fetch(:name) }.map do |service|
          limits = yield(service).sort.map { |key, value| "#{key} => #{value}" }
          "#{literal(atom(service.fetch(:name)))} =>\n        \#{#{limits.join(', ')}}"
        end
        return "-define(#{macro}, \#{})." if entries.empty?

        "-define(#{macro}, \#{\n    #{entries.join(",\n    ")}\n})."
      end

      # ?ERX_<ENUM>_MEMBERS: an enum's members as {Name, Value} in value order,
      # so code that walks the whole set, such as a file tree's list of files,
      # takes it from the ABI file instead of copying the names.
      def enum_members(schema, type)
        name = "#{type.name}_members"
        raise SchemaError, "enum member list #{name} collides with a constant" if schema.constants.key?(name)

        members = type.members.sort_by { |_member, value| value }
                      .map { |member, value| "{#{literal(atom(member))}, #{value}}" }
        compact = "-define(#{Names.macro(name)}, [#{members.join(', ')}])."
        return compact if compact.bytesize <= 80

        "-define(#{Names.macro(name)}, [\n    #{members.join(",\n    ")}\n])."
      end

      # ?ERX_IS_<ENUM>(Term): a guard test true exactly when Term is one of
      # the enum's member names, so a clause head admits the members without
      # spelling them. A guard has no side effects, so Term repeats freely.
      def enum_guard(type)
        macro = Names.macro("is_#{type.name}")
        tests = member_names(type).map { |member| "(Term) =:= #{literal(atom(member))}" }
        compact = "-define(#{macro}(Term), (#{tests.join(' orelse ')}))."
        return compact if compact.bytesize <= 100

        "-define(#{macro}(Term),\n        (#{tests.join("\n         orelse ")}))."
      end

      # One attribute of one enum, as erx_abi_enums names its predicate.
      Predicate = Data.define(:type, :attribute) do
        def function = "#{type.name}_#{attribute}"
        def holders = type.attributes.fetch(attribute)
      end

      # erx_abi_enums: each enum of the ABI file as the type of its member
      # names and each flags type as the type of an ordset of its bit names;
      # name/2 and value/2, the one translation between a type's integers and
      # those names (docs/design-abi.md, "Layouts in Erlang"); and each
      # attribute an enum declares as a predicate ENUM_ATTRIBUTE/1, true for
      # the members that carry it and false for the others, with no clause for
      # a name that is no member. A type named as an Erlang built-in type
      # would fail erlc; none is.
      def enums(schema)
        coded = schema.type_order.map { |name| schema.types.fetch(name) }.grep(EnumType)
        types = coded.reject(&:flags)
        flags = coded.select(&:flags)
        predicates = types.flat_map { |type| type.attributes.keys.map { |attribute| Predicate.new(type:, attribute:) } }
        duplicate, = predicates.map(&:function).tally.find { |_function, count| count > 1 }
        raise SchemaError, "enum attribute predicate #{duplicate} is named twice" if duplicate

        [NOTICE, '-module(erx_abi_enums).',
         '-moduledoc "The ABI file\'s enum and flags types, their integers and their attributes.".',
         form_list('export', ['name/2', 'value/2',
                              *predicates.map { |predicate| "#{literal(atom(predicate.function))}/1" }]),
         form_list('export_type', ['type/0', *coded.map { |type| "#{literal(atom(type.name))}/0" }]), '',
         *types.map { |type| enum_type(type) },
         *flags.map { |type| flags_type(type) }, '',
         coded_type(coded), '',
         name_function(coded), '',
         value_function(coded), '',
         *(flags.empty? ? [] : [FLAGS_HELPERS]),
         *(flags.any?(&:allowed) ? [ALLOWED_HELPER] : []),
         *predicates.flat_map { |predicate| ['', attribute_predicate(predicate)] }, ''].join("\n")
      end

      # A flags type: an ordset of its bit names, which sort as their atoms do.
      def flags_type(type)
        head = "-type #{literal(atom(type.name))}() ::"
        names = flag_names(type).map { |name| literal(atom(name)) }
        compact = "#{head} [#{names.join(' | ')}]."
        return compact if compact.bytesize <= 100

        "#{head}\n      [#{names.join("\n     | ")}]."
      end

      def flag_names(type) = type.members.keys.sort

      # Each bit of a flags type as {Name, Mask}, in name order, on one line
      # or one to a line.
      def flag_bits(type)
        bits = flag_names(type).map { |name| "{#{literal(atom(name))}, #{type.members.fetch(name)}}" }
        compact = "[#{bits.join(', ')}]"
        compact.bytesize <= 60 ? compact : "[#{bits.join(",\n          ")}]"
      end

      def coded_type(coded)
        "-doc \"An enum or flags type of the ABI file, by its name.\".\n" \
          "-type type() ::\n    #{coded.map { |type| literal(atom(type.name)) }.join("\n  | ")}."
      end

      # The guard that admits a flags value: its bits all declared, and when
      # the type has an allow line, one of the combinations it lists.
      def flags_guard(type)
        return type.allowed.map { |value| "Value =:= #{value}" }.join(' orelse ') if type.allowed

        "is_integer(Value), Value band bnot #{type.mask} =:= 0"
      end

      def name_function(coded)
        clauses = coded.flat_map do |type|
          head = "name(#{literal(atom(type.name))}, "
          known = if type.flags
                    ["#{head}Value) when #{flags_guard(type)} ->\n    {ok, bits(Value, #{flag_bits(type)})}"]
                  else
                    member_names(type).map { |member| "#{head}#{type.members.fetch(member)}) -> {ok, #{literal(atom(member))}}" }
                  end
          known + ["#{head}_) -> error"]
        end
        <<~ERLANG.chomp
          -doc """
          The name of a value of an enum or flags type: an enum member's atom, or
          the ordset of a flags value's bit names; error for any other value, an
          integer that no member holds, a flags value with a bit its type does
          not declare, or a combination its allow line does not list. A type the
          ABI file does not declare is a function_clause error.
          """.
          -spec name(type(), term()) -> {ok, atom() | [atom()]} | error.
          #{clauses.join(";\n")}.
        ERLANG
      end

      def value_function(coded)
        clauses = coded.flat_map do |type|
          head = "value(#{literal(atom(type.name))}, "
          if type.flags
            mask = "mask(Names, #{flag_bits(type)})"
            ["#{head}Names) ->\n    #{type.allowed ? "allowed(#{mask}, #{type.allowed})" : mask}"]
          else
            member_names(type).map { |member| "#{head}#{literal(atom(member))}) -> #{type.members.fetch(member)}" }
          end
        end
        <<~ERLANG.chomp
          -doc """
          The integer of a name of an enum or flags type, the inverse of name/2:
          a name that is no member, a bit name the type does not declare, or a
          combination its allow line does not list is an error.
          """.
          -spec value(type(), atom() | [atom()]) -> integer().
          #{clauses.join(";\n")}.
        ERLANG
      end

      FLAGS_HELPERS = <<~ERLANG
        %% A flags value's bit names, in the order Bits gives them.
        bits(Value, Bits) ->
            [Name || {Name, Mask} <- Bits, Value band Mask =/= 0].

        %% The flags value of bit names, each one of Bits; any other is a badmatch.
        mask(Names, Bits) ->
            lists:foldl(fun(Name, Value) ->
                                {Name, Mask} = lists:keyfind(Name, 1, Bits),
                                Value bor Mask
                        end, 0, Names).
      ERLANG

      ALLOWED_HELPER = <<~ERLANG
        %% A flags value that is one of its type's allowed combinations.
        allowed(Value, Allowed) ->
            true = lists:member(Value, Allowed),
            Value.
      ERLANG

      # -NAME([ITEM, ...]). on one line, or one item to a line.
      def form_list(name, items)
        compact = "-#{name}([#{items.join(', ')}])."
        return compact if compact.bytesize <= 100

        "-#{name}([\n    #{items.join(",\n    ")}\n])."
      end

      # An enum's type, its member names on one line or one to a line.
      def enum_type(type)
        head = "-type #{literal(atom(type.name))}() ::"
        names = member_names(type).map { |member| literal(atom(member)) }
        compact = "#{head} #{names.join(' | ')}."
        return compact if compact.bytesize <= 100

        "#{head}\n      #{names.join("\n    | ")}."
      end

      # One clause per member, so a name that is no member fails to match.
      def attribute_predicate(predicate)
        head = literal(atom(predicate.function))
        clauses = member_names(predicate.type).map do |member|
          "#{head}(#{literal(atom(member))}) -> #{predicate.holders.include?(member)}"
        end
        ["-spec #{head}(#{literal(atom(predicate.type.name))}()) -> boolean().", clauses.join(";\n") + '.'].join("\n")
      end

      # An enum's member names in value order, the order its other outputs use.
      def member_names(type) = type.members.sort_by { |_member, value| value }.map(&:first)

      # erx_abi_events:describe(Enum, Value): for each enum with args
      # lines, its member numbered Value as {Name, [{ArgName, Type}]}, or
      # unknown for a value the enum does not hold. status(Value) names a
      # status argument, and flags(Flags) gives each bit of a flags type a
      # layout binds, so a reader of a record decodes no word by hand.
      def events(schema)
        enums = schema.event_enums
        enum_type = enums.empty? ? 'atom()' : enums.map { |type| literal(atom(type.name)) }.join(' | ')
        clauses = enums.flat_map do |type|
          enum = literal(atom(type.name))
          type.members.sort_by { |_member, value| value }.map do |member, value|
            arguments = type.args.fetch(member, []).map do |argument|
              "{#{literal(atom(argument.name))}, #{literal(atom(argument.type))}}"
            end
            "describe(#{enum}, #{value}) -> {#{literal(atom(member))}, [#{arguments.join(', ')}]}"
          end + ["describe(#{enum}, _Value) -> unknown"]
        end
        clauses = ['describe(_Enum, _Value) -> unknown'] if enums.empty?
        argument_type = Model::EVENT_ARGUMENT_TYPES.map { |type| literal(atom(type)) }.join(' | ')
        [NOTICE, '-module(erx_abi_events).',
         '-moduledoc "The events of the ABI file\'s enums with args lines and their typed arguments.".',
         '-export([describe/2, status/1, flags/1]).', '-export_type([argument_type/0]).', '',
         '%% An arg word read as an unsigned or signed 64-bit integer, or as a status.',
         "-type argument_type() :: #{argument_type}.", '',
         "-spec describe(#{enum_type}, integer()) ->",
         '    {atom(), [{atom(), argument_type()}]} | unknown.',
         clauses.join(";\n") + '.', '', status_function(schema), '', flags_function(schema), ''].join("\n")
      end

      # erx_abi_signals: each signal a program may name, by its protocol
      # name (sig and its name, sigint or 'sigrtmin+1'), with its number and
      # default action. Reserved numbers are the C library's and have no
      # protocol name.
      def signals(schema)
        nameable = schema.signals.signals.select(&:nameable?)
        name = ->(signal) { atom("sig#{signal.name}") }
        actions = Signals::ACTIONS.keys - %w[none reserved]
        [NOTICE, '-module(erx_abi_signals).',
         '-moduledoc "The signal table of the ABI file: each signal a program may name, its number and ' \
         'its default action.".',
         '-export([number/1, name/1, default_action/1]).', '-export_type([action/0]).', '',
         "-type action() :: #{actions.map { |action| literal(atom(action)) }.join(' | ')}.", '',
         '%% The number of a signal, or unknown for an atom that names none.',
         '-spec number(atom()) -> pos_integer() | unknown.',
         lookup('number', nameable.map { |signal| [name.call(signal), signal.number] }), '',
         '%% The name of a signal number, or unknown for a number that is no signal a program may name.',
         '-spec name(integer()) -> atom() | unknown.',
         lookup('name', nameable.map { |signal| [signal.number, name.call(signal)] }), '',
         '%% The default action of a signal, or unknown for an atom that names none.',
         '-spec default_action(atom()) -> action() | unknown.',
         lookup('default_action', nameable.map { |signal| [name.call(signal), atom(signal.action)] }), '']
          .join("\n")
      end

      # erx_abi_errno: each errno of the table by its protocol name (einval)
      # with its number, and each number with that name. An alias is a C
      # name only, so one error has one atom and no alias is a protocol name.
      def errnos(schema)
        table = schema.errnos
        named = table.errnos.map { |entry| [atom(entry.name), entry.number] }
        [NOTICE, '-module(erx_abi_errno).',
         '-moduledoc "The errno table of the ABI file: each error name a reply may carry and its number.".',
         '-export([number/1, name/1]).', '',
         '%% The number of an errno name, or unknown for an atom that names none.',
         '-spec number(atom()) -> pos_integer() | unknown.',
         lookup('number', named), '',
         '%% The name of an errno number, or unknown for a number the table does not list.',
         '-spec name(integer()) -> atom() | unknown.',
         lookup('name', table.errnos.map { |entry| [entry.number, atom(entry.name)] }), '']
          .join("\n")
      end

      # The clauses of a generated lookup function: one per key, then unknown.
      def lookup(function, pairs)
        (pairs.map { |key, value| "#{function}(#{literal(key)}) -> #{literal(value)}" } +
         ["#{function}(_) -> unknown"]).join(";\n") + '.'
      end

      # erx_abi_termios: the termios table's flags and characters, the types
      # of erx_tty's termios map, and the codec between that map and a C
      # program's struct termios (docs/design-live.md, "The tty"). The code
      # is fixed; only the types and the three table functions vary.
      def termios(table)
        hex = ->(value) { format('16#%08x', value) }
        list = ->(rows) { "[#{rows.join(",\n     ")}]" }
        # A type of atoms, five to a line.
        union = lambda do |type, names|
          head = "-type #{type}() :: "
          atoms = names.empty? ? ['none()'] : names.map { |name| literal(atom(name)) }
          "#{head}#{atoms.each_slice(5).map { |slice| slice.join(' | ') }.join(" |\n#{' ' * head.size}")}."
        end
        map_type = lambda do |type, keys|
          head = "-type #{type}() :: \#{"
          "#{head}#{keys.join(",\n#{' ' * head.size}")}}."
        end
        bits = table.words.map do |word|
          "bits(#{word.name}) ->\n    #{list.call(word.flags.map { |flag| "{#{literal(atom(flag.name))}, #{hex.call(flag.bit)}}" })}"
        end
        sizes = table.words.flat_map do |word|
          word.sizes.map do |size|
            "{#{word.name}, #{literal(atom(size.name))}, #{hex.call(size.mask)}, #{size.shift}, #{size.first}}"
          end
        end
        indices = table.chars.map { |char| "{#{literal(atom(char.name))}, #{char.index}}" }
        speeds = ['ispeed := speed()', 'ospeed := speed()']
        termios_keys = [*table.words.map { |word| "#{word.name} := [#{word.name}()]" },
                        *table.words.flat_map(&:sizes).map { |size| "#{size.name} := #{size.first}..#{size.last}" },
                        "cc := \#{char_name() => byte()}", *speeds]
        struct_keys = [*table.words.map { |word| "#{word.name} := word()" }, 'cc := [byte()]', *speeds]
        word_names = table.words.map(&:name)
        [NOTICE, '-module(erx_abi_termios).', TERMIOS_DOC,
         "-export_type([termios/0, c_termios/0, #{word_names.map { |word| "#{word}/0" }.join(', ')}, " \
         'char_name/0, speed/0]).', '',
         "-define(WORD_MAX, #{hex.call(Termios::WORD_MASK)}).",
         "-define(NCCS, #{table.count}).",
         '%% What c_cc holds where the table names no character.',
         "-define(UNNAMED, #{format('16#%02x', table.unnamed)}).",
         "-define(WORDS, [#{word_names.join(', ')}]).", '',
         '-type word() :: 0..?WORD_MAX.', '-type speed() :: 0..?WORD_MAX.',
         *table.words.map { |word| union.call(word.name, word.flags.map(&:name)) },
         union.call('char_name', table.chars.map(&:name)),
         map_type.call('termios', termios_keys),
         '-doc "A C program\'s struct termios: its words, c_cc\'s bytes in index order and the two speeds.".',
         map_type.call('c_termios', struct_keys), '',
         '-doc "The flags a word of termios may hold, in name order.".',
         "-spec flags(#{word_names.map { |word| "#{word}) -> [#{word}()]" }.join('; (')}.",
         TERMIOS_CODE,
         '%% Each flag of a word and its bit, in name order.',
         "#{bits.join(";\n")}.", '',
         '%% Each field of contiguous bits: its word, name, mask, the shift of its',
         '%% lowest bit, and the value its bits read as when 0.',
         "sizes() ->\n    #{list.call(sizes)}.", '',
         '%% Each special character and its index in c_cc, in name order.',
         "indices() ->\n    #{list.call(indices)}.", ''].join("\n")
      end

      # erx_abi_translations: for each translation a function of its name
      # that takes a source value and gives its target member's value, or
      # none for a value with no target, so HID's usage map
      # (abi/formats/hid.txt) is read from the ABI file and never copied. A
      # function takes any term, since a device's report supplies the value,
      # and gives none for every term it does not map; none, not the unknown
      # of erx_abi_signals, because the value is known and has no target.
      def translations(schema)
        functions = schema.translations.map do |translation|
          unless translation.name.match?(/\A[a-z][a-z0-9_]*\z/) && !RESERVED_FUNCTIONS.include?(translation.name)
            raise SchemaError, "translation #{translation.name} cannot name an Erlang function"
          end
          target = schema.types.fetch(translation.target)
          clauses = translation.map.map do |value, member|
            "#{translation.name}(#{value}) -> #{target.members.fetch(member)}; % #{member}"
          end
          ["%% #{translation.name}: a #{translation.source} value's #{translation.target} code, or none.",
           "-spec #{translation.name}(term()) -> integer() | none.",
           *clauses, "#{translation.name}(_) -> none.", '']
        end
        exports = schema.translations.map { |translation| "#{translation.name}/1" }
        [NOTICE, '-module(erx_abi_translations).',
         '-moduledoc "The translations of the ABI file, each a function from a source value to its target\'s value.".',
         "-export([#{exports.join(', ')}]).", '', *functions.flatten].join("\n")
      end

      # erx_prog: status/1, the one reading of a program's end
      # (docs/design-programs.md, "A program's end"). Its clauses come from
      # the signal table, the fault table and exit_kind's signal and parent,
      # which the model has checked (Signals.faults); the two catch-all
      # clauses take every other status and fault record.
      def program_status(schema)
        value = ->(name) { schema.constants.fetch(name).value }
        signal_atom = ->(signal) { literal(atom("sig#{signal.name}")) }
        nameable = schema.signals.signals.select(&:nameable?)
        kill = nameable.find { |signal| signal.name == 'kill' }
        fault_clauses = schema.faults.map do |row|
          "%% fault_kind #{row.kind}.\nstatus({fault, #{row.value}}) -> {signaled, #{signal_atom.call(row.signal)}}"
        end
        clauses = ['status(Status) when is_integer(Status), Status >= 0, Status =< 255 -> {exited, Status}',
                   "status(Status) when is_integer(Status), Status > ?EXIT_SIGNAL, Status =< ?EXIT_SIGNAL + 255 ->\n" \
                   '    signaled(Status - ?EXIT_SIGNAL)',
                   "status(?EXIT_PARENT) -> {signaled, #{signal_atom.call(kill)}}", *fault_clauses,
                   'status(Status) when is_integer(Status) -> {exited, 255}',
                   'status({fault, Kind}) when is_integer(Kind) -> {exited, 255}']
        # A function of its own whose clauses are small integers only: the
        # host tests run this module on stock OTP 29.1.2, whose JIT faults on
        # a jump table that shares its select with a bignum such as
        # ERX_EXIT_PARENT when the argument falls in a gap (erXos's copy makes
        # no such jump table: otp/erts/emulator/beam/jit/arm/ops.tab).
        signaled = [*nameable.map { |signal| "signaled(#{signal.number}) -> {signaled, #{signal_atom.call(signal)}}" },
                    'signaled(_) -> {exited, 255}']
        [NOTICE, '-module(erx_prog).',
         %(-moduledoc "The reading of a program's end: the status its parent's wait and rc's $status see".),
         '-export([status/1]).', '-export_type([status/0]).', '',
         "-define(EXIT_SIGNAL, #{value.call('exit_signal')}). % ERX_EXIT_SIGNAL",
         "-define(EXIT_PARENT, #{value.call('exit_parent')}). % ERX_EXIT_PARENT", '',
         '-type status() :: {exited, 0..255} | {signaled, atom()}.', '',
         "%% The status of a program's end, read from the exit status its space",
         '%% stopped with or from the kind of a fault record of one of its threads.',
         '%% A halt 0 to 255 is exited with it. ERX_EXIT_SIGNAL plus a signal a',
         "%% program may name, the stop of its parent's end and each fault kind are",
         "%% signaled. Every other status, the kernel's nothread among them, and a",
         '%% fault record of no fault kind are exited 255.',
         '-spec status(integer() | {fault, integer()}) -> status().',
         clauses.join(";\n") + '.', '',
         '%% The end by signal N, or exited 255 for an N that is no signal a program may name.',
         signaled.join(";\n") + '.', ''].join("\n")
      end

      def status_function(schema)
        clauses = (schema.statuses || {}).map { |name, value| "status(#{value}) -> #{literal(atom(name))}" }
        ['%% The name of a status value, or unknown for a value no status holds.',
         '-spec status(integer()) -> atom() | unknown.',
         (clauses + ['status(_Value) -> unknown']).join(";\n") + '.'].join("\n")
      end

      # The flags types a layout's names lines bind, each bit with its mask.
      def flags_function(schema)
        bound = schema.types.values.grep(Layout).flat_map { |layout| (layout.bindings || {}).values.map(&:type) }
        flags = schema.type_order.select { |name| bound.include?(name) }.map { |name| schema.types.fetch(name) }
                      .select(&:flags)
        clauses = flags.map do |type|
          bits = type.members.sort_by { |_name, mask| mask }.map { |name, mask| "{#{literal(atom(name))}, #{mask}}" }
          "flags(#{literal(atom(type.name))}) -> [#{bits.join(', ')}]"
        end
        ['%% Each bit of a flags type a layout binds, as {Name, Mask}; [] for any other.',
         '-spec flags(atom()) -> [{atom(), pos_integer()}].',
         (clauses + ['flags(_Flags) -> []']).join(";\n") + '.'].join("\n")
      end

      def reader(schema, specification)
        unless specification.root.is_a?(Layout) && specification.root.storage == 'wire_le' && !specification.root.tail
          raise SchemaError, 'Erlang reader requires a fixed wire root'
        end
        unknown = specification.rules.map { |rule| rule.fetch(:kind) }.uniq - SUPPORTED_RULES
        raise SchemaError, "unsupported Erlang reader rules: #{unknown.join(', ')}" unless unknown.empty?
        types = reachable_types(specification)
        types.each_value do |type|
          next unless type.is_a?(Layout)
          raise SchemaError, 'Erlang reader cannot embed a variable layout' if type.tail
          if type.fields.any? { |field| field.array? && field.type.is_a?(Layout) }
            raise SchemaError, 'Erlang reader does not support nested record arrays'
          end
        end
        module_name = Names.c(specification.name)
        prefix_export = specification.extent ? ['-export([open_prefix/1]).'] : []
        readable = spans(specification)
        accessors = %w[read/1 open/1 header/1 count/2 fetch/3] + (readable.empty? ? [] : ['span/4']) +
                    %w[string/2 fold/4 fuzz/1]
        lines = [NOTICE, "-module(#{module_name}).",
                 '-moduledoc "Bounded structural reader over immutable ABI bytes; policy admission is separate.".',
                 "-export([#{accessors.join(', ')}]).",
                 *prefix_export,
                 '-export_type([view/0, error/0]).', '',
                 '-record(view, {schema = ?MODULE :: module(), bytes :: binary()}).',
                 '-opaque view() :: #view{}.',
                 '-type error() :: #{reason := atom(), field := binary(), offset := non_neg_integer()}.', '']
        named_types = types.values.reject { |type| type.is_a?(IntegerType) }.sort_by(&:name)
        unless named_types.empty?
          names = named_types.map { |type| "#{type_name(type)}/0" }
          lines << '-export_type([' + names.join(",\n              ") + ']).'
          lines << ''
          named_types.each { |type| lines.concat(type_specification(type)) }
        end
        lines << RUNTIME
        lines << span_accessor(readable, specification) unless readable.empty?
        lines << PREFIX_RUNTIME if specification.extent
        lines << 'reader_spec() ->'
        lines << indent(literal(reader_data(specification), depth: 1), 4) + '.'
        lines << ''
        ordered = types.values.sort_by(&:name)
        ordered.each do |type|
          lines << "type(#{literal(atom(type.name))}) ->"
          lines << indent(literal(type_data(type), depth: 1), 4) + ';'
        end
        lines << 'type(_) ->'
        lines << '    fail(unsupported, <<"schema">>, 0).'
        lines << ''
        output = lines.join("\n")
        raise SchemaError, 'generated Erlang source is not ASCII' unless output.ascii_only?
        output
      end

      # A span: the field `field` of table `owner`'s records, the pair `field.offset` and
      # `field.count` that a slice or partition rule bounds to the records of table `table`.
      Span = Data.define(:owner, :field, :table)

      # The spans the reader's slice and partition rules give, each once. span/4 takes a span's
      # owner row and field, never a span value, so the table it reads is always the rule's.
      def spans(reader)
        found = reader.rules.filter_map do |rule|
          next unless %w[slice partition].include?(rule.fetch(:kind))

          Span.new(owner: rule.fetch(:offset).scope, field: span_field(rule), table: rule.fetch(:table))
        end.uniq
        found.group_by { |span| [span.owner, span.field] }.each do |key, group|
          raise SchemaError, "Erlang reader span #{key.join('[].')} names two tables" if group.size > 1
        end
        found.sort_by { |span| [span.owner, span.field] }
      end

      # The field a slice or partition rule bounds: its offset and count paths are
      # OWNER[].FIELD.offset and OWNER[].FIELD.count, the shape span/4 names a span by.
      def span_field(rule)
        offset = rule.fetch(:offset)
        count = rule.fetch(:count)
        field = offset.fields.first
        unless offset.scope != 'root' && offset.fields == [field, 'offset'] &&
               count.scope == offset.scope && count.fields == [field, 'count']
          raise SchemaError, "Erlang reader span #{offset.name} is not a record's FIELD.offset and FIELD.count"
        end
        field
      end

      # span/4, typed per span: each clause of its spec names an owner and field pair and the
      # records of the table that pair's rule gives, so Dialyzer refuses any other pair too.
      def span_accessor(spans, reader)
        clauses = spans.map do |span|
          record = type_name(reader.tables.fetch(span.table).fetch(:type))
          "(view(), #{literal(atom(span.owner))}, non_neg_integer(), #{literal(atom(span.field))}) ->\n" \
            "          {ok, [#{record}()]} | {error, error()}"
        end
        [SPAN_DOC, "-spec span#{clauses.join(";\n          ")}.", SPAN_CODE].join("\n")
      end

      def reachable_types(reader)
        pending = [reader.root] + reader.tables.values.map { |table| table.fetch(:type) }
        result = {}
        until pending.empty?
          type = pending.pop
          next if result.key?(type.name)
          result[type.name] = type
          case type
          when Layout
            type.fields.each { |field| pending << field.type }
          when ScalarType, EnumType
            pending << type.base
          end
        end
        result.freeze
      end

      def type_name(type)
        name = Names.c(type.name) + '_t'
        raise SchemaError, 'generated Erlang type name exceeds atom limit' if name.bytesize > 255
        name
      end

      def physical_type(type)
        if type.is_a?(IntegerType)
          "#{type.minimum}..#{type.maximum}"
        else
          "#{type_name(type)}()"
        end
      end

      def type_specification(type)
        name = type_name(type)
        case type
        when ScalarType, EnumType
          ["-type #{name}() :: #{type.integer.minimum}..#{type.integer.maximum}.", '']
        when BytesType
          ["-type #{name}() :: <<_:#{type.size * 8}>>.", '']
        when Layout
          lines = ["-type #{name}() :: " + '#{']
          members = type.fields.map do |field|
            value_type = if field.array? && field.type.name == 'u8'
                           "<<_:#{field.count * 8}>>"
                         elsif field.array?
                           "[#{physical_type(field.type)}]"
                         else
                           physical_type(field.type)
                         end
            "    #{literal(atom(field.name))} := #{value_type}"
          end
          lines << members.join(",\n")
          lines << '}.'
          lines << ''
          lines
        else
          raise SchemaError, 'unsupported Erlang type declaration'
        end
      end

      def atom(name)
        raise SchemaError, 'generated atom exceeds limit' if name.bytesize > 255
        Atom.new(name).freeze
      end

      def type_data(type)
        case type
        when IntegerType
          { kind: atom('integer'), size: type.size, signed: type.signed }
        when ScalarType
          { kind: atom('scalar'), size: type.size, base: atom(type.base.name),
            minimum: type.minimum, maximum: type.maximum, multiple: type.multiple }
        when EnumType
          { kind: atom('enum'), size: type.size, base: atom(type.base.name),
            flags: type.flags, mask: type.mask, values: type.members.values.sort,
            allowed: type.allowed || atom('none') }
        when BytesType
          { kind: atom('bytes'), size: type.size, fixed: type.fixed || atom('none') }
        when Layout
          { kind: atom('layout'), size: type.size,
            fields: type.fields.map { |field| field_data(field) }, padding: type.padding }
        else
          raise SchemaError, "unsupported Erlang data type #{type.name}"
        end
      end

      def field_data(field)
        { name: atom(field.name), type: atom(field.type.name), offset: field.offset,
          count: field.count || atom('scalar'), zero: field.zero_mask,
          input_masks: field.input_masks.to_h { |role, mask| [atom(role), mask] } }
      end

      def path_data(path)
        { scope: atom(path.scope), fields: path.fields.map { |field| atom(field) },
          offset: path.offset, size: path.field.size, label: path.name }
      end

      def reader_data(reader)
        { root: atom(reader.root.name), maximum: reader.maximum,
          extent: reader.extent ? path_data(reader.extent) : atom('none'),
          source_role: reader.source_role ? atom(reader.source_role) : atom('none'),
          order: reader.order.map { |name| atom(name) },
          tables: reader.tables.to_h { |name, table| [atom(name), table_data(table)] },
          strings: reader.strings.to_h { |name, table| [atom(name), table_data(table)] },
          rules: reader.rules.map { |rule| rule_data(rule) } }
      end

      def table_data(table)
        result = { offset: path_data(table.fetch(:offset_path)),
                   count: path_data(table.fetch(:count_path)),
                   maximum: table.fetch(:maximum), alignment: table.fetch(:alignment) }
        if table[:type]
          result[:type] = atom(table.fetch(:type).name)
          result[:size] = table.fetch(:type).size
        else
          result[:type] = atom('bytes')
          result[:size] = 1
        end
        result
      end

      def rule_data(rule)
        result = { kind: atom(rule.fetch(:kind)) }
        result = case rule.fetch(:kind)
        when 'value', 'range'
          result.merge(path: path_data(rule.fetch(:path)), values: rule.fetch(:values))
        when 'index'
          result.merge(path: path_data(rule.fetch(:path)), table: atom(rule.fetch(:table)),
                       absent: rule[:absent] || atom('none'))
        when 'slice', 'partition', 'string'
          result[:offset] = path_data(rule.fetch(:offset))
          result[:count] = path_data(rule.fetch(:count))
          result[:table] = atom(rule.fetch(:table))
          result[:field] = atom(span_field(rule)) unless rule.fetch(:kind) == 'string'
          if rule.fetch(:kind) == 'string'
            result[:class] = atom(rule.fetch(:class))
            result[:maximum] = rule.fetch(:maximum)
            result[:empty] = rule.fetch(:empty)
          end
          result
        when 'optional'
          result.merge(path: path_data(rule.fetch(:path)), flags: path_data(rule.fetch(:flags)),
                       mask: rule.fetch(:mask))
        when 'choice'
          result.merge(tag: path_data(rule.fetch(:tag)),
                       fields: rule.fetch(:fields).map { |path| path_data(path) },
                       cases: rule.fetch(:cases).sort.to_h do |tag, paths|
                         [tag, paths.map { |path| path_data(path) }]
                       end)
        else
          raise SchemaError, 'unsupported Erlang reader rule'
        end
        if rule[:guard]
          result[:guard] = { tag: path_data(rule.fetch(:guard).fetch(:tag)),
                             value: rule.fetch(:guard).fetch(:value) }
        end
        result
      end

      def indent(value, spaces)
        value.lines.map { |line| (' ' * spaces) + line }.join.chomp
      end

      def literal(value, depth: 0)
        case value
        when Atom
          "'#{value.name.gsub(/[\\']/) { |character| '\\' + character }}'"
        when Symbol
          literal(atom(value.to_s), depth: depth)
        when String
          if value.bytes.all? { |byte| byte.between?(32, 126) }
            '<<"' + value.gsub(/[\\"]/) { |character| '\\' + character } + '">>'
          else
            '<<' + value.bytes.map { |byte| format('16#%02x', byte) }.join(', ') + '>>'
          end
        when Integer
          value.to_s
        when TrueClass then 'true'
        when FalseClass then 'false'
        when NilClass then "'none'"
        when Array
          return '[]' if value.empty?
          elements = value.map { |item| literal(item, depth: depth + 1) }
          compact = '[' + elements.join(', ') + ']'
          return compact if !compact.include?("\n") && compact.bytesize <= 76 - depth * 4
          "[\n" + elements.map { |item| indent(item, 4) }.join(",\n") + "\n]"
        when Hash
          return '#{}' if value.empty?
          members = value.map do |key, item|
            literal(key, depth: depth + 1) + ' => ' + literal(item, depth: depth + 1)
          end
          compact = '#{' + members.join(', ') + '}'
          return compact if !compact.include?("\n") && compact.bytesize <= 76 - depth * 4
          '#{' + "\n" + members.map { |member| indent(member, 4) }.join(",\n") + "\n}"
        else
          raise SchemaError, "unsupported generated Erlang literal #{value.class}"
        end
      end

      # The entry of a reader whose input is the front of a longer binary, such as a
      # file's header: emitted for a reader that declares an extent, which names the
      # input's length. The root it decodes to find that length never leaves it.
      PREFIX_RUNTIME = <<~'ERLANG'.freeze
        -doc """
        Validate the input at the front of a longer binary: the root's extent
        field names its length, and the bytes up to it, or as many as there
        are, are opened as open/1 opens them.
        """.
        -spec open_prefix(binary()) -> {ok, view()} | {error, error()}.
        open_prefix(Bytes) when is_binary(Bytes) ->
            Reader = reader_spec(),
            Root = attempt(fun() ->
                decode(maps:get(root, Reader), Bytes, 0, <<"root">>)
            end),
            case Root of
                {ok, Header} ->
                    Length = path_value(maps:get(extent, Reader), Header, Header),
                    open(binary:part(Bytes, 0, min(Length, byte_size(Bytes))));
                {error, _} = Error ->
                    Error
            end;
        open_prefix(_) ->
            {error, error_value(length, <<"root">>, 0)}.
      ERLANG

      RUNTIME = <<~'ERLANG'.freeze
        -doc "Validate the complete file and retain its immutable bytes.".
        -spec read(binary()) -> {ok, view()} | {error, error()}.
        read(Bytes) ->
            open(Bytes).

        -doc "Validate structure, references and declared constraints; not policy admission.".
        -spec open(binary()) -> {ok, view()} | {error, error()}.
        open(Bytes) ->
            attempt(fun() ->
                {Reader, Header} = checked_header(Bytes),
                Tables = maps:get(tables, Reader),
                lists:foreach(fun(Name) ->
                    case maps:find(Name, Tables) of
                        {ok, Table} ->
                            check_records(Name, Table, Bytes, Header, Reader, 0);
                        error ->
                            ok
                    end
                end, maps:get(order, Reader)),
                check_partitions(Reader, Header, Bytes),
                #view{bytes = Bytes}
            end).

        -doc "Return the checked header of a view from open/1.".
        -spec header(view()) -> {ok, map()} | {error, error()}.
        header(View) ->
            attempt(fun() ->
                {_Bytes, _Reader, Header} = view_data(View),
                Header
            end).

        -doc "Count records in a statically named table.".
        -spec count(view(), atom()) -> {ok, non_neg_integer()} | {error, error()}.
        count(View, Name) ->
            attempt(fun() ->
                {_Bytes, Reader, Header} = view_data(View),
                Table = record_table(Name, Reader),
                path_value(maps:get(count, Table), Header, Header)
            end).

        -doc "Fetch one checked record; out-of-range indices are errors.".
        -spec fetch(view(), atom(), non_neg_integer()) -> {ok, map()} | {error, error()}.
        fetch(View, Name, Index) ->
            attempt(fun() ->
                {Bytes, Reader, Header} = view_data(View),
                {_Base, Record} = indexed_record(Name, Index, Bytes, Header, Reader),
                Record
            end).

        %% The byte offset of the record at Index of table Name, and the record;
        %% an index outside the table is an error.
        indexed_record(Name, Index, Bytes, Header, Reader) ->
            Table = record_table(Name, Reader),
            Count = path_value(maps:get(count, Table), Header, Header),
            ensure(is_integer(Index) andalso Index >= 0 andalso Index < Count,
                   index, <<"table">>, 0),
            {record_base(Table, Index, Header), record_at(Name, Table, Index, Bytes, Header, Reader)}.

        %% The byte offset of the record at Index of Table.
        record_base(Table, Index, Header) ->
            path_value(maps:get(offset, Table), Header, Header) + Index * maps:get(size, Table).

        %% The record at Index of Table, which the caller bounded.
        record_at(Name, Table, Index, Bytes, Header, Reader) ->
            Offset = record_base(Table, Index, Header),
            Type = maps:get(type, Table),
            Record = decode(Type, Bytes, Offset, <<"table">>),
            check_scope(Name, Type, Record, Bytes, Offset, Header, Reader),
            Record.

        -doc "Resolve a bounded reference into the manifest's string table.".
        -spec string(view(), #{offset := non_neg_integer(), length := non_neg_integer()}) ->
            {ok, binary()} | {error, error()}.
        string(View, Reference) ->
            attempt(fun() ->
                {Bytes, Reader, Header} = view_data(View),
                case Reference of
                    #{offset := Offset, length := Length}
                      when is_integer(Offset), Offset >= 0,
                           is_integer(Length), Length >= 0 ->
                        Table = string_table(strings, Reader),
                        Count = path_value(maps:get(count, Table), Header, Header),
                        ensure(Offset =< Count andalso Length =< Count - Offset,
                               string_range, <<"strings">>, 0),
                        Start = path_value(maps:get(offset, Table), Header, Header),
                        slice(Bytes, Start + Offset, Length, <<"strings">>);
                    _ ->
                        fail(string_reference, <<"strings">>, 0)
                end
            end).

        -doc "Fold a validated table without retaining every decoded record.".
        -spec fold(view(), atom(), fun((map(), term()) -> term()), term()) ->
            {ok, term()} | {error, error()}.
        fold(View, Name, Function, Initial) when is_function(Function, 2) ->
            Prepared = attempt(fun() ->
                {Bytes, Reader, Header} = view_data(View),
                {Bytes, Reader, Header, record_table(Name, Reader)}
            end),
            case Prepared of
                {ok, {Bytes, Reader, Header, Table}} ->
                    fold_records(Name, Table, Bytes, Header, Reader,
                                 Function, Initial, 0);
                {error, _} = Error ->
                    Error
            end;
        fold(_, _, _, _) ->
            {error, error_value(callback, <<"table">>, 0)}.

        -doc "Fuzz entry point: execute the production reader and retain its outcome.".
        -spec fuzz(binary()) -> {ok, view()} | {error, error()}.
        fuzz(Bytes) ->
            open(Bytes).

        %% Only our explicit parse errors are translated. An implementation bug
        %% remains an exception for tests/fuzzing instead of becoming bad input.
        attempt(Function) ->
            try Function() of
                Value -> {ok, Value}
            catch
                throw:{abi_error, Reason, Field, Offset}:_Stacktrace ->
                    {error, error_value(Reason, Field, Offset)}
            end.

        error_value(Reason, Field, Offset) ->
            #{reason => Reason, field => Field, offset => Offset}.

        fail(Reason, Field, Offset) ->
            throw({abi_error, Reason, Field, Offset}).

        ensure(true, _Reason, _Field, _Offset) -> ok;
        ensure(false, Reason, Field, Offset) -> fail(Reason, Field, Offset).

        %% A view stores no independently mutable copy of offsets or counts.
        %% Accessors recheck the small header/table directory, not every row.
        view_data(#view{schema = ?MODULE, bytes = Bytes}) when is_binary(Bytes) ->
            {Reader, Header} = checked_header(Bytes),
            {Bytes, Reader, Header};
        view_data(_) ->
            fail(view, <<"view">>, 0).

        checked_header(Bytes) when is_binary(Bytes) ->
            Reader = reader_spec(),
            ensure(byte_size(Bytes) =< maps:get(maximum, Reader),
                   length, <<"root">>, 0),
            RootType = maps:get(root, Reader),
            Header = decode(RootType, Bytes, 0, <<"root">>),
            case maps:get(extent, Reader) of
                none -> ok;
                Extent ->
                    ensure(path_value(Extent, Header, Header) =:= byte_size(Bytes),
                           length, maps:get(label, Extent), maps:get(offset, Extent))
            end,
            End = check_tables(maps:get(order, Reader), Reader, Header,
                               Bytes, maps:get(size, type(RootType))),
            ensure(End =:= byte_size(Bytes), trailing, <<"root">>, End),
            check_scope(root, RootType, Header, Bytes, 0, Header, Reader),
            {Reader, Header};
        checked_header(_) ->
            fail(length, <<"root">>, 0).

        record_table(Name, Reader) ->
            case maps:find(Name, maps:get(tables, Reader)) of
                {ok, Table} -> Table;
                error -> fail(unknown_table, <<"table">>, 0)
            end.

        string_table(Name, Reader) ->
            case maps:find(Name, maps:get(strings, Reader)) of
                {ok, Table} -> Table;
                error -> fail(unknown_string_table, <<"strings">>, 0)
            end.

        table(Name, Reader) ->
            case maps:find(Name, maps:get(tables, Reader)) of
                {ok, Table} -> Table;
                error -> string_table(Name, Reader)
            end.

        check_tables([], _Reader, _Header, _Bytes, Cursor) -> Cursor;
        check_tables([Name | Rest], Reader, Header, Bytes, Cursor) ->
            Table = table(Name, Reader),
            Alignment = maps:get(alignment, Table),
            Padding = (Alignment - Cursor rem Alignment) rem Alignment,
            Label = atom_to_binary(Name, utf8),
            ensure(Padding =< byte_size(Bytes) - Cursor,
                   truncated, Label, Cursor),
            ensure(zero(slice(Bytes, Cursor, Padding, Label)),
                   padding, Label, Cursor),
            Start = Cursor + Padding,
            Offset = path_value(maps:get(offset, Table), Header, Header),
            Count = path_value(maps:get(count, Table), Header, Header),
            Stride = maps:get(size, Table),
            ensure(Offset =:= Start, order, Label, Start),
            ensure(Count =< maps:get(maximum, Table) andalso
                   Count =< (byte_size(Bytes) - Start) div Stride,
                   extent, Label, Start),
            check_tables(Rest, Reader, Header, Bytes, Start + Count * Stride).

        check_records(Name, Table, Bytes, Header, Reader, Index) ->
            Count = path_value(maps:get(count, Table), Header, Header),
            case Index < Count of
                false -> ok;
                true ->
                    Offset = record_base(Table, Index, Header),
                    Type = maps:get(type, Table),
                    Record = decode(Type, Bytes, Offset, atom_to_binary(Name, utf8)),
                    check_scope(Name, Type, Record, Bytes, Offset, Header, Reader),
                    check_records(Name, Table, Bytes, Header, Reader, Index + 1)
            end.

        %% An owner span partitions one target table. Progress is measured in
        %% target records, so an offset never multiplies an unchecked count.
        check_partitions(Reader, Header, Bytes) ->
            lists:foreach(fun(Rule) ->
                case maps:get(kind, Rule) of
                    partition ->
                        Path = maps:get(offset, Rule),
                        Owner = record_table(maps:get(scope, Path), Reader),
                        Target = record_table(maps:get(table, Rule), Reader),
                        partition_rows(Rule, Owner, Target, Header, Bytes, 0, 0);
                    _ -> ok
                end
            end, maps:get(rules, Reader)).

        partition_rows(Rule, Owner, Target, Header, Bytes, Index, Covered) ->
            OwnerCount = path_value(maps:get(count, Owner), Header, Header),
            TargetCount = path_value(maps:get(count, Target), Header, Header),
            TargetOffset = path_value(maps:get(offset, Target), Header, Header),
            Stride = maps:get(size, Target),
            Path = maps:get(offset, Rule),
            case Index < OwnerCount of
                false ->
                    ensure(Covered =:= TargetCount, partition,
                           maps:get(label, Path), TargetOffset + Covered * Stride);
                true ->
                    OwnerBase = record_base(Owner, Index, Header),
                    Record = decode(maps:get(type, Owner), Bytes, OwnerBase,
                                    maps:get(label, Path)),
                    Offset = path_value(Path, Record, Header),
                    Count = path_value(maps:get(count, Rule), Record, Header),
                    ensure(Offset =:= TargetOffset + Covered * Stride andalso
                           Covered =< TargetCount andalso
                           Count =< TargetCount - Covered,
                           partition, maps:get(label, Path),
                           OwnerBase + maps:get(offset, Path)),
                    partition_rows(Rule, Owner, Target, Header, Bytes,
                                   Index + 1, Covered + Count)
            end.

        %% The first row and the count of the rows of a slice or partition
        %% rule's table that the rule's span in Record, the record at byte Base,
        %% names. The span's offset is the byte offset of its first row; a span
        %% that does not fall whole on the table's rows is an error at that
        %% offset field. The open check and span/4 both locate a span here.
        span_rows(#{offset := Path, count := CountPath, table := Name}, Record, Header, Base, Reader) ->
            Table = record_table(Name, Reader),
            Total = path_value(maps:get(count, Table), Header, Header),
            Stride = maps:get(size, Table),
            Relative = path_value(Path, Record, Header) - path_value(maps:get(offset, Table), Header, Header),
            Count = path_value(CountPath, Record, Header),
            ensure(Relative >= 0 andalso Relative rem Stride =:= 0 andalso
                   Relative div Stride =< Total andalso
                   Count =< Total - Relative div Stride,
                   slice, maps:get(label, Path), Base + maps:get(offset, Path)),
            {Relative div Stride, Count}.

        fold_records(Name, Table, Bytes, Header, Reader, Function, Accumulator, Index) ->
            Count = path_value(maps:get(count, Table), Header, Header),
            case Index < Count of
                false -> {ok, Accumulator};
                true ->
                    Parsed = attempt(fun() ->
                        record_at(Name, Table, Index, Bytes, Header, Reader)
                    end),
                    case Parsed of
                        {ok, Record} ->
                            Next = Function(Record, Accumulator),
                            fold_records(Name, Table, Bytes, Header, Reader,
                                         Function, Next, Index + 1);
                        {error, _} = Error -> Error
                    end
            end.

        slice(Bytes, Offset, Length, Label) ->
            ensure(is_integer(Offset) andalso Offset >= 0 andalso
                   is_integer(Length) andalso Length >= 0 andalso
                   Offset =< byte_size(Bytes) andalso
                   Length =< byte_size(Bytes) - Offset,
                   truncated, Label, Offset),
            binary:part(Bytes, Offset, Length).

        decode(Name, Bytes, Offset, Label) ->
            Type = type(Name),
            Size = maps:get(size, Type),
            _ = slice(Bytes, Offset, Size, Label),
            case maps:get(kind, Type) of
                integer ->
                    Bits = Size * 8,
                    case maps:get(signed, Type) of
                        true ->
                            <<Value:Bits/little-signed-integer>> =
                                binary:part(Bytes, Offset, Size),
                            Value;
                        false ->
                            <<Value:Bits/little-unsigned-integer>> =
                                binary:part(Bytes, Offset, Size),
                            Value
                    end;
                scalar -> decode(maps:get(base, Type), Bytes, Offset, Label);
                enum -> decode(maps:get(base, Type), Bytes, Offset, Label);
                bytes -> binary:part(Bytes, Offset, Size);
                layout ->
                    maps:from_list([decode_field(Field, Bytes, Offset, Label)
                                    || Field <- maps:get(fields, Type)])
            end.

        decode_field(Field, Bytes, Base, Label) ->
            Name = maps:get(name, Field),
            Type = maps:get(type, Field),
            Offset = Base + maps:get(offset, Field),
            Value = case {maps:get(count, Field), Type} of
                {scalar, _} -> decode(Type, Bytes, Offset, Label);
                {Count, u8} -> slice(Bytes, Offset, Count, Label);
                {Count, _} -> decode_array(Type, Count, Bytes, Offset, Label, [])
            end,
            {Name, Value}.

        decode_array(_Type, 0, _Bytes, _Offset, _Label, Result) ->
            lists:reverse(Result);
        decode_array(Type, Count, Bytes, Offset, Label, Result) ->
            Value = decode(Type, Bytes, Offset, Label),
            decode_array(Type, Count - 1, Bytes,
                         Offset + maps:get(size, type(Type)), Label, [Value | Result]).

        check_scope(Scope, Type, Record, Bytes, Base, Header, Reader) ->
            Rules = maps:get(rules, Reader),
            check_layout(Type, Record, Bytes, Base, Scope, [], Record, Header,
                         Rules, maps:get(source_role, Reader)),
            lists:foreach(fun(Rule) ->
                Path = rule_path(Rule),
                case maps:get(scope, Path) =:= Scope of
                    false -> ok;
                    true ->
                        Kind = maps:get(kind, Rule),
                        StorageActive = Kind =:= optional orelse Kind =:= choice orelse
                                        active(Rules, Scope, maps:get(fields, Path),
                                               Record, Header),
                        Enabled = StorageActive andalso rule_enabled(Rule, Record, Header),
                        case Enabled of
                            true -> check_rule(Rule, Record, Header, Bytes, Base, Reader);
                            false -> ok
                        end
                end
            end, Rules).

        check_layout(Name, Value, Bytes, Base, Scope, Prefix, Record, Header, Rules, Role) ->
            Layout = type(Name),
            lists:foreach(fun([Offset, Length]) ->
                Label = field_label(Scope, Prefix ++ [padding]),
                ensure(zero(slice(Bytes, Base + Offset, Length, Label)),
                       reserved, Label, Base + Offset)
            end, maps:get(padding, Layout)),
            lists:foreach(fun(Field) ->
                FieldName = maps:get(name, Field),
                Fields = Prefix ++ [FieldName],
                FieldValue = maps:get(FieldName, Value),
                Offset = Base + maps:get(offset, Field),
                TypeName = maps:get(type, Field),
                FieldType = type(TypeName),
                case {maps:get(kind, FieldType), maps:get(count, Field)} of
                    {layout, scalar} ->
                        check_layout(TypeName, FieldValue, Bytes, Offset, Scope,
                                     Fields, Record, Header, Rules, Role);
                    _ ->
                        case active(Rules, Scope, Fields, Record, Header) of
                            false -> ok;
                            true ->
                                Label = field_label(Scope, Fields),
                                check_field(Field, FieldValue, Label, Offset, Role)
                        end
                end
            end, maps:get(fields, Layout)).

        check_field(#{count := scalar} = Field, Value, Label, Offset, Role) ->
            check_leaf(Field, Value, Label, Offset, Role);
        check_field(Field, Values, Label, Offset, Role) when is_binary(Values) ->
            check_array(Field, binary_to_list(Values), Label, Offset, Role);
        check_field(Field, Values, Label, Offset, Role) ->
            check_array(Field, Values, Label, Offset, Role).

        check_array(_Field, [], _Label, _Offset, _Role) -> ok;
        check_array(Field, [Value | Rest], Label, Offset, Role) ->
            check_leaf(Field, Value, Label, Offset, Role),
            check_array(Field, Rest, Label,
                        Offset + maps:get(size, type(maps:get(type, Field))), Role).

        check_leaf(Field, Value, Label, Offset, Role) ->
            Type = type(maps:get(type, Field)),
            case maps:get(kind, Type) of
                bytes ->
                    case maps:get(fixed, Type) of
                        none -> ok;
                        Fixed -> ensure(Value =:= Fixed, value, Label, Offset)
                    end,
                    ensure(maps:get(zero, Field) =:= 0 orelse zero(Value),
                           reserved, Label, Offset);
                _ ->
                    check_integer_type(Type, Value, Label, Offset),
                    WidthMask = (1 bsl (maps:get(size, Type) * 8)) - 1,
                    Unsigned = Value band WidthMask,
                    ensure((Unsigned band maps:get(zero, Field)) =:= 0,
                           reserved, Label, Offset),
                    case maps:find(Role, maps:get(input_masks, Field)) of
                        {ok, Mask} ->
                            ensure((Unsigned band bnot Mask) =:= 0,
                                   ownership, Label, Offset);
                        error -> ok
                    end
            end.

        check_integer_type(#{kind := integer}, _Value, _Label, _Offset) -> ok;
        check_integer_type(#{kind := scalar} = Type, Value, Label, Offset) ->
            ensure(Value >= maps:get(minimum, Type) andalso
                   Value =< maps:get(maximum, Type) andalso
                   Value rem maps:get(multiple, Type) =:= 0,
                   range, Label, Offset);
        check_integer_type(#{kind := enum} = Type, Value, Label, Offset) ->
            Valid = case maps:get(allowed, Type) of
                none ->
                    case maps:get(flags, Type) of
                        true -> (Value band bnot maps:get(mask, Type)) =:= 0;
                        false -> lists:member(Value, maps:get(values, Type))
                    end;
                Allowed -> lists:member(Value, Allowed)
            end,
            Reason = case maps:get(flags, Type) of true -> flags; false -> tag end,
            ensure(Valid, Reason, Label, Offset).

        active(Rules, Scope, Fields, Record, Header) ->
            lists:all(fun(Rule) ->
                case maps:get(kind, Rule) of
                    optional ->
                        Path = maps:get(path, Rule),
                        Applies = maps:get(scope, Path) =:= Scope andalso
                                  lists:prefix(maps:get(fields, Path), Fields),
                        not Applies orelse
                            (path_value(maps:get(flags, Rule), Record, Header)
                             band maps:get(mask, Rule)) =/= 0;
                    choice ->
                        Tag = maps:get(tag, Rule),
                        Candidates = [Path || Path <- maps:get(fields, Rule),
                            lists:prefix(maps:get(fields, Path), Fields)],
                        case {maps:get(scope, Tag) =:= Scope, Candidates} of
                            {true, [Selected]} ->
                                Value = path_value(Tag, Record, Header),
                                Active = maps:get(Value, maps:get(cases, Rule), []),
                                lists:member(Selected, Active);
                            _ -> true
                        end;
                    _ -> true
                end
            end, Rules).

        rule_path(#{path := Path}) -> Path;
        rule_path(#{offset := Path}) -> Path;
        rule_path(#{tag := Path}) -> Path.

        rule_enabled(#{guard := #{tag := Tag, value := Expected}}, Record, Header) ->
            path_value(Tag, Record, Header) =:= Expected;
        rule_enabled(_Rule, _Record, _Header) -> true.

        path_value(#{scope := root, fields := Fields}, _Record, Header) ->
            field_value(Fields, Header);
        path_value(#{fields := Fields}, Record, _Header) ->
            field_value(Fields, Record).

        field_value([], Value) -> Value;
        field_value([Field | Rest], Value) ->
            field_value(Rest, maps:get(Field, Value)).

        field_label(Scope, Fields) ->
            Prefix = case Scope of
                root -> <<"root">>;
                _ -> <<(atom_to_binary(Scope, utf8))/binary, "[]">>
            end,
            iolist_to_binary([Prefix | [[<<".">>, atom_to_binary(Field, utf8)]
                                       || Field <- Fields]]).

        check_rule(#{kind := value, path := Path, values := [Expected]},
                   Record, Header, _Bytes, Base, _Reader) ->
            ensure(path_value(Path, Record, Header) =:= Expected,
                   value, maps:get(label, Path), Base + maps:get(offset, Path));
        check_rule(#{kind := range, path := Path, values := [Minimum, Maximum]},
                   Record, Header, _Bytes, Base, _Reader) ->
            Value = path_value(Path, Record, Header),
            ensure(Value >= Minimum andalso Value =< Maximum,
                   range, maps:get(label, Path), Base + maps:get(offset, Path));
        check_rule(#{kind := index, path := Path, table := Name, absent := Absent},
                   Record, Header, _Bytes, Base, Reader) ->
            Value = path_value(Path, Record, Header),
            Table = record_table(Name, Reader),
            Count = path_value(maps:get(count, Table), Header, Header),
            ensure(Value < Count orelse Value =:= Absent,
                   index, maps:get(label, Path), Base + maps:get(offset, Path));
        check_rule(#{kind := Kind} = Rule, Record, Header, _Bytes, Base, Reader)
          when Kind =:= slice; Kind =:= partition ->
            {_First, _Count} = span_rows(Rule, Record, Header, Base, Reader),
            ok;
        check_rule(#{kind := string} = Rule, Record, Header, Bytes, Base, Reader) ->
            check_string(Rule, Record, Header, Bytes, Base, Reader);
        check_rule(#{kind := optional, path := Path, flags := Flags, mask := Mask},
                   Record, Header, Bytes, Base, _Reader) ->
            Present = (path_value(Flags, Record, Header) band Mask) =/= 0,
            Offset = Base + maps:get(offset, Path),
            ensure(Present orelse zero(slice(Bytes, Offset, maps:get(size, Path),
                                             maps:get(label, Path))),
                   inactive, maps:get(label, Path), Offset);
        check_rule(#{kind := choice, tag := Tag, cases := Cases, fields := Fields},
                   Record, Header, Bytes, Base, _Reader) ->
            Value = path_value(Tag, Record, Header),
            case maps:find(Value, Cases) of
                error ->
                    fail(tag, maps:get(label, Tag), Base + maps:get(offset, Tag));
                {ok, Active} ->
                    lists:foreach(fun(Path) ->
                        Offset = Base + maps:get(offset, Path),
                        ensure(lists:member(Path, Active) orelse
                               zero(slice(Bytes, Offset, maps:get(size, Path),
                                          maps:get(label, Path))),
                               inactive, maps:get(label, Path), Offset)
                    end, Fields)
            end.

        check_string(Rule, Record, Header, Bytes, Base, Reader) ->
            Path = maps:get(offset, Rule),
            Offset = path_value(Path, Record, Header),
            Length = path_value(maps:get(count, Rule), Record, Header),
            Table = string_table(maps:get(table, Rule), Reader),
            Total = path_value(maps:get(count, Table), Header, Header),
            Label = maps:get(label, Path),
            Location = Base + maps:get(offset, Path),
            ensure(Offset =< Total andalso Length =< Total - Offset andalso
                   Length =< maps:get(maximum, Rule) andalso
                   (maps:get(empty, Rule) orelse Length > 0),
                   string_range, Label, Location),
            case Length =:= 0 andalso maps:get(empty, Rule) of
                true -> ok;
                false ->
                    Start = path_value(maps:get(offset, Table), Header, Header),
                    Text = slice(Bytes, Start + Offset, Length, Label),
                    ensure(valid_string(maps:get(class, Rule), Text),
                           string_class, Label, Location)
            end.

        zero(<<>>) -> true;
        zero(<<0, Rest/binary>>) -> zero(Rest);
        zero(_) -> false.

        valid_string(bytes, _Bytes) -> true;
        valid_string(identifier, Bytes) ->
            byte_size(Bytes) >= 1 andalso byte_size(Bytes) =< 63 andalso
                identifier(Bytes, first);
        valid_string(utf8, Bytes) -> valid_utf8(Bytes, true);
        valid_string(dt_path, Bytes) -> valid_path(Bytes, true);
        valid_string(namespace_path, Bytes) -> valid_path(Bytes, false);
        valid_string(relative_path, Bytes) ->
            Bytes =/= <<>> andalso valid_path(<<$/, Bytes/binary>>, true);
        valid_string(args, <<>>) -> true;
        valid_string(args, Bytes) -> binary:last(Bytes) =:= 0;
        valid_string(env, Bytes) -> environment(Bytes, #{}).

        identifier(<<>>, _Position) -> true;
        identifier(<<Byte, Rest/binary>>, Position) ->
            AlphaNumeric = (Byte >= $a andalso Byte =< $z) orelse
                           (Byte >= $0 andalso Byte =< $9),
            Valid = AlphaNumeric orelse (Position =:= rest andalso
                     (Byte =:= $_ orelse Byte =:= $-)),
            Valid andalso identifier(Rest, rest).

        valid_utf8(<<>>, _Clean) -> true;
        valid_utf8(<<Point/utf8, Rest/binary>>, Clean) ->
            Safe = not Clean orelse
                   (Point >= 16#20 andalso not (Point >= 16#7f andalso Point =< 16#9f)),
            Safe andalso valid_utf8(Rest, Clean);
        valid_utf8(_, _) -> false.

        valid_path(<<$/, Rest/binary>> = Bytes, Clean) ->
            valid_utf8(Bytes, Clean) andalso
                (Rest =:= <<>> orelse path_component(Rest, 0, true));
        valid_path(_, _) -> false.

        path_component(<<>>, Length, Dots) ->
            Length > 0 andalso not (Dots andalso Length =< 2);
        path_component(<<0, _/binary>>, _Length, _Dots) -> false;
        path_component(<<$/, Rest/binary>>, Length, Dots) ->
            Length > 0 andalso not (Dots andalso Length =< 2) andalso
                path_component(Rest, 0, true);
        path_component(<<Byte, Rest/binary>>, Length, Dots) ->
            path_component(Rest, Length + 1, Dots andalso Byte =:= $.).

        environment(<<>>, _Seen) -> true;
        environment(Bytes, Seen) ->
            case binary:match(Bytes, <<0>>) of
                nomatch -> false;
                {End, 1} ->
                    Entry = binary:part(Bytes, 0, End),
                    case binary:match(Entry, <<$=>>) of
                        {At, 1} when At > 0 ->
                            Key = binary:part(Entry, 0, At),
                            not maps:is_key(Key, Seen) andalso
                                environment(binary:part(Bytes, End + 1,
                                                       byte_size(Bytes) - End - 1),
                                            maps:put(Key, true, Seen));
                        _ -> false
                    end
            end.
      ERLANG

      # span/4 reads a span from its owner row itself and takes its table from the span's
      # rule, so no caller hands it a span value or pairs a span with another table.
      SPAN_DOC = <<~'ERLANG'.chomp.freeze
        -doc """
        The checked rows that span field `Field` of row `Index` of table
        `Owner` names, in the table that span's slice or partition rule
        gives. An `Owner` and `Field` pair that no such rule names is an
        unknown_span error; an `Index` outside `Owner` is an index error.
        """.
      ERLANG

      SPAN_CODE = <<~'ERLANG'.freeze
        span(View, Owner, Index, Field) ->
            attempt(fun() ->
                {Bytes, Reader, Header} = view_data(View),
                Rule = span_rule(Owner, Field, Reader),
                {Base, Record} = indexed_record(Owner, Index, Bytes, Header, Reader),
                {First, Count} = span_rows(Rule, Record, Header, Base, Reader),
                TargetName = maps:get(table, Rule),
                Target = record_table(TargetName, Reader),
                [record_at(TargetName, Target, Row, Bytes, Header, Reader)
                 || Row <- lists:seq(First, First + Count - 1)]
            end).

        %% The slice or partition rule of span field Field of table Owner's rows.
        span_rule(Owner, Field, Reader) ->
            Rules = [Rule || #{field := RuleField, offset := #{scope := RuleOwner}} = Rule
                                 <- maps:get(rules, Reader),
                             RuleOwner =:= Owner, RuleField =:= Field],
            case Rules of
                [Rule | _] -> Rule;
                [] -> fail(unknown_span, <<"span">>, 0)
            end.
      ERLANG
    end
  end
