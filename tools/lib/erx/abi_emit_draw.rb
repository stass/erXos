# frozen_string_literal: true

require_relative 'abi_draw'

module Erx
  module ABI
    # Emits the draw protocol's codec from the `draw` declaration
    # (docs/design-display.md, "Draw messages"): erx_draw_codec, the Erlang
    # decoder and encoder, and its bounded C twin, which the fuzz target and the
    # differential test link. Both are one table of every message's fields,
    # generated from the declaration, read by one fixed walk over the fields;
    # so a message is declared once and no message has code of its own.
    module DrawEmitter
      ERLANG_PATH = 'erlang/apps/erx_display/src/erx_draw_codec.erl'
      C_HEADER_PATH = 'include/erx/draw_codec.h'
      C_SOURCE_PATH = 'display/generated/erx_draw_codec.c'
      # Each field type's Erlang type, and its C enumerator after ERX_DRAW_F_.
      ERLANG_TYPES = { 'u8' => 'byte()', 'u16' => '0..16#ffff', 'u32' => '0..16#ffffffff',
                       'i32' => '-16#80000000..16#7fffffff', 'id' => 'image_id()', 'point' => 'point()',
                       'rect' => 'rect()', 'points' => '[point(), ...]', 'indices' => '[0..16#ffff]',
                       'pixels' => 'binary()', 'compressed' => 'binary()' }.freeze

      module_function

      def outputs(schema)
        return {} unless schema.draw

        draw = schema.draw
        { ERLANG_PATH => erlang(draw), C_HEADER_PATH => c_header(draw), C_SOURCE_PATH => c_source(draw) }.freeze
      end

      # A field as the Erlang table writes it: a count is `count`, a field
      # that depends on earlier ones names their 1-based positions.
      def erlang_field(field)
        case field
        in { counted: true } then 'count'
        in { type: 'points' | 'indices', count: } then "{#{field.type}, #{count + 1}}"
        in { type: 'pixels' | 'compressed', id:, rect: } then "{#{field.type}, #{id + 1}, #{rect + 1}}"
        else field.type
        end
      end

      def erlang_letter(letter) = letter.match?(/[a-zA-Z]/) ? "$#{letter}" : letter.ord.to_s

      def erlang_term_type(message)
        return message.name if message.carried.empty?

        fields = message.carried.map { |field| "#{camel(field.name)} :: #{ERLANG_TYPES.fetch(field.type)}" }
        "{#{message.name},\n         #{fields.join(",\n         ")}}"
      end

      def camel(name) = name.split('_').map(&:capitalize).join

      def erlang(draw)
        types = draw.messages.map { |message| erlang_term_type(message) }
        layouts = draw.messages.map do |message|
          "layout(#{erlang_letter(message.letter)}) -> {#{message.name}, [#{message.fields.map { |field| erlang_field(field) }.join(', ')}]};"
        end
        letters = draw.messages.map { |message| "letter(#{message.name}) -> #{erlang_letter(message.letter)};" }
        <<~ERLANG + ERLANG_WALK
          %% Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
          %% SPDX-License-Identifier: BSD-2-Clause
          %% Generated by tools/gen_abi.rb from abi/formats/draw.txt.
          %% Do not edit this file.

          -module(erx_draw_codec).
          -moduledoc """
          The draw protocol's messages (docs/design-display.md, "Draw messages").
          decode/2 decodes the one message at the start of the bytes it is given,
          with Depth, the connection's view of an image's depth, which only the
          pixels of `y` and `Y` consult; encode/1 writes one message. Integers are
          little-endian, a point is two signed 32-bit coordinates and a rectangle
          four. A decoded `Y` carries the pixels erx_draw_image decoded, not its
          codes, and a count field is not part of a decoded message: the list it
          counts is. The decoder makes no atom, since every name comes from
          layout/1, checks each length against the bytes left before it reads,
          and fails with the errno and the offset, within the bytes given, of the
          field that failed, or 0 for an empty input or an unknown letter.
          """.
          -export([decode/2, encode/1, layout/1, letter/1]).
          -export_type([msg/0, depth/0, image_id/0, point/0, rect/0, field/0]).

          -type image_id() :: 0..16#ffffffff.
          -type coord() :: -16#80000000..16#7fffffff.
          -type point() :: {X :: coord(), Y :: coord()}.
          -type rect() :: {X0 :: coord(), Y0 :: coord(), X1 :: coord(), Y1 :: coord()}.
          -type depth() :: fun((image_id()) -> 1..32 | none).
          -type msg() ::
                  #{types.join("\n      | ")}.
          %% A field's type: a fixed one, a count, or a field whose length an
          %% earlier field gives, by its 1-based position in the message.
          -type field() :: u8 | u16 | u32 | i32 | id | point | rect | count |
                           {points | indices, pos_integer()} |
                           {pixels | compressed, pos_integer(), pos_integer()}.

          -doc "A message's name and its fields after the letter, in wire order.".
          -spec layout(byte()) -> {atom(), [field()]} | unknown.
          #{layouts.join("\n")}
          layout(_) -> unknown.

          -doc "A message's letter.".
          -spec letter(atom()) -> byte().
          #{letters.join("\n")}
          letter(Name) -> error({badarg, Name}).
        ERLANG
      end

      # The fixed walk over a message's fields, decoding and encoding.
      ERLANG_WALK = <<~'ERLANG'

        -spec decode(binary(), depth()) ->
                  {ok, msg(), Rest :: binary()} |
                  {error, einval | enoent, Offset :: non_neg_integer()}.
        decode(<<Letter, Body/binary>> = Bytes, Depth) ->
            case layout(Letter) of
                {Name, Fields} -> fields(Fields, Body, byte_size(Bytes), Depth, [], {Name, Fields});
                unknown -> {error, einval, 0}
            end;
        decode(<<>>, _Depth) ->
            {error, einval, 0}.

        %% Values holds the fields read so far, in wire order.
        fields([], Rest, _Size, _Depth, Values, Layout) ->
            {ok, message(Layout, Values), Rest};
        fields([Field | Fields], Bytes, Size, Depth, Values, Layout) ->
            case field(Field, Bytes, Depth, Values) of
                {ok, Value, Rest} -> fields(Fields, Rest, Size, Depth, Values ++ [Value], Layout);
                {error, Errno} -> {error, Errno, Size - byte_size(Bytes)}
            end.

        %% The decoded term: the name and every field but the counts.
        message({Name, Fields}, Values) ->
            case [Value || {Field, Value} <- lists:zip(Fields, Values), Field =/= count] of
                [] -> Name;
                Carried -> list_to_tuple([Name | Carried])
            end.

        %% The value of the field at 1-based Position, of those read so far.
        value(Position, Values) -> lists:nth(Position, Values).

        field(u8, <<Value, Rest/binary>>, _, _) -> {ok, Value, Rest};
        field(Type, <<Value:16/little, Rest/binary>>, _, _) when Type =:= u16; Type =:= count -> {ok, Value, Rest};
        field(Type, <<Value:32/little, Rest/binary>>, _, _) when Type =:= u32; Type =:= id -> {ok, Value, Rest};
        field(i32, <<Value:32/little-signed, Rest/binary>>, _, _) -> {ok, Value, Rest};
        field(point, <<X:32/little-signed, Y:32/little-signed, Rest/binary>>, _, _) -> {ok, {X, Y}, Rest};
        field(rect, <<X0:32/little-signed, Y0:32/little-signed, X1:32/little-signed, Y1:32/little-signed,
                      Rest/binary>>, _, _) ->
            {ok, {X0, Y0, X1, Y1}, Rest};
        field({points, Count}, Bytes, _, Values) ->
            points(value(Count, Values) + 1, Bytes, 0, 0, []);
        field({indices, Count}, Bytes, _, Values) ->
            Length = 2 * value(Count, Values),
            case Bytes of
                <<Indices:Length/binary, Rest/binary>> -> {ok, [Index || <<Index:16/little>> <= Indices], Rest};
                _ -> {error, einval}
            end;
        field({Payload, Id, Rect}, Bytes, Depth, Values) ->
            R = value(Rect, Values),
            case {Depth(value(Id, Values)), R} of
                {none, _} -> {error, enoent};
                {Bits, {X0, Y0, X1, Y1}} when is_integer(Bits), Bits >= 1, Bits =< 32, X1 > X0, Y1 > Y0 ->
                    payload(Payload, Bytes, R, Bits);
                _ -> {error, einval}
            end;
        field(_, _, _, _) ->
            {error, einval}.

        %% Raw pixels are exactly the rows of the rectangle; compressed ones end
        %% at the code that completes its last row.
        payload(pixels, Bytes, {_, Y0, _, Y1} = R, Bits) ->
            Length = erx_draw_image:bytes_per_line(R, Bits) * (Y1 - Y0),
            case Length =< byte_size(Bytes) of
                true -> {ok, binary:part(Bytes, 0, Length), binary:part(Bytes, Length, byte_size(Bytes) - Length)};
                false -> {error, einval}
            end;
        payload(compressed, Bytes, R, Bits) ->
            case erx_draw_image:decode(Bytes, R, Bits) of
                {ok, Pixels, Rest} -> {ok, Pixels, Rest};
                error -> {error, einval}
            end.

        %% Coded points: each coordinate one byte, a 7-bit signed difference from
        %% the previous one, or three when the first byte's top bit is set, a
        %% 23-bit signed value; the first point counts from 0.
        points(0, Rest, _, _, Points) ->
            {ok, lists:reverse(Points), Rest};
        points(N, Bytes, OldX, OldY, Points) ->
            maybe
                {ok, X, Rest} ?= coord(Bytes, OldX),
                {ok, Y, Rest1} ?= coord(Rest, OldY),
                points(N - 1, Rest1, X, Y, [{X, Y} | Points])
            end.

        coord(<<0:1, Difference:7/signed, Rest/binary>>, Old) -> {ok, Old + Difference, Rest};
        coord(<<1:1, Low:7, Middle, High:8/signed, Rest/binary>>, _) -> {ok, (High bsl 15) bor (Middle bsl 7) bor Low, Rest};
        coord(_, _) -> {error, einval}.

        -spec encode(msg()) -> binary().
        encode(Name) when is_atom(Name) ->
            encode(Name, []);
        encode(Message) when is_tuple(Message) ->
            [Name | Carried] = tuple_to_list(Message),
            encode(Name, Carried).

        encode(Name, Carried) ->
            Letter = letter(Name),
            {Name, Fields} = layout(Letter),
            Values = wire_values(Fields, Carried),
            iolist_to_binary([Letter | [write(Field, Value, Values) || {Field, Value} <- lists:zip(Fields, Values)]]).

        %% Every field's value in wire order: the term's own, and each count the
        %% length of the points or indices field that names it.
        wire_values(Fields, Carried) ->
            Placed = place(Fields, Carried),
            Counts = maps:from_list([{Count, items(Type, Value)} || {{Type, Count}, Value} <- lists:zip(Fields, Placed)]),
            [maps:get(Position, Counts, Value) || {Position, Value} <- lists:enumerate(Placed)].

        place([count | Fields], Carried) -> [count | place(Fields, Carried)];
        place([_ | Fields], [Value | Carried]) -> [Value | place(Fields, Carried)];
        place([], []) -> [];
        place(_, _) -> error(badarg).

        items(points, Points) when is_list(Points) -> length(Points) - 1;
        items(indices, Indices) when is_list(Indices) -> length(Indices).

        write(u8, Value, _) when is_integer(Value), Value >= 0, Value =< 16#ff -> <<Value>>;
        write(Type, Value, _) when (Type =:= u16 orelse Type =:= count), is_integer(Value), Value >= 0, Value =< 16#ffff ->
            <<Value:16/little>>;
        write(Type, Value, _) when (Type =:= u32 orelse Type =:= id), is_integer(Value), Value >= 0, Value =< 16#ffffffff ->
            <<Value:32/little>>;
        write(i32, Value, _) when is_integer(Value), Value >= -16#80000000, Value =< 16#7fffffff -> <<Value:32/little-signed>>;
        write(point, {X, Y}, _) -> <<(write(i32, X, none))/binary, (write(i32, Y, none))/binary>>;
        write(rect, {X0, Y0, X1, Y1}, _) -> << <<(write(i32, V, none))/binary>> || V <- [X0, Y0, X1, Y1] >>;
        write({points, _}, [_ | _] = Points, _) -> coded(Points, 0, 0);
        write({indices, _}, Indices, _) -> << <<(write(u16, Index, none))/binary>> || Index <- Indices >>;
        write({pixels, _, _}, Pixels, _) when is_binary(Pixels) -> Pixels;
        write({compressed, _, Rect}, Pixels, Values) when is_binary(Pixels) ->
            erx_draw_image:encode(Pixels, lists:nth(Rect, Values));
        write(Field, Value, _) -> error({badarg, Field, Value}).

        coded([], _, _) -> <<>>;
        coded([{X, Y} | Points], OldX, OldY) ->
            <<(coded_coord(X, OldX))/binary, (coded_coord(Y, OldY))/binary, (coded(Points, X, Y))/binary>>.

        coded_coord(Value, Old) when is_integer(Value), Value - Old >= -64, Value - Old =< 63 -> <<0:1, (Value - Old):7>>;
        coded_coord(Value, _) when is_integer(Value), Value >= -16#400000, Value =< 16#3fffff ->
            <<1:1, Value:7, (Value bsr 7):8, (Value bsr 15):8>>;
        coded_coord(Value, _) -> error({badarg, Value}).
      ERLANG

      def c_enum(type) = "ERX_DRAW_F_#{type.upcase}"

      def c_field(field)
        type = field.counted ? 'count' : field.type
        refs = [field.count || field.id || 0, field.rect || 0]
        "{ #{c_enum(type)}, #{refs[0]}, #{refs[1]} }"
      end

      def c_header(draw)
        fields_max = draw.messages.map { |message| message.fields.size }.max
        <<~C
          /*
           * Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
           * SPDX-License-Identifier: BSD-2-Clause
           * Generated by tools/gen_abi.rb from abi/formats/draw.txt.
           * Do not edit this file.
           *
           * The C twin of erx_draw_codec (docs/design-display.md, "Draw
           * messages"), a host test tool: it decodes one draw message at a time
           * from untrusted bytes, reading nothing outside them and allocating
           * nothing, as erx_draw_codec:decode/2 does, so the fuzz target and the
           * differential test run the same table.
           */

          #ifndef ERX_DRAW_CODEC_H
          #define ERX_DRAW_CODEC_H

          #include <stdbool.h>
          #include <stddef.h>
          #include <stdint.h>

          #define ERX_DRAW_FIELDS_MAX #{fields_max}
          #define ERX_DRAW_MESSAGES #{draw.messages.size}

          /* decode's results: the errnos a failed message gives. */
          #define ERX_DRAW_OK 0
          #define ERX_DRAW_EINVAL 1
          #define ERX_DRAW_ENOENT 2

          typedef enum erx_draw_ftype {
          	ERX_DRAW_F_U8,
          	ERX_DRAW_F_U16,
          	ERX_DRAW_F_U32,
          	ERX_DRAW_F_I32,
          	ERX_DRAW_F_ID,
          	ERX_DRAW_F_POINT,
          	ERX_DRAW_F_RECT,
          	ERX_DRAW_F_COUNT,	/* a u16 counting a later field's items */
          	ERX_DRAW_F_POINTS,	/* coded points; ref names the count */
          	ERX_DRAW_F_INDICES,	/* u16 glyph indices; ref names the count */
          	ERX_DRAW_F_PIXELS,	/* raw rows; ref the id, rect the rectangle */
          	ERX_DRAW_F_COMPRESSED	/* image(6) codes; ref and rect as pixels */
          } erx_draw_ftype_t;

          /* A field and the 0-based positions of the earlier fields it needs. */
          typedef struct erx_draw_field {
          	erx_draw_ftype_t type;
          	uint8_t ref;		/* the count, or the id of pixels */
          	uint8_t rect;		/* the rectangle of pixels */
          } erx_draw_field_t;

          typedef struct erx_draw_layout {
          	uint8_t letter;
          	const char *name;
          	uint8_t nfields;
          	erx_draw_field_t fields[ERX_DRAW_FIELDS_MAX];
          } erx_draw_layout_t;

          /*
           * A decoded field: an integer in scalar; a point in xy[0..1] and a
           * rectangle in xy[0..3]; and a variable field as the bytes it took
           * from the input, with the items of points and indices in count.
           */
          typedef struct erx_draw_value {
          	int64_t scalar;
          	int32_t xy[4];
          	const uint8_t *data;
          	size_t length;
          	uint32_t count;
          } erx_draw_value_t;

          typedef struct erx_draw_msg {
          	const erx_draw_layout_t *layout;
          	erx_draw_value_t values[ERX_DRAW_FIELDS_MAX];
          } erx_draw_msg_t;

          /* The depth of an image id, 1 to 32, or 0 for an id the connection lacks. */
          typedef int erx_draw_depth_fn(void *, uint32_t);

          const erx_draw_layout_t *erx_draw_layout(uint8_t);
          int erx_draw_decode(const uint8_t *, size_t, erx_draw_depth_fn *, void *,
              erx_draw_msg_t *, size_t *, size_t *);
          int64_t erx_draw_bytesperline(int32_t, int32_t, int);
          bool erx_draw_points_next(const erx_draw_value_t *, size_t *, int32_t *,
              int32_t *);

          /*
           * The bytes image(6)'s codes take to fill the rectangle at the depth, or
           * -1 for codes that cross a row's end or end before its last row. The
           * program that links the twin provides it: cloadmemimage's walk.
           */
          int64_t erx_draw_cload_frame(const uint8_t *, size_t, const int32_t[4], int);

          #endif /* ERX_DRAW_CODEC_H */
        C
      end

      def c_source(draw)
        rows = draw.messages.sort_by(&:letter).map do |message|
          fields = message.fields.map { |field| c_field(field) }
          body = fields.empty? ? '{ { 0 } }' : "{\n\t    #{fields.join(",\n\t    ")} }"
          "\t{ #{message.letter.ord}, \"#{message.name}\", #{message.fields.size}, #{body} }"
        end
        <<~C + C_WALK
          /*
           * Copyright (c) 2026, Stanislav Sedov <stas@deglitch.com>
           * SPDX-License-Identifier: BSD-2-Clause
           * Generated by tools/gen_abi.rb from abi/formats/draw.txt.
           * Do not edit this file.
           *
           * The table of every draw message's fields, in letter order, and the one
           * walk that decodes a message by it (erx/draw_codec.h).
           */

          #include <stdbool.h>
          #include <stddef.h>
          #include <stdint.h>

          #include <erx/draw_codec.h>

          static const erx_draw_layout_t erx_draw_layouts[ERX_DRAW_MESSAGES] = {
          #{rows.join(",\n")}
          };
        C
      end

      C_WALK = <<~'C'

        const erx_draw_layout_t *
        erx_draw_layout(uint8_t letter)
        {
        	for (size_t i = 0; i < ERX_DRAW_MESSAGES; i++) {
        		if (erx_draw_layouts[i].letter == letter)
        			return (&erx_draw_layouts[i]);
        	}
        	return (NULL);
        }

        static uint32_t
        le(const uint8_t *p, size_t width)
        {
        	uint32_t value;

        	value = 0;
        	for (size_t i = width; i > 0; i--)
        		value = value << 8 | p[i - 1];
        	return (value);
        }

        static int32_t
        signed32(uint32_t value)
        {
        	return (value >= UINT32_C(0x80000000) ?
        	    (int32_t)((int64_t)value - INT64_C(0x100000000)) : (int32_t)value);
        }

        /*
         * 9front's bytesperline, in 64 bits so that no coordinate overflows; it
         * divides as C does, toward zero, which counts one byte more than the
         * row covers for some rows left of 0, and the twin keeps that.
         */
        int64_t
        erx_draw_bytesperline(int32_t x0, int32_t x1, int depth)
        {
        	if (x0 >= 0)
        		return (((int64_t)x1 * depth + 7) / 8 - (int64_t)x0 * depth / 8);
        	return ((-(int64_t)x0 * depth + 7) / 8 + ((int64_t)x1 * depth + 7) / 8);
        }

        /* One coded coordinate at p, of at most left bytes; *used its size. */
        static bool
        coord(const uint8_t *p, size_t left, int32_t old, int32_t *value,
            size_t *used)
        {
        	int32_t x;

        	if (left < 1)
        		return (false);
        	if ((p[0] & 0x80) == 0) {
        		x = p[0] & 0x3f;
        		if (p[0] & 0x40)
        			x -= 0x40;
        		*value = old + x;
        		*used = 1;
        		return (true);
        	}
        	if (left < 3)
        		return (false);
        	x = (int32_t)((uint32_t)(p[0] & 0x7f) | (uint32_t)p[1] << 7 |
        	    (uint32_t)(p[2] & 0x7f) << 15);
        	if (p[2] & 0x80)
        		x -= 0x400000;
        	*value = x;
        	*used = 3;
        	return (true);
        }

        /* The next point of a decoded points field; *cursor starts at 0. */
        bool
        erx_draw_points_next(const erx_draw_value_t *value, size_t *cursor,
            int32_t *x, int32_t *y)
        {
        	size_t used;

        	if (*cursor >= value->length)
        		return (false);
        	if (*cursor == 0)
        		*x = *y = 0;
        	if (!coord(value->data + *cursor, value->length - *cursor, *x, x,
        	    &used))
        		return (false);
        	*cursor += used;
        	if (!coord(value->data + *cursor, value->length - *cursor, *y, y,
        	    &used))
        		return (false);
        	*cursor += used;
        	return (true);
        }

        /* The bytes a pixels or compressed field takes, or an errno. */
        static int
        payload(const erx_draw_field_t *field, const erx_draw_value_t *values,
            const uint8_t *p, size_t left, erx_draw_depth_fn *depth, void *arg,
            size_t *length)
        {
        	const int32_t *r;
        	int64_t line, rows, framed;
        	int bits;

        	bits = depth(arg, (uint32_t)values[field->ref].scalar);
        	if (bits == 0)
        		return (ERX_DRAW_ENOENT);
        	if (bits < 1 || bits > 32)
        		return (ERX_DRAW_EINVAL);
        	r = values[field->rect].xy;
        	if (r[2] <= r[0] || r[3] <= r[1])
        		return (ERX_DRAW_EINVAL);
        	if (field->type == ERX_DRAW_F_COMPRESSED) {
        		framed = erx_draw_cload_frame(p, left, r, bits);
        		if (framed < 0 || (uint64_t)framed > left)
        			return (ERX_DRAW_EINVAL);
        		*length = (size_t)framed;
        		return (ERX_DRAW_OK);
        	}
        	line = erx_draw_bytesperline(r[0], r[2], bits);
        	rows = (int64_t)r[3] - r[1];
        	if ((uint64_t)line > left || (uint64_t)rows > left / (uint64_t)line)
        		return (ERX_DRAW_EINVAL);
        	*length = (size_t)(line * rows);
        	return (ERX_DRAW_OK);
        }

        /* Reads field i at p, of at most left bytes, into values[i]. */
        static int
        read_field(const erx_draw_layout_t *layout, uint8_t i, const uint8_t *p,
            size_t left, erx_draw_depth_fn *depth, void *arg,
            erx_draw_value_t *values, size_t *used)
        {
        	static const size_t widths[] = {
        		[ERX_DRAW_F_U8] = 1, [ERX_DRAW_F_U16] = 2, [ERX_DRAW_F_U32] = 4,
        		[ERX_DRAW_F_I32] = 4, [ERX_DRAW_F_ID] = 4, [ERX_DRAW_F_POINT] = 8,
        		[ERX_DRAW_F_RECT] = 16, [ERX_DRAW_F_COUNT] = 2
        	};
        	const erx_draw_field_t *field;
        	erx_draw_value_t *value;
        	size_t at, step;
        	int32_t x, y;
        	int status;

        	field = &layout->fields[i];
        	value = &values[i];
        	*value = (erx_draw_value_t){ 0 };
        	switch (field->type) {
        	case ERX_DRAW_F_POINTS:
        		value->count = (uint32_t)values[field->ref].scalar + 1;
        		x = y = 0;
        		at = 0;
        		for (uint32_t n = 0; n < value->count; n++) {
        			if (!coord(p + at, left - at, x, &x, &step))
        				return (ERX_DRAW_EINVAL);
        			at += step;
        			if (!coord(p + at, left - at, y, &y, &step))
        				return (ERX_DRAW_EINVAL);
        			at += step;
        		}
        		value->data = p;
        		value->length = *used = at;
        		return (ERX_DRAW_OK);
        	case ERX_DRAW_F_INDICES:
        		value->count = (uint32_t)values[field->ref].scalar;
        		if (left < (size_t)value->count * 2)
        			return (ERX_DRAW_EINVAL);
        		value->data = p;
        		value->length = *used = (size_t)value->count * 2;
        		return (ERX_DRAW_OK);
        	case ERX_DRAW_F_PIXELS:
        	case ERX_DRAW_F_COMPRESSED:
        		status = payload(field, values, p, left, depth, arg, used);
        		if (status == ERX_DRAW_OK) {
        			value->data = p;
        			value->length = *used;
        		}
        		return (status);
        	case ERX_DRAW_F_U8:
        	case ERX_DRAW_F_U16:
        	case ERX_DRAW_F_U32:
        	case ERX_DRAW_F_I32:
        	case ERX_DRAW_F_ID:
        	case ERX_DRAW_F_POINT:
        	case ERX_DRAW_F_RECT:
        	case ERX_DRAW_F_COUNT:
        		break;
        	}
        	if (left < widths[field->type])
        		return (ERX_DRAW_EINVAL);
        	*used = widths[field->type];
        	switch (field->type) {
        	case ERX_DRAW_F_I32:
        		value->scalar = signed32(le(p, 4));
        		break;
        	case ERX_DRAW_F_POINT:
        	case ERX_DRAW_F_RECT:
        		for (size_t k = 0; k < *used / 4; k++)
        			value->xy[k] = signed32(le(p + 4 * k, 4));
        		break;
        	default:
        		value->scalar = le(p, widths[field->type]);
        		break;
        	}
        	return (ERX_DRAW_OK);
        }

        /*
         * Decodes the message at the start of data. On success *used is its
         * size; on failure *offset is that of the field that failed, or 0 for
         * an empty input or an unknown letter.
         */
        int
        erx_draw_decode(const uint8_t *data, size_t size, erx_draw_depth_fn *depth,
            void *arg, erx_draw_msg_t *msg, size_t *used, size_t *offset)
        {
        	const erx_draw_layout_t *layout;
        	size_t at, step;
        	int status;

        	*offset = 0;
        	if (size == 0 || (layout = erx_draw_layout(data[0])) == NULL)
        		return (ERX_DRAW_EINVAL);
        	msg->layout = layout;
        	at = 1;
        	for (uint8_t i = 0; i < layout->nfields; i++) {
        		status = read_field(layout, i, data + at, size - at, depth, arg,
        		    msg->values, &step);
        		if (status != ERX_DRAW_OK) {
        			*offset = at;
        			return (status);
        		}
        		at += step;
        	}
        	*used = at;
        	return (ERX_DRAW_OK);
        }
      C
