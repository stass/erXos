# What the system release and the oracle's hosted tree ship: each application's
# beams and resource file from its build, and its include/ headers from the tree,
# each header recorded as its own source, and no .appup, since an update replaces
# a whole slot.
class ReleaseFilesTest < Minitest::Test
  ROOT = File.expand_path('../..', __dir__)
  VERSION = '1.0'

  # Stands in for systools: writes the boot script the release names.
  class BootRunner
    def run(_argv, chdir:, **) = File.write(File.join(chdir, 'start.boot'), 'boot')
  end

  class Codec
    def member(_type, name) = name
  end

  class FakeOracle
    def erl_path(_flavour) = '/nonexistent/bin/erl'
  end

  def setup
    @scratch = File.realpath(Dir.mktmpdir('erx-release-files-'))
    @otp = File.join(@scratch, 'otp')
    write(@otp, 'erts/vsn.mk', "VSN = 1.0\n")
    applications = Erx::ReleaseFiles::APPLICATIONS
    applications.each do |application|
      write(@otp, "lib/#{application}/ebin/#{application}.app", "{application,#{application},[{vsn,\"#{VERSION}\"}]}.\n")
      write(@otp, "lib/#{application}/ebin/#{application}.appup", "{\"#{VERSION}\",[],[]}.\n")
    end
    write(@otp, 'lib/runtime_tools/ebin/dbg.beam', 'beam')
  end

  def teardown
    FileUtils.remove_entry(@scratch) if @scratch
  end

  def write(base, path, text)
    full = File.join(base, path)
    FileUtils.mkdir_p(File.dirname(full))
    File.write(full, text)
  end

  def entries
    Erx::ReleaseFiles.new(root: ROOT, otp: @otp, directory: File.join(@scratch, 'release'), runner: BootRunner.new,
                          codec: Codec.new, oracle: FakeOracle.new).entries
  end

  def reference(path) = { 'path' => path, 'sha256' => Digest::SHA256.file(File.join(ROOT, path)).hexdigest }

  # Code compiled on erXos includes stdlib's headers through include_lib, as on stock.
  def test_the_release_ships_stdlibs_headers_each_its_own_source
    entry = entries.find { |candidate| candidate.fetch('path') == "system/lib/stdlib-#{VERSION}/include/qlc.hrl" }
    refute_nil entry, 'the release ships no stdlib/include/qlc.hrl'
    header = 'otp/lib/stdlib/include/qlc.hrl'
    assert_equal File.join(ROOT, header), entry.fetch('artifact')
    receipt = JSON.parse(File.read(entry.fetch('receipt')))
    assert_equal({ 'version' => 1, 'kind' => 'compiled', 'artifact' => reference(header), 'sources' => [reference(header)] },
                 receipt)
  end

  # A generated module's receipt names the file the build compiled, in build/gen.
  def test_a_generated_modules_receipt_names_its_generated_source
    Erx::Generated.ensure(root: ROOT)
    write(@otp, 'lib/erx/ebin/erx_manifest.beam', 'beam')
    entry = entries.find { |candidate| candidate.fetch('path') == "system/lib/erx-#{VERSION}/ebin/erx_manifest.beam" }
    source = 'build/gen/erlang/apps/erx/src/generated/erx_manifest.erl'
    assert_equal [reference(source)], JSON.parse(File.read(entry.fetch('receipt'))).fetch('sources')
  end

  # public_key's ASN.1 modules are generated by the build, so the tree holds no Erlang
  # of theirs: a module's receipt names its specification, and PKCS-FRAME's names its set
  # and each specification the set names, whose licenses the module carries.
  def test_a_public_key_asn1_modules_receipt_names_its_specifications
    %w[DSS PKCS-FRAME].each { |name| write(@otp, "lib/public_key/ebin/#{name}.beam", 'beam') }
    release = Erx::ProductionImage.domain_boot('ssh')
    sources = domain_entries(Erx::ReleaseFiles.domain([release])).to_h do |entry|
      [File.basename(entry.fetch('path')), JSON.parse(File.read(entry.fetch('receipt'))).fetch('sources')]
    end
    asn1 = 'otp/lib/public_key/asn1'
    assert_equal [reference("#{asn1}/DSS.asn1")], sources.fetch('DSS.beam')
    assert_equal %W[#{asn1}/PKCS-FRAME.set.asn #{asn1}/AsymmetricKeyPackageModuleV1.asn1 #{asn1}/PKCS5v2-0.asn1].map { |path| reference(path) },
                 sources.fetch('PKCS-FRAME.beam')
  end

  def test_the_release_ships_every_header_of_kernel_and_stdlib
    paths = entries.map { |entry| entry.fetch('path') }
    %w[kernel stdlib].each do |application|
      Dir.glob('*.hrl', base: File.join(ROOT, 'otp/lib', application, 'include')).each do |name|
        assert_includes paths, "system/lib/#{application}-#{VERSION}/include/#{name}"
      end
    end
  end

  # The shell on erXos has c:c and dbg, as design-runtime.md keeps compiler and
  # runtime_tools, but neither starts at boot: start type load puts each on the boot
  # script's code path and loads its .app, and starts nothing, runtime_tools'
  # ttb_autostart included.
  def test_the_release_file_loads_compiler_and_runtime_tools_and_starts_neither
    paths = entries.map { |entry| entry.fetch('path') }
    assert_includes paths, "system/lib/compiler-#{VERSION}/ebin/compiler.app"
    assert_includes paths, "system/lib/runtime_tools-#{VERSION}/ebin/dbg.beam"
    release = File.read(File.join(@scratch, 'release/boot/start/start.rel'))
    %w[compiler runtime_tools].each { |application| assert_includes release, "{#{application},\"#{VERSION}\",load}" }
    assert_includes release, "{erx_session,\"#{VERSION}\",load}", 'a domain\'s own application runs in no system domain'
    started = Erx::ReleaseFiles::SYSTEM_APPLICATIONS - Erx::Runtime::APPLICATIONS - Erx::ReleaseFiles::DOMAIN_ONLY
    [*%w[kernel stdlib], *started].each do |application|
      assert_includes release, "{#{application},\"#{VERSION}\"}"
    end
  end

  # The system release neither ships nor names an application that runs only in other
  # domains. asn1 and crypto, whose NIFs the system image lacks, and public_key, ssh, ssl
  # and inets, which call them, ship only in the domain releases that ask for them. The block
  # driver, littlefs and F2FS run in the storage domain alone, the network stack in the
  # network domain alone, the web line in a session alone, the display's applications in
  # the display domain alone and the client side of the window system in display clients
  # alone, the Bluetooth stack in the Bluetooth domain alone, and ntpd and bleuart each
  # in its own session alone. The network client is not among them: the system release ships and starts it,
  # so a socket call there answers {error, eacces} rather than raising undef.
  # They are named here, not taken from the allow-list, so that adding one to
  # SYSTEM_APPLICATIONS, or taking erx_net_client out of it, fails this test.
  def test_the_system_release_ships_no_domain_only_application
    paths = entries.map { |entry| entry.fetch('path') }
    release = File.read(File.join(@scratch, 'release/boot/start/start.rel'))
    only = %w[asn1 crypto public_key ssh ssl inets erx_blk erx_fat erx_storage erx_f2fs erx_media erx_memdraw erx_display erx_fb erx_usb erx_win erx_ui
              erx_desk erx_web erx_net erx_wifi erx_bt_client erx_web_line erx_tty_line erx_app erx_bt erx_bleuart erx_ntpd erx_pcie]
    assert_equal Erx::ReleaseFiles::APPLICATIONS - Erx::ReleaseFiles::SYSTEM_APPLICATIONS, only
    only.each do |application|
      refute_includes release, "{#{application},"
      refute(paths.any? { |path| path.start_with?("system/lib/#{application}-") }, "the system release ships #{application}")
    end
  end

  # Every domain boot script starts the network client (docs/design-network-stack.md,
  # "Modules"), so a socket call in a domain without a grant answers {error, eacces}
  # rather than raising undef on erx_gen_tcp or erx_gen_udp.
  def test_every_domain_script_holds_the_network_client
    Erx::ReleaseFiles::RELEASE_SCRIPTS.each do |name, applications|
      assert_includes applications, 'erx_net_client', "the #{name} script"
    end
  end

  # init ignores what a boot script's start of an application answers, so an application
  # started before one it requires, or with one it requires only loaded, would silently
  # not run: every application a domain script starts finds each application its
  # resource file requires started before it, in the order its boot script starts them,
  # which is the release's order (ReleaseFiles.domain_boot) and not the script's list.
  def test_every_started_application_finds_what_it_requires_started
    Erx::ReleaseFiles::RELEASE_SCRIPTS.each do |name, applications|
      started = Erx::ReleaseFiles.domain_boot(name, applications: applications).applications
                                 .select { |application| Erx::ReleaseFiles.started?(application, script: name) }
      started.each_with_index do |application, index|
        missing = required_applications(application, held: applications) - started.take(index)
        assert_empty missing, "the #{name} script starts #{application} without what it requires"
      end
    end
  end

  # The bt script starts erx_bt, so that its mint of ble is named before init's ready
  # report (docs/design-bluetooth.md, "The Bluetooth domain"), and crypto and
  # erx_bt_client, whose erx_bt_pair composes the control tree's lines, which erx_bt
  # requires; every other script that holds crypto only loads it.
  def test_the_bt_script_starts_erx_bt_and_what_it_requires
    bt = Erx::ReleaseFiles::RELEASE_SCRIPTS.fetch('bt')
    assert(%w[crypto erx_bt_client erx_bt].all? do |application|
      bt.include?(application) && Erx::ReleaseFiles.started?(application, script: 'bt')
    end)
    others = Erx::ReleaseFiles::RELEASE_SCRIPTS.select { |name, applications| name != 'bt' && applications.include?('crypto') }
    refute_empty others
    others.each_key { |name| refute Erx::ReleaseFiles.started?('crypto', script: name), "the #{name} script starts crypto" }
  end

  # The applications application's resource file lists, but for an optional one that held,
  # the script's applications, lacks: OTP starts an optional application first only when
  # the release has it. The lists are atoms, which the scan reads whole.
  def required_applications(application, held:)
    text = File.read(Erx::ReleaseFiles.app_resource(root: ROOT, application: application))
    listed = ->(key) { text[/\{#{key},\s*\[([^\]]*)\]/m, 1].to_s.scan(/[a-z][a-z0-9_]*/) }
    listed.call('applications') - (listed.call('optional_applications') - held)
  end

  def test_the_release_ships_no_appup
    assert_empty(entries.map { |entry| entry.fetch('path') }.grep(/\.appup\z/))
  end

  # The hosted tree carries runtime_tools, which design-runtime.md keeps, so dbg is
  # defined there as on stock.
  def test_the_hosted_tree_ships_runtime_tools
    files = Erx::OracleHosted.application_files(root: ROOT, otp: @otp)
    assert_equal File.join(@otp, 'lib/runtime_tools/ebin/dbg.beam'), files['lib/runtime_tools/ebin/dbg.beam']
    assert_includes files.keys, 'lib/runtime_tools/ebin/runtime_tools.app'
  end

  # The hosted runtime links neither crypto's NIF nor asn1rt_nif, so its tree carries
  # neither application, nor public_key and ssh, which call them, and OTP's suites see
  # no crypto there, as on a stock OTP built without it, rather than a crypto whose
  # every call fails.
  def test_the_hosted_tree_ships_no_application_of_the_domain_images_alone
    files = Erx::OracleHosted.application_files(root: ROOT, otp: @otp)
    %w[asn1 crypto public_key ssh].each do |application|
      refute(files.keys.any? { |path| path.start_with?("lib/#{application}/") }, "the hosted tree ships #{application}")
    end
  end

  # The oracle tests what the image ships: each application the two share is laid out
  # the same, under its own directory.
  def test_the_hosted_tree_lays_out_each_application_as_the_release_does
    release = entries.map { |entry| entry.fetch('path') }.filter_map { |path| path[%r{\Asystem/lib/stdlib-#{VERSION}/(.*)}, 1] }
    tree = Erx::OracleHosted.application_files(root: ROOT, otp: @otp).keys.filter_map { |path| path[%r{\Alib/stdlib/(.*)}, 1] }
    assert_equal release.sort, tree.sort
  end

  # A link in include/ would ship another file's bytes under the header's name.
  def test_a_linked_header_is_refused
    include = File.join(@scratch, 'root/otp/lib/stdlib/include')
    FileUtils.mkdir_p(include)
    File.write(File.join(@scratch, 'other'), 'other')
    File.symlink(File.join(@scratch, 'other'), File.join(include, 'linked.hrl'))
    error = assert_raises(Erx::Error) { Erx::ReleaseFiles.headers(root: File.join(@scratch, 'root'), application: 'stdlib') }
    assert_includes error.message, 'linked.hrl is not a plain file'
  end

  def domain_entries(release)
    Erx::ReleaseFiles.new(root: ROOT, otp: @otp, directory: File.join(@scratch, 'domain'), runner: BootRunner.new,
                          codec: Codec.new, oracle: FakeOracle.new, release: release).entries
  end

  def base_boot(name = 'base') = Erx::ReleaseFiles.domain_boot(name, applications: %w[erx_net_client erx_files stdlib erx kernel])

  # The release file a boot script of the domain release was made from.
  def boot_release_file(name) = File.read(File.join(@scratch, "domain/boot/#{name}/start.rel"))

  # The domain release is laid out as the system release is, under domains/erxos/, and
  # no file of it carries the system mark, which only the system release's files carry.
  def test_the_domain_release_lies_under_its_prefix_without_the_system_mark
    files = domain_entries(Erx::ReleaseFiles.domain([base_boot]))
    paths = files.map { |entry| entry.fetch('path') }
    assert_includes paths, "domains/erxos/lib/kernel-#{VERSION}/ebin/kernel.app"
    assert_includes paths, "domains/erxos/lib/stdlib-#{VERSION}/include/qlc.hrl"
    assert_includes paths, 'domains/erxos/bin/base.boot'
    assert(paths.all? { |path| path.start_with?('domains/erxos/') }, paths.join(', '))
    assert_equal [0], files.map { |entry| entry.fetch('flags') }.uniq
    assert_equal ['system'], entries.map { |entry| entry.fetch('flags') }.uniq
  end

  # Each release holds an empty directory at each facet's mount point, marked as its
  # files are, and no file of the release lies under one.
  def test_each_release_holds_the_mount_points_as_empty_directories
    domain = Erx::ReleaseFiles.new(root: ROOT, otp: @otp, directory: File.join(@scratch, 'domain'), runner: BootRunner.new,
                                   codec: Codec.new, oracle: FakeOracle.new, release: Erx::ReleaseFiles.domain([base_boot]))
    system = Erx::ReleaseFiles.new(root: ROOT, otp: @otp, directory: File.join(@scratch, 'release'), runner: BootRunner.new,
                                   codec: Codec.new, oracle: FakeOracle.new)
    assert_equal(%w[data media svc].map { |name| { 'path' => "system/#{name}", 'kind' => 'directory', 'flags' => 'system' } },
                 system.directories)
    assert_equal(%w[data media svc].map { |name| { 'path' => "domains/erxos/#{name}", 'kind' => 'directory', 'flags' => 0 } },
                 domain.directories)
    [system, domain].each do |release|
      points = release.directories.map { |entry| "#{entry.fetch('path')}/" }
      assert(release.entries.none? { |entry| points.any? { |point| entry.fetch('path').start_with?(point) } })
    end
  end

  # The mount points a release holds are where erx_ns mounts a tree: every point of
  # erx_ns:place/1 is a release's mount point but those of the system domain's files
  # services, /apps and /line, and the storage domain's bt_state, /data/bt beneath
  # /data, which a domain that holds no such facet lacks (erx_ns.erl, place/1), and
  # nothing else is, but /svc, where every domain's /svc entry lies
  # (erx_ns:mount_facets/1). So a new place fails this test
  # until it is either a release directory or one of those. NsPlaces raises on a place/1 clause
  # it cannot read, so a place written in another shape is never skipped.
  def test_the_mount_points_are_where_erx_ns_mounts_facets
    places = Erx::NsPlaces.points(File.read(File.join(ROOT, Erx::NsPlaces::SOURCE)))
    released = Erx::ReleaseFiles::MOUNT_POINTS.map { |name| "/#{name}" }
    assert_equal [*released, '/apps', '/line', '/data/bt'].sort, [*places.values, '/svc'].sort
  end

  # A place/1 clause in a shape NsPlaces does not read, here one split over two lines,
  # fails rather than drops out of the comparison above.
  def test_an_unreadable_place_clause_fails
    text = "place(data) -> {<<\"/data\">>, [rw]};\nplace(new) ->\n    {<<\"/new\">>, [rw]};\nplace(_) -> none.\n"
    assert_raises(Erx::NsPlaces::Error) { Erx::NsPlaces.points(text) }
    assert_equal({ 'data' => '/data' }, Erx::NsPlaces.points(text.sub(/^place\(new\).*\n.*\n/, '')))
  end

  # One release holds every script's applications, each file once, and a script per
  # name; each script's release file is named after the script and lists only its own
  # applications, so a domain boots only what its script names and init:script_id() says which.
  def test_each_boot_script_lists_only_its_own_applications
    session = Erx::ProductionImage.domain_boot('session')
    paths = domain_entries(Erx::ReleaseFiles.domain([session, base_boot('erts')])).map { |entry| entry.fetch('path') }
    assert_equal paths.uniq, paths
    assert_equal 1, paths.count("domains/erxos/lib/kernel-#{VERSION}/ebin/kernel.app")
    assert_includes paths, "domains/erxos/lib/erx_shell-#{VERSION}/ebin/erx_shell.app"
    assert_equal %w[domains/erxos/bin/erts.boot domains/erxos/bin/session.boot], paths.grep(%r{/bin/})
    erts = boot_release_file('erts')
    assert_equal "{release,{\"erts\",\"1\"},{erts,\"#{VERSION}\"},[{kernel,\"#{VERSION}\"},{stdlib,\"#{VERSION}\"}," \
                 "{erx,\"#{VERSION}\"},{erx_files,\"#{VERSION}\"},{erx_net_client,\"#{VERSION}\"}]}.\n", erts
    assert_includes boot_release_file('session'), "{erx_shell,\"#{VERSION}\"}"
  end

  # The session script (ReleaseFiles::RELEASE_SCRIPTS) boots the command
  # shell, the web line and erx_session beside what every domain boots through, and
  # starts the shell and the line, which init's ready report names, but only loads
  # erx_session, which the session template's -eval starts once init holds the domain's
  # facets. It starts the client side of the display, erx_win with the pixel primitives,
  # since a session template's grant on a display (root's display_root) needs the
  # allocator a program's window is allocated from (docs/design-display.md, "The pixel
  # area").
  def test_the_session_script_boots_the_shell_erx_session_and_the_client_side
    domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot('session')]))
    release = boot_release_file('session')
    assert_match(/\{erx_memdraw,"#{VERSION}"\},\{erx_win,"#{VERSION}"\},/, release, 'the session script starts the client side')
    assert_match(/\{erx_shell,"#{VERSION}"\},\{erx_web_line,"#{VERSION}"\},\{erx_tty_line,"#{VERSION}"\},\{erx_session,"#{VERSION}",load\}\]\}\.\n\z/,
                 release, 'the session script starts the line and only loads erx_session')
  end

  # btpair, a command of every session's shell, reads the Bluetooth pairing window
  # through erx_bt_pair (docs/design-bluetooth.md, "The pairing window"), so the session
  # script carries the Bluetooth client, a library that starts no process, and not
  # erx_bt, whose start brings up a controller.
  def test_the_session_script_carries_the_bluetooth_client_and_not_the_stack
    domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot('session')]))
    release = boot_release_file('session')
    assert_includes release, "{erx_bt_client,\"#{VERSION}\"}", 'the session script carries erx_bt_pair'
    refute_match(/\{erx_bt,/, release, 'the session script starts no Bluetooth stack')
  end

  # The ntpd script only loads erx_ntpd, which the ntpd template's -eval starts once
  # init holds the session's facets (docs/design-time.md, "Who does what"), so ntpd's
  # first lookup and sample do not run before the session holds its net and clock facets.
  def test_the_ntpd_script_only_loads_erx_ntpd
    domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot('ntpd')]))
    assert_match(/\{erx_net_client,"#{VERSION}"\},\{erx_ntpd,"#{VERSION}",load\}\]\}\.\n\z/,
                 boot_release_file('ntpd'), 'the ntpd script starts the network client and only loads erx_ntpd')
  end

  # The app script, which the app template boots (docs/design-packaging.md, "The apps
  # row"), boots what every session boots, as the session script does, starts the client
  # side of the display, only loads compiler, which an app's own
  # application may name, as Elixir's elixir does, and asn1, crypto and public_key,
  # holds no ssh, and only loads erx_session and erx_app, which the template's -eval
  # starts, and which asks for the app's record (erx:app/0), so an app's session has its
  # command server and pipe server (docs/design-programs.md, "The command server").
  def test_the_app_script_boots_the_client_side_and_only_loads_erx_session_and_erx_app
    domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot('app')]))
    release = boot_release_file('app')
    %w[compiler asn1 crypto public_key].each { |name| assert_match(/\{#{name},"[^"]+",load\}/, release, "app only loads #{name}") }
    refute_match(/\{ssh,/, release, 'an app runs no ssh daemon')
    assert_match(/\{erx_ui,"#{VERSION}"\},\{erx_bt_client,"#{VERSION}"\},\{erx_shell,"#{VERSION}"\},
                  \{erx_session,"#{VERSION}",load\},\{erx_app,"#{VERSION}",load\}\]\}\.\n\z/x,
                 release, 'the app script starts the client side and the Bluetooth client and only loads erx_session and erx_app')
  end

  # A principal can run OTP's ssh daemon in its own session (docs/design-ssh.md, "Stages",
  # stage 1), so the session script, as the ssh script does, names asn1, crypto,
  # public_key and ssh, in the release order that puts each after what it depends on,
  # and ships them; it only loads them, so no domain runs ssh's supervisors until a
  # program of its own calls ssh:start/0.
  def test_the_session_and_ssh_scripts_load_crypto_public_key_and_ssh
    loaded = %w[asn1 crypto public_key ssh].map { |application| "{#{application},\"#{VERSION}\",load}" }.join(',')
    %w[session ssh].each do |name|
      paths = domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot(name)])).map { |entry| entry.fetch('path') }
      assert_includes boot_release_file(name), "{stdlib,\"#{VERSION}\"},#{loaded}"
      %w[public_key ssh].each { |application| assert_includes paths, "domains/erxos/lib/#{application}-#{VERSION}/ebin/#{application}.app" }
    end
  end

  # A release that holds public_key carries the image's trust store as its priv/cacerts.pem,
  # where pubkey_os_cacerts's {unix, erxos} row loads it (docs/design-crypto.md, "The trust
  # store"): the roots of config/trust, each the bytes its origin record pins, joined in name
  # order, with a receipt naming each root. A release without public_key carries no store.
  def test_a_release_with_public_key_carries_the_trust_store
    store = "domains/erxos/lib/public_key-#{VERSION}/priv/cacerts.pem"
    entry = domain_entries(Erx::ReleaseFiles.domain([Erx::ProductionImage.domain_boot('session')]))
            .find { |candidate| candidate.fetch('path') == store }
    refute_nil entry, "the session's release carries no #{store}"
    recorded = Erx::Origin.new(root: File.join(ROOT, Erx::TrustStore::DIRECTORY)).inventory.fetch('files')
    roots = recorded.keys.sort.map { |name| File.join(Erx::TrustStore::DIRECTORY, name) }
    assert_equal recorded.keys.sort.map { |name| recorded.fetch(name).fetch('sha256') },
                 roots.map { |root| Digest::SHA256.file(File.join(ROOT, root)).hexdigest }
    assert_equal roots.map { |root| File.binread(File.join(ROOT, root)) }.join, File.binread(entry.fetch('artifact'))
    assert_equal roots.map { |root| reference(root) }, JSON.parse(File.read(entry.fetch('receipt'))).fetch('sources')

    paths = domain_entries(Erx::ReleaseFiles.domain([base_boot])).map { |candidate| candidate.fetch('path') }
    assert_empty paths.grep(%r{/priv/cacerts\.pem\z})
  end

  # The network script starts the stack permanent, so the stack's end ends the network
