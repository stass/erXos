-doc """
How a frame reached the interface: `unicast` to its link-layer address, `broadcast` to the
broadcast address, or `multicast` with the group bit (FreeBSD's `M_BCAST` and `M_MCAST`).
A looped packet is `unicast`.
""".
-type link_cast() :: unicast | broadcast | multicast.

-doc """
What the interface classifies: a frame from its driver, with its network sum or `none`; on
the loopback interface, an IP
packet with the zone its sender's path gave it; or a datagram erx_ip4_reass or
erx_ip6_reass rebuilt, with its family and the zone and link cast of its fragment at
offset 0 (IPv4's zone is `none`); or, on an Ethernet interface, a unit of the merge as
`erx_bytes:tcp_merge/1` answers it.
""".
-type input() :: {frame, binary(), erx_net_sum:sum() | none}
               | {frame, Zone :: term(), binary()}
               | {reassembled, family(), Zone :: term(), link_cast(), binary()}
               | {merged, 2..256, First :: {sum, erx_net_sum:sum(), binary()},
                  Last :: {sum, erx_net_sum:sum(), binary()}, Payload :: [binary()]}.

-doc """
What `classify/2` reads of the interface: its link (`none` for the loopback interface) and
link-layer address; erx_ip4's and erx_ip6's views, the latter with the interface's zone;
the multicast groups it joined, by address (each of the interface's own zone); whether it
is configured for DHCP; and `demux`, the lookup of the demultiplexing table, which answers
the entries that hold a key, none or one each.
""".
-type view() :: #{link := ethernet | none,
                  lladdr := <<_:48>> | none,
                  ip4 := erx_ip4:view(),
                  ip6 := erx_ip6:view(),
                  groups := [erx_net_addr:addr()],
                  dhcp := boolean(),
                  demux := fun((key()) -> [entry()])}.

-doc """
A demultiplexing key, most specific first: a connection's or a connected datagram
socket's full four-tuple, local end first, then a listener's or a bound datagram socket's
local address and port, then the same with any address. Addresses are zoned. An ICMP echo
socket holds its identifier, the one key of the echo replies it takes.
""".
-type key() :: {tcp | udp, family(), Local :: addr(), port_number(), Remote :: addr(), port_number()}
             | {tcp_listen | udp, family(), Local :: addr() | any, port_number()}
             | {icmp_echo, inet, Ident :: 0..16#ffff}.

-doc """
A holder of a key: its pid and the credit a frame for it takes one unit of; a listener's
entry also holds its grant and the options of the connections it accepts.
""".
-type entry() :: #{pid := pid(), credit := term(), listener => erx_tcp_syncache:listener(),
                   atom() => term()}.

-doc "The decision on one frame.".
-type verdict() :: {owned, [{pid(), Credit :: term()}, ...], pending()}
                 | {local, pending()}
                 | {drop, reason()}.

-doc """
Why a frame was dropped: the link's `other_host` and `ethertype`, Ethernet's and the IP
layers' own reasons, `not_member` for a group the interface has not joined, and the reasons
of the table above IP (`bcast_tcp`, `no_reply`, `no_port`, `no_socket`, `icmp_type`,
`no_next_header`, and a quote's `bad_length` or `bad_addr`), `too_short` for a datagram
without the fields its row reads, `malformed` for a unit of the merge whose claims fail; and
from `verify/1`, the decoders' reasons.
""".
-type reason() :: other_host | ethertype | not_member | bcast_tcp | no_reply | no_port
                | no_socket | icmp_type | no_next_header | too_short | bad_length | bad_addr | malformed
                | erx_net_eth:error_reason() | erx_ip4:reason() | erx_ip6:reason()
                | erx_tcp_wire:reason() | erx_udp_wire:reason() | erx_icmp4_wire:reason()
                | erx_icmp6_wire:reason() | erx_arp_wire:error_reason().

-doc """
What an IP datagram's consumer learns of its IP layer: the family and IP record, the link
cast of its frame, its destination's class, whether it may be answered (erx_ip4's and
erx_ip6's `reply()`), its zoned addresses, and the zone they took.
""".
-type head() :: #{family := family(), ip := #ip4{} | #ip6{}, link := link_cast(),
                  cast := link_cast(), reply := boolean(), src := addr(), dst := addr(),
                  zone := term()}.

-doc """
A classified frame waiting for `verify/1`: its kind (what its consumer is), its head and
the bytes above IP, for a segment to a listener the listener's entry, and for the DHCP
path, ARP, a fragment and a parameter problem what each needs: a fragment its zone and its
frame's link cast, which reassembly keeps for the datagram, and a parameter problem its
packet's zone, so the error goes back to the zoned source; and a unit of the merge its
count, its first and last frames' pending connection segments and its payload pieces. A
datagram's consumer above IP
comes with what the sum of the bytes above IP is derived from, or `none` when its decoder
sums them.
""".
-opaque pending() :: {above, {binary(), erx_net_sum:sum(), Start :: non_neg_integer()} | none, above()}
                   | {dhcp, #ip4{}, binary()}
                   | {arp, binary()}
                   | {fragment, family(), Zone :: term(), link_cast(), #ip4{} | #ip6{}, binary()}
                   | {param_problem, family(), Zone :: term(), Problem :: tuple(), Packet :: binary()}
                   | {merged, 2..256, First :: pending(), Last :: pending(), Payload :: [binary()]}.

%% A classified datagram's consumer above IP: its kind, its head and the bytes above IP, and
%% for a segment to a listener the listener's entry.
-type above() :: {conn | datagram | report | echo | udp | icmp | other, head(), binary()}
               | {tcp, head(), binary(), entry() | none}.

-doc """
What `verify/1` hands on. For the holders of an owned frame: a connection's
`erx_tcp:segment()`; a datagram socket's `{datagram, {Src, SrcPort}, Dst, Payload}`; or an
ICMP or ICMPv6 error with the datagram it quotes, for the socket that sent it; or an echo
reply's sender, TTL, identifier, sequence number and data, for the echo socket. For the
interface: a TCP segment with the listener it is for, or `none` for a closed port; a UDP
datagram to a closed port, whole, for the port unreachable error that quotes it; a datagram
for the DHCP path; an ICMP or ICMPv6 message; an ARP
message; a datagram of another protocol; a fragment for reassembly; or a parameter problem
with the packet it is about, for erx_icmp4 or erx_icmp6 to answer.
""".
-type item() :: erx_tcp:segment()
              | {datagram, {addr(), port_number()}, addr(), binary()}
              | {report, #icmp4{} | #icmp6{}, erx_icmp4:quoted() | erx_icmp6:quoted()}
              | {echo_reply, Src :: <<_:32>>, Ttl :: 0..255, Ident :: 0..16#ffff,
                 Seq :: 0..16#ffff, Data :: binary()}
              | {tcp, head(), #tcp{}, binary(), entry() | none}
              | {udp, head(), #udp{}, Datagram :: binary()}
              | {dhcp, #ip4{}, #udp{}, Payload :: binary()}
              | {icmp, head(), #icmp4{} | #icmp6{}, binary()}
              | {arp, #arp{}}
              | {other, head(), binary()}
              | {fragment, family(), Zone :: term(), link_cast(), #ip4{} | #ip6{}, binary()}
              | {param_problem, family(), Zone :: term(), term(), binary()}.

