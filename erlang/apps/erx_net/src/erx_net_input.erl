%% Verification

-doc """
Runs the decoder of the layer above IP over a classified frame, checksum first, or ARP's
decoder, and returns the item its consumer takes, or the decoder's reason to drop it. A
fragment, a parameter problem and a datagram of another protocol pass as they are.
""".
-spec verify(pending()) -> {ok, item()} | {drop, reason()}.
verify({above, From, Above}) ->
    verify_above(Above, upper_sum(From, element(3, Above)));
verify({dhcp, #ip4{src = Src, dst = Dst} = Ip, Upper}) ->
    Sum = erx_ip4_wire:pseudo_sum(Src, Dst, byte_size(Upper), ?PROTO_UDP),
    then(erx_udp_wire:decode(inet, Sum, Upper), fun(Udp, Payload) -> {dhcp, Ip, Udp, Payload} end);
verify({arp, Bytes}) ->
    then(erx_arp_wire:decode(Bytes), fun(Arp, _) -> {arp, Arp} end);
verify({fragment, _, _, _, _, _} = Fragment) ->
    {ok, Fragment};
verify({param_problem, _, _, _, _} = Problem) ->
    {ok, Problem};
verify({merged, N, {above, FirstFrom, {conn, FirstHead, FirstUpper} = FirstAbove},
        {above, LastFrom, {conn, LastHead, LastUpper} = LastAbove}, Payload}) ->
    maybe
        {ok, First} ?= verify_above(FirstAbove, upper_sum(FirstFrom, FirstUpper)),
        {ok, Last} ?= verify_above(LastAbove, upper_sum(LastFrom, LastUpper)),
        true ?= (flow(FirstHead, FirstUpper) =:= flow(LastHead, LastUpper)
                 andalso unit_claims_hold(FirstHead, FirstUpper, First, Last, Payload))
                orelse {drop, malformed},
        {ok, erx_tcp:merged(First, Last, {N, Payload})}
    end.

-doc """
The units of a holder's credit a pending frame takes: N for a unit of the merge, so that a
merged segment costs its connection what its N frames would have
(docs/design-network-fastpath.md, "Credit counts segments"), and one for anything else.
The connection takes back as many for the segment `verify/1` makes of it.
""".
-spec units(pending()) -> 1..256.
units({merged, N, _, _, _}) -> N;
units(_) -> 1.

%% What makes two segments of a unit one flow: their heads but for the IP headers' own
%% fields, their ECN fields and their ports.
flow(Head, <<Sport:16, Dport:16, _/binary>>) -> {maps:remove(ip, Head), ecn(Head), Sport, Dport}.

%% What Erlang can check of a unit without its middle frames: its first and last frames are
%% merge candidates (ACK, and no other flag but PSH), the last starts where the pieces before
%% it end, and the pieces fit one IP packet behind the first frame's headers. Only a bug of
%% the merge makes a unit that fails.
unit_claims_hold(Head, Upper, {#tcp{seq = Seq, flags = FirstFlags}, FirstPayload, _, _},
         {#tcp{seq = LastSeq, flags = LastFlags}, LastPayload, _, _}, Payload) ->
    Size = erx_tcp_payload:size(Payload),
    TcpHeader = byte_size(Upper) - byte_size(FirstPayload),
    candidate(FirstFlags) andalso candidate(LastFlags)
        andalso LastSeq =:= erx_tcp_seq:wire(Seq + Size - byte_size(LastPayload))
        andalso ip_header(Head) + TcpHeader + Size =< ?IP_MAXPACKET.

candidate(Flags) -> Flags band ?TH_ACK =/= 0 andalso Flags band bnot (?TH_ACK bor ?TH_PUSH) =:= 0.

%% The bytes of the IP header an IP packet's length counts: IPv4's whole header, and none of
%% IPv6's, whose payload length leaves its fixed header out.
ip_header(#{ip := #ip4{options = Options}}) -> ?IP4_HDR_LEN + byte_size(Options);
ip_header(#{ip := #ip6{}}) -> 0.

%% A consumer above IP, with Sum the sum of its bytes above IP, the third element of each, or none.
verify_above({conn, Head, Upper}, Sum) ->
    then(tcp_wire(Head, Upper, Sum),
         fun(Tcp, Payload) -> {Tcp, Payload, ecn(Head), maps:get(link, Head)} end);
verify_above({tcp, Head, Upper, Listener}, Sum) ->
    then(tcp_wire(Head, Upper, Sum), fun(Tcp, Payload) -> {tcp, Head, Tcp, Payload, Listener} end);
verify_above({datagram, #{src := Src, dst := Dst} = Head, Upper}, Sum) ->
    then(udp_wire(Head, Upper, Sum), fun(#udp{sport = Sport}, Payload) -> {datagram, {Src, Sport}, Dst, Payload} end);
verify_above({udp, Head, Upper}, Sum) ->
    then(udp_wire(Head, Upper, Sum), fun(Udp, _Payload) -> {udp, Head, Udp, Upper} end);
verify_above({report, Head, Upper}, Sum) ->
    case icmp_wire(Head, Upper, Sum) of
        {ok, Icmp, Invoking} ->
            case decode_quoted(Head, Invoking) of
                {ok, Quoted} -> {ok, {report, Icmp, Quoted}};
                {error, Reason} -> {drop, Reason}
            end;
        {error, Reason} ->
            {drop, Reason}
    end;
verify_above({echo, #{ip := #ip4{src = Src, ttl = Ttl}}, Upper}, Sum) ->
    then(erx_icmp4_wire:decode(Upper, Sum),
         fun(#icmp4{msg = {echo, Id, Seq}}, Data) -> {echo_reply, Src, Ttl, Id, Seq, Data} end);
verify_above({icmp, Head, Upper}, Sum) ->
    then(icmp_wire(Head, Upper, Sum), fun(Icmp, Rest) -> {icmp, Head, Icmp, Rest} end);
verify_above({other, _, _} = Other, _) ->
    {ok, Other}.

then({ok, Record, Rest}, Item) -> {ok, Item(Record, Rest)};
then({error, Reason}, _) -> {drop, Reason}.

tcp_wire(Head, Upper, Sum) -> erx_tcp_wire:decode(pseudo_sum(Head, Upper, ?PROTO_TCP), Upper, Sum).

udp_wire(#{family := Family} = Head, Upper, Sum) ->
    erx_udp_wire:decode(Family, pseudo_sum(Head, Upper, ?PROTO_UDP), Upper, Sum).

icmp_wire(#{family := inet}, Upper, Sum) -> erx_icmp4_wire:decode(Upper, Sum);
icmp_wire(#{family := inet6} = Head, Upper, Sum) ->
    erx_icmp6_wire:decode(pseudo_sum(Head, Upper, ?PROTO_ICMPV6), Upper, Sum).

decode_quoted(#{family := inet}, Invoking) -> erx_icmp4:decode_quoted(Invoking);
decode_quoted(#{family := inet6}, Invoking) -> erx_icmp6:decode_quoted(Invoking).

pseudo_sum(#{ip := #ip4{src = Src, dst = Dst}}, Upper, Proto) ->
    erx_ip4_wire:pseudo_sum(Src, Dst, byte_size(Upper), Proto);
pseudo_sum(#{ip := #ip6{src = Src, dst = Dst}}, Upper, Proto) ->
    erx_ip6_wire:pseudo_sum(Src, Dst, byte_size(Upper), Proto).

%% The ECN field of the IP header, the low two bits of the type of service or the traffic
%% class (RFC 3168).
ecn(#{ip := #ip4{tos = Tos}}) -> Tos band 3;
ecn(#{ip := #ip6{tclass = Class}}) -> Class band 3.

-doc """
The sender of a pending ARP reply, for the interface to tell whether it answers a
resolution it awaits (docs/design-network-stack.md, "The ingress limiter"); `none` for
anything else. Like `classify/2` it reads the fields before they are verified, for that
decision alone.
""".
-spec arp_reply(pending()) -> {ok, <<_:32>>} | none.
arp_reply({arp, <<_:6/binary, 2:16, _:6/binary, Spa:4/binary, _/binary>>}) -> {ok, Spa};
arp_reply(_) -> none.
