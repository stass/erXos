%% Classification

-doc "Where Input goes, given the receiving interface's View.".
-spec classify(input(), view()) -> verdict().
classify({frame, Bytes, Sum}, #{link := ethernet} = View) when is_binary(Bytes) ->
    ether(Bytes, Sum, View);
classify({frame, Zone, Bytes}, #{link := none} = View) ->
    loopback(Zone, Bytes, View);
classify({reassembled, inet, none, LinkCast, Bytes}, View) ->
    ip4(Bytes, none, LinkCast, View);
classify({reassembled, inet6, Zone, LinkCast, Bytes}, View) ->
    ip6(Bytes, none, reassembled, LinkCast, Zone, View);
classify({merged, N, {sum, FirstSum, First}, {sum, LastSum, Last}, Payload}, #{link := ethernet} = View)
  when is_binary(First), is_binary(Last) ->
    {MaxFrames, _} = erx_bytes:tcp_merge_limit(),
    case is_integer(N) andalso N >= 2 andalso length(Payload) =< N andalso N =< MaxFrames of
        true -> unit(N, ether(First, FirstSum, View), fun() -> ether(Last, LastSum, View) end, Payload);
        false -> {drop, malformed}
    end.

%% A unit of the merge (docs/design-network-fastpath.md, "The merge, before
%% classification") is classified by its first frame, its count checked against the pieces
%% Erlang sees before anyone is charged for it. A unit for a connection is owned when its
%% last frame classifies as a segment of a connection with the same holders; verify/1 then
%% checks that the two name one flow. A unit no connection holds, for a closed port or a
%% listener, or one dropped, is taken as its last frame, whose acknowledgement FreeBSD's
%% merged segment carries (tcp_lro.c:731-740), so a closed port answers it with the one RST
%% tcp_dropwithreset makes for the LRO packet. The last frame comes as a fun, ClassifyLast,
%% so that it is classified once on either path.
unit(N, {owned, Holders, {above, _, {conn, _, _}} = First}, ClassifyLast, Payload) ->
    case ClassifyLast() of
        {owned, Holders, {above, _, {conn, _, _}} = LastPending} ->
            {owned, Holders, {merged, N, First, LastPending, Payload}};
        _ ->
            {drop, malformed}
    end;
unit(_N, _NotConnection, ClassifyLast, _Payload) ->
    ClassifyLast().

%% ether_input drops a frame to another host's unicast address (no promiscuous mode), and
%% ether_demux one of a type no protocol takes. The frame's network sum is the sum of its bytes
%% after the link header, so it is the IP packet's.
ether(Bytes, Sum, #{lladdr := Mine, ip6 := #{zone := Zone}} = View) ->
    case erx_net_eth:decode(Bytes) of
        {ok, #eth{dst = Dst, type = Type}, Payload} ->
            case link_cast(Dst, Mine) of
                other_host -> {drop, other_host};
                LinkCast -> ethertype(Type, Payload, Sum, LinkCast, Zone, View)
            end;
        {error, Reason} ->
            {drop, Reason}
    end.

link_cast(Mine, Mine) -> unicast;
link_cast(?ETHER_BROADCAST, _) -> broadcast;
link_cast(<<_:7, 1:1, _:40>>, _) -> multicast;
link_cast(_, _) -> other_host.

ethertype(?ETHERTYPE_IP, Packet, Sum, LinkCast, _, #{dhcp := true} = View) ->
    case dhcp(Packet) of
        {ok, Ip, Upper} -> {local, {dhcp, Ip, Upper}};
        no -> ip4(Packet, Sum, LinkCast, View)
    end;
ethertype(?ETHERTYPE_IP, Packet, Sum, LinkCast, _, View) ->
    ip4(Packet, Sum, LinkCast, View);
ethertype(?ETHERTYPE_IPV6, Packet, Sum, LinkCast, Zone, View) ->
    ip6(Packet, Sum, received, LinkCast, Zone, View);
ethertype(?ETHERTYPE_ARP, Packet, _, _, _, _) ->
    {local, {arp, Packet}};
ethertype(_, _, _, _, _, _) ->
    {drop, ethertype}.

%% The loopback interface's frame is the IP packet itself, its family read from the version.
loopback(Zone, <<6:4, _/bits>> = Packet, View) -> ip6(Packet, none, received, unicast, Zone, View);
loopback(_, Packet, View) -> ip4(Packet, none, unicast, View).

%% dhcp_bpf_filter: an IPv4 packet that is not a fragment, carrying UDP to the client's
%% port, whatever its destination address, since the offer may be unicast to the address
%% being offered, which is not yet the stack's. The header must be one erx_ip4_wire
%% accepts, so its addresses and length are sound. The decision is made here, before the
%% IP layer's, and never after it refused the packet.
dhcp(Packet) ->
    case erx_ip4_wire:decode(Packet) of
        {ok, #ip4{p = ?PROTO_UDP, mf = 0, off = 0} = Ip,
         <<_:16, ?DHCP_CLIENT_PORT:16, _/binary>> = Upper} when byte_size(Upper) >= ?UDP_HDR_LEN ->
            {ok, Ip, Upper};
        _ ->
            no
    end.

ip4(Packet, Sum, LinkCast, #{ip4 := Ip4View} = View) ->
    case erx_ip4:input(Packet, LinkCast, Ip4View) of
        {ours, Cast, Reply, #ip4{p = Proto, src = Src, dst = Dst, options = Options} = Ip, Upper} ->
            Head = head(inet, Ip, LinkCast, Cast, Reply, Src, Dst, none),
            From = after_checked_header(Packet, Sum, ?IP_HDR_LEN + byte_size(Options)),
            above_sum(member(Head, Proto, Upper, View), From);
        {fragment, Ip, Payload} -> {local, {fragment, inet, none, LinkCast, Ip, Payload}};
        {param_problem, _} = Problem -> {local, {param_problem, inet, none, Problem, Packet}};
        {drop, _} = Drop -> Drop
    end.

ip6(Packet, Sum, Origin, LinkCast, Zone, #{ip6 := Ip6View} = View) ->
    case erx_ip6:input(Packet, Origin, LinkCast, Ip6View#{zone := Zone}) of
        {ours, Cast, Reply, #ip6{proto = Proto, src = Src, dst = Dst, hdrlen = HdrLen} = Ip, Upper} ->
            Head = head(inet6, Ip, LinkCast, Cast, Reply, Src, Dst, Zone),
            above_sum(member(Head, Proto, Upper, View), sum_from(Packet, Sum, ?IP6_HDR_LEN + HdrLen));
        {fragment, Ip, Payload} -> {local, {fragment, inet6, Zone, LinkCast, Ip, Payload}};
        {param_problem, _, _} = Problem -> {local, {param_problem, inet6, Zone, Problem, Packet}};
        {drop, _} = Drop -> Drop
    end.

%% A datagram for a consumer above IP carries what the sum of its bytes above IP comes from,
%% or `none` without a network sum. `verify/1` derives the sum, so a frame dropped for want
%% of room costs no addition.
above_sum({owned, Holders, Above}, From) -> {owned, Holders, {above, From, Above}};
above_sum({local, Above}, From) -> {local, {above, From, Above}};
above_sum({drop, _} = Drop, _) -> Drop.

%% What the sum of the bytes above IP comes from: the packet, its network sum and Start, where
%% the bytes above IP begin in it.
sum_from(_, none, _) -> none;
sum_from(Packet, Sum, Start) -> {Packet, Sum, Start}.

%% An IPv4 header whose checksum has been checked sums to 16#ffff, one's-complement zero, so
%% the packet's sum is also that of the bytes after the header, which are handed over with
%% Start 0: the header is not read again. An IPv6 header has no checksum, so `sum_from/3`
%% keeps it, and `upper_sum/2` subtracts its sum.
after_checked_header(_, none, _) -> none;
after_checked_header(Packet, Sum, HdrLen) ->
    {binary_part(Packet, HdrLen, byte_size(Packet) - HdrLen), Sum, 0}.

%% The sum of Upper, the bytes above IP: the packet's sum less its header's and its padding's.
upper_sum(none, _) -> none;
upper_sum({Packet, Sum, Start}, Upper) -> erx_net_sum:span(Packet, Sum, Start, byte_size(Upper)).

head(Family, Ip, LinkCast, Cast, Reply, Src, Dst, Zone) ->
    #{family => Family, ip => Ip, link => LinkCast, cast => Cast, reply => Reply,
      src => erx_net_addr:zoned(Src, Zone), dst => erx_net_addr:zoned(Dst, Zone), zone => Zone}.

%% A multicast datagram goes on only to a group the interface joined; the IP layers accept
%% every group and leave the filter to the protocols, as ip_input and ip6_input do.
member(#{cast := multicast, ip := Ip} = Head, Proto, Upper, #{groups := Groups} = View) ->
    case lists:member(ip_dst(Ip), Groups) of
        true -> above(Head, Proto, Upper, View);
        false -> {drop, not_member}
    end;
member(Head, Proto, Upper, View) ->
    above(Head, Proto, Upper, View).

ip_dst(#ip4{dst = Dst}) -> Dst;
ip_dst(#ip6{dst = Dst}) -> Dst.

%% The table above IP.
above(Head, ?PROTO_TCP, Upper, View) -> tcp(Head, Upper, View);
above(Head, ?PROTO_UDP, Upper, View) -> udp(Head, Upper, View);
above(#{family := inet} = Head, ?PROTO_ICMP, Upper, View) -> icmp4(Head, Upper, View);
above(#{family := inet6} = Head, ?PROTO_ICMPV6, Upper, View) -> icmp6(Head, Upper, View);
%% rip6_input frees a packet with no next header unanswered.
above(#{family := inet6}, ?PROTO_NONE, _, _) -> {drop, no_next_header};
%% Any other protocol draws rip_input's protocol unreachable or rip6_input's parameter
%% problem at the next-header byte, when it may be answered.
above(Head, _, Upper, _) -> answerable(Head, {other, Head, Upper}).

answerable(#{reply := true}, Pending) -> {local, Pending};
answerable(_, _) -> {drop, no_reply}.

%% A connection's key owns the segment. Else a listener's key: the interface's, for the
%% syncache, unless the frame came as a link-layer broadcast or multicast, which
%% tcp_input drops for a listener (tcp_input.c:1288), or was sent to a broadcast or
%% multicast address, which it drops before syncache_add (:1326-1338); for a segment
%% without SYN to such an address no handshake can match and tcp_dropwithreset answers
%% none (:3450-3471), so the row drops them all alike. Departure: an ACK or RST of a
%% handshake in a link-layer broadcast or multicast frame is dropped here, where FreeBSD's
%% syncache_expand and syncache_chkrst see it before the drop (:1081, :1175). Else a
%% closed port, which may draw a RST.
tcp(#{family := Family, src := Src, dst := Dst, link := LinkCast, cast := Cast} = Head,
    <<Sport:16, Dport:16, _/binary>> = Upper, #{demux := Demux}) ->
    case Demux({tcp, Family, Dst, Dport, Src, Sport}) of
        [_ | _] = Entries ->
            {owned, holders(Entries), {conn, Head, Upper}};
        [] ->
            case listener(Family, Dst, Dport, Demux) of
                {ok, Entry} when LinkCast =:= unicast, Cast =:= unicast -> {local, {tcp, Head, Upper, Entry}};
                {ok, _} -> {drop, bcast_tcp};
                none -> answerable(Head, {tcp, Head, Upper, none})
            end
    end;
tcp(_, _, _) ->
    {drop, too_short}.

listener(Family, Local, Port, Demux) ->
    case Demux({tcp_listen, Family, Local, Port}) of
        [Entry | _] -> {ok, Entry};
        [] ->
            case Demux({tcp_listen, Family, any, Port}) of
                [Entry | _] -> {ok, Entry};
                [] -> none
            end
    end.

%% The holders of the datagram's keys, most specific first, reduced by erx_udp:input/3.
udp(#{family := Family, src := Src, dst := Dst, cast := Cast, reply := Reply} = Head,
    <<Sport:16, Dport:16, _/binary>> = Upper, #{demux := Demux}) ->
    Keys = [{udp, Family, Dst, Dport, Src, Sport}, {udp, Family, Dst, Dport}, {udp, Family, any, Dport}],
    case erx_udp:input(Cast, Reply, lists:append([Demux(Key) || Key <- Keys])) of
        {deliver, Sockets} -> {owned, holders(Sockets), {datagram, Head, Upper}};
        port_unreach -> {local, {udp, Head, Upper}};
        {drop, no_port} -> {drop, no_port}
    end;
udp(_, _, _) ->
    {drop, too_short}.

%% icmp_input: an error goes to the socket its quote names; an echo or timestamp request
%% is answered when it may be; an echo reply goes to the echo socket holding its identifier,
%% as rip_input hands it to the raw socket ping(8) filters by its identifier; a redirect is
%% the interface's; every other type ends here.
icmp4(Head, <<Type, _/binary>> = Upper, View)
  when Type =:= ?ICMP_UNREACH; Type =:= ?ICMP_TIMXCEED; Type =:= ?ICMP_PARAMPROB ->
    quoted(Head, erx_icmp4:decode_quoted(invoking(Upper)), Upper, View);
icmp4(Head, <<Type, _/binary>> = Upper, _) when Type =:= ?ICMP_ECHO; Type =:= ?ICMP_TSTAMP ->
    answerable(Head, {icmp, Head, Upper});
icmp4(Head, <<?ICMP_ECHOREPLY, _Code, _Sum:16, Id:16, _Seq:16, _/binary>> = Upper, #{demux := Demux}) ->
    case Demux({icmp_echo, inet, Id}) of
        [_ | _] = Entries -> {owned, holders(Entries), {echo, Head, Upper}};
        [] -> {drop, no_socket}
    end;
icmp4(_, <<?ICMP_ECHOREPLY, _/binary>>, _) ->
    {drop, too_short};
icmp4(Head, <<?ICMP_REDIRECT, _/binary>> = Upper, _) ->
    {local, {icmp, Head, Upper}};
icmp4(_, <<_, _/binary>>, _) ->
    {drop, icmp_type};
icmp4(_, <<>>, _) ->
    {drop, too_short}.

%% icmp6_input: the four error types, the echo request, and the router, neighbour and
%% redirect messages and the MLD query, which the interface's core handles.
icmp6(Head, <<Type, _/binary>> = Upper, View)
  when Type >= ?ICMP6_DST_UNREACH, Type =< ?ICMP6_PARAM_PROB ->
    quoted(Head, erx_icmp6:decode_quoted(invoking(Upper)), Upper, View);
icmp6(Head, <<?ICMP6_ECHO_REQUEST, _/binary>> = Upper, _) ->
    answerable(Head, {icmp, Head, Upper});
icmp6(Head, <<Type, _/binary>> = Upper, _)
  when Type =:= ?MLD_LISTENER_QUERY; Type >= ?ND_ROUTER_SOLICIT, Type =< ?ND_REDIRECT ->
    {local, {icmp, Head, Upper}};
icmp6(_, <<_, _/binary>>, _) ->
    {drop, icmp_type};
icmp6(_, <<>>, _) ->
    {drop, too_short}.

%% The datagram an error quotes, after its fixed fields; a message too short for them
%% quotes nothing, which decode_quoted/1 refuses.
invoking(<<_:?ICMP_HDR_LEN/binary, Invoking/binary>>) -> Invoking;
invoking(_) -> <<>>.

%% The quoted datagram is one the stack sent: its source is the local end, and its
%% addresses take the zone of the packet that carries the error. tcp_ctlinput and
%% udp_common_ctlinput look up the full four-tuple alone; a TCP quote without a
%% connection goes to the syncache (syncache_unreach), but only when a listener's key
%% exists, since only a listener's handshakes are there.
quoted(#{family := Family, zone := Zone} = Head,
       {ok, #{proto := Proto, src := QSrc, dst := QDst, upper := <<QSport:16, QDport:16, _/binary>>}},
       Upper, #{demux := Demux}) ->
    Local = erx_net_addr:zoned(QSrc, Zone),
    Remote = erx_net_addr:zoned(QDst, Zone),
    case Proto of
        ?PROTO_TCP ->
            case Demux({tcp, Family, Local, QSport, Remote, QDport}) of
                [_ | _] = Entries -> {owned, holders(Entries), {report, Head, Upper}};
                [] ->
                    case listener(Family, Local, QSport, Demux) of
                        {ok, _} -> {local, {icmp, Head, Upper}};
                        none -> {drop, no_socket}
                    end
            end;
        ?PROTO_UDP ->
            case Demux({udp, Family, Local, QSport, Remote, QDport}) of
                [_ | _] = Entries -> {owned, holders(Entries), {report, Head, Upper}};
                [] -> {drop, no_socket}
            end;
        _ ->
            {drop, no_socket}
    end;
%% decode_quoted/1 guarantees 8 bytes of the upper layer; this keeps the function total.
quoted(_, {ok, _}, _, _) ->
    {drop, bad_length};
quoted(_, {error, Reason}, _, _) ->
    {drop, Reason}.

holders(Entries) -> [holder(Entry) || Entry <- Entries].

holder(#{pid := Pid, credit := Credit}) -> {Pid, Credit}.

