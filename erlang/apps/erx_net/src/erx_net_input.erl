-module(erx_net_input).
-moduledoc """
The receive decision of an interface (docs/design-network-stack.md, "Classifying a
frame"): where a frame goes, as FreeBSD's `ether_input` and `ether_demux`
(sys/net/if_ethersubr.c), `ip_input` and `ip6_input` (through erx_ip4 and erx_ip6), the pcb
lookups of `tcp_input_with_port` and `udp_input`, and the type dispatch of `icmp_input`
and `icmp6_input` choose it, at the commit NOTICE-freebsd records, taken as far as the
choice and no further; and the DHCP client's receive filter (`dhcp_bpf_filter`,
sbin/dhclient/bpf.c), which sees a frame ahead of `ip_input`.

`classify/2` reads only the fields that choose a destination, before any checksum above IP
is checked: the link-layer destination and EtherType, what erx_ip4 and erx_ip6 read, the
protocol, the ports, and an ICMP or ICMPv6 message's type with the protocol, addresses and
ports its quote names. It answers `owned` with the holders a frame belongs to, `local` for
the interface itself, or `drop` with a reason. The caller then reserves a unit of each
holder's credit or a token of its ingress bucket, and only a frame that holds one reaches
`verify/1`, which runs the decoder of the layer above IP (or ARP's), checksum first, and
returns the item its consumer takes. A frame may come with its network sum, the sum the copy
computed over its bytes after the link header; the IP layer's classification derives the sum
of the bytes above IP from it with `erx_net_sum:span/4`, and the decoder checks the checksum
from that sum instead of reading the bytes again (docs/design-network-stack.md, "Checksums in
the copy"). A frame without one, a looped packet and a reassembled datagram are summed by their
decoder. No length or offset is taken from a sum. A frame that fails `verify/1` was looked up by
unverified fields alone, so nothing it carries above the fields named here is acted on.

Inside the stack an IPv6 address of link-local or interface-local scope is zoned
(`erx_net_addr:zoned/2`): a received packet's addresses take its interface's zone (the
view's `ip6` zone), a looped one's the zone its frame carries, and the addresses an ICMPv6
error quotes the zone of the packet that carries them, so the demultiplexing keys hold
zoned addresses and a key bound in one zone never matches a packet of another.

Everything here is a pure function of the input, the view and what the view's `demux`
lookup answers. Frames are untrusted: both functions are total over every binary, create
no atoms, and allocate only sub-binaries of the frame and the terms they return.

Departures: a datagram too short to hold the fields its row of the table names (the
ports, or an ICMP type) is dropped as `too_short` before verification, where FreeBSD's
decoder drops it in the same place under its own counter; IPv4 multicast is checked
against the view's `groups`, which hold no IPv4 group until sockets join one.
""".

